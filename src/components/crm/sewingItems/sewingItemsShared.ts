/**
 * ОТМЕНЁННЫЙ ЗАКАЗ — ЭТО НЕ РАБОТА.
 *
 * Отмену видит МАРКЕТПЛЕЙС: у каждой площадки своё слово для неё
 * (ozon_status='cancelled', ym_status='...CANCELLED'), а наш собственный status
 * при этом остаётся прежним — «Новый». Поэтому признак считает сервер и кладёт
 * в isCancelled, а здесь мы им просто пользуемся.
 *
 * Из-за разного счёта конвейер и вкладка «Заказы» расходились: восемь заказов
 * «Шифон» стояли на конвейере в «Новых» как живая очередь, а во вкладке заказов
 * их не было вовсе — все восемь отменил покупатель. Закройщик видел работу,
 * которой нет, и не мог понять, куда она делась из списка заказов.
 */
export const isOrderCancelled = (o: {
  isCancelled?: boolean | null;
  status?: string;
  sewingStatus?: string;
}): boolean =>
  !!o.isCancelled || o.status === 'Отменён' || o.sewingStatus === 'Отменён';

/**
 * Отменённый заказ, по которому крой УЖЕ СДЕЛАН и вещь ещё не дошла до склада.
 *
 * Ткань разрезана и обратно в рулон не вернётся, поэтому вещь надо дошить и
 * провести через стикеровку: там ей напечатают складской стикер GW, и она
 * законно ляжет на полку. Пока этого не произошло, крой висит в цехе, а в
 * системе заказ считается отменённым — то есть невидимым для очереди.
 *
 * Именно так терялись заказы 0149246251-0168-1 и 40863907-0422-1: крой лежал
 * на вешалке, а найти его в системе было негде.
 *
 * «Готовые» и «Со склада» сюда не попадают: вещь уже прошла конвейер и лежит
 * на складе — доделывать нечего.
 */
export const isCancelledWithCut = (o: {
  isCancelled?: boolean | null;
  status?: string;
  sewingStatus?: string;
  cutAt?: string | null;
  cutGivenToOrderId?: number | null;
}): boolean => {
  if (!isOrderCancelled(o)) return false;
  // КРОЙ УЖЕ ОТДАН ЖИВОМУ ЗАКАЗУ — доделывать по этому заказу нечего.
  //
  // Пришёл новый заказ того же размера, и висящий крой передали ему: вещь
  // сошьют под новым номером и отправят покупателю, а не на склад. Здесь такой
  // заказ показывать нельзя — швея пошла бы искать вешалку, которую уже
  // забрала другая работа, и в списке «доделать» он висел бы вечно.
  if (o.cutGivenToOrderId) return false;
  // Вещь уже на складе — доделывать нечего.
  if (o.sewingStatus === 'Готовые' || o.sewingStatus === 'Со склада') return false;
  // Крой отмечен в системе — вещь точно существует в цехе.
  if (o.cutAt) return true;
  // КРОЙ БЫВАЕТ И БЕЗ ОТМЕТКИ В СИСТЕМЕ.
  //
  // Закройщица режет ткань, а кнопку «Раскроено» нажать не успевает: заказ
  // отменяют раньше, и раскрой на нём блокируется. cutAt остаётся пустым, но
  // вещь физически висит на вешалке с листком — ровно так зависли заказы
  // 0149246251-0168-1 и 40863907-0422-1.
  //
  // Поэтому в список берём и те отменённые заказы, которые дошли хотя бы до
  // этапа раскроя: по ним нужно выяснить, резали ткань или нет. Заказы из
  // общей очереди («Новый») сюда не попадают — там ткань точно цела.
  return o.sewingStatus === 'На раскрое'
    || o.sewingStatus === 'Раскроено'
    || o.sewingStatus === 'В работе'
    || o.sewingStatus === 'Стикеровка';
};

/** Сокращает ФИО до "Фамилия И.О." — например "Коротаева Наталья Александровна" → "Коротаева Н.А.". */
export const shortFio = (fullName: string): string => {
  const parts = fullName.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return '';
  const [last, first, middle] = parts;
  const initials = [first, middle].filter(Boolean).map((p) => `${p[0].toUpperCase()}.`).join('');
  return initials ? `${last} ${initials}` : last;
};

/**
 * Остаток ожидания следующего заказа в человеческом виде: до минуты — секунды,
 * дальше — «мин:сек». Секунды из счётчика показываем всегда, а не округляем до
 * минут: швея должна видеть, что время реально идёт, иначе застывшая «5 мин»
 * читается как зависшая кнопка.
 */
export const formatWait = (totalSec: number): string => {
  const sec = Math.max(0, Math.round(totalSec));
  if (sec < 60) return `${sec} сек.`;
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  return `${m}:${String(s).padStart(2, '0')}`;
};

