/**
 * Кэш ответов на короткое время — чтобы не платить за один и тот же запрос дважды.
 *
 * Зачем: общий макет (CrmLayout) лежит внутри КАЖДОЙ из 68 страниц, а не над
 * ними. Из-за этого при каждом переходе по меню React разбирает его и собирает
 * заново — вместе со всеми проверками, которые он делает при появлении. Человек
 * кликает по разделам десятки раз за смену, и столько же раз уходят запросы,
 * ответ на которые не меняется месяцами: «есть ли неподписанный договор»,
 * «не вышел ли срок на документы».
 *
 * Кэш держит ответ несколько минут: первый переход спрашивает сервер, остальные
 * берут готовое. Данные при этом не устаревают заметно — договор и срок на
 * документы меняются раз в недели, а не в секунды.
 *
 * Отдельно храним сам «обещание», а не только результат: если два виджета
 * спросят одновременно, запрос уйдёт один, а ответ получат оба.
 */

interface Entry<T> {
  /** Незавершённый запрос — чтобы параллельные вызовы не плодили копии. */
  promise: Promise<T>;
  /** До какого момента ответ считается свежим. */
  expiresAt: number;
}

const store = new Map<string, Entry<unknown>>();

/**
 * Выполняет запрос не чаще, чем раз в ttlMs.
 *
 * @param key    под каким именем помнить ответ
 * @param loader сам запрос
 * @param ttlMs  сколько миллисекунд ответ считается свежим
 */
export const cachedRequest = <T>(
  key: string,
  loader: () => Promise<T>,
  ttlMs: number,
): Promise<T> => {
  const now = Date.now();
  const hit = store.get(key) as Entry<T> | undefined;
  if (hit && hit.expiresAt > now) return hit.promise;

  const promise = loader().catch((e) => {
    // Неудачный ответ не кэшируем: иначе разовый сбой сети «залипнет» на
    // несколько минут и человек будет видеть ошибку там, где всё уже работает.
    store.delete(key);
    throw e;
  });

  store.set(key, { promise, expiresAt: now + ttlMs });
  return promise;
};

/** Сбрасывает кэш — после действия, которое точно изменило данные. */
export const invalidateCache = (keyPrefix: string) => {
  for (const key of store.keys()) {
    if (key.startsWith(keyPrefix)) store.delete(key);
  }
};
