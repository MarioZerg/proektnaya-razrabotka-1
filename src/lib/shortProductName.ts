/**
 * Короткое название вещи: «Бамбук 300x255» вместо простыни из карточки маркетплейса.
 *
 * Площадки требуют в заголовке все ключевые слова сразу, поэтому товар называется
 * «Тюль для комнаты 300x255 см Бамбук белая в гостиную на кухню для спальни МЕГАТЮЛЬ».
 * В таблице такое название занимает три строки и вытесняет то, что кладовщику реально
 * нужно, — ткань и размер. Именно по ним вещь ищут на полке и сверяют с заказом.
 *
 * Сначала берём ткань и размеры из полей заказа: это точные данные. Если их нет
 * (у части старых заказов поля пустые), вытаскиваем из заголовка — размер по цифрам,
 * ткань по списку тех, с которыми работает цех.
 */

/** Ткани, из которых шьют. Порядок важен: сначала длинные, иначе «Вуаль» */
/** перехватит «Вуаль (молочная)» и уточнение потеряется. */
const FABRICS = [
  'Вуаль без утяжелителя',
  'Вуаль (без ут)',
  'Вуаль (молочная)',
  'Бамбук',
  'Мрамор',
  'Молния',
  'Шифон',
  'Сетка',
  'Вуаль',
  'Лен',
  'Лён',
];

/** Размер в заголовке: «300x255», «300х255 см», «400 X 270». Русская и латинская «х». */
const SIZE_RE = /(\d{2,4})\s*[xх×X]\s*(\d{2,4})/;

export interface ShortNameSource {
  product?: string | null;
  material?: string | null;
  width?: number | null;
  height?: number | null;
}

/**
 * @returns «Ткань ШхВ», либо что удалось собрать, либо исходное название целиком —
 * пустую строку не возвращаем никогда, иначе в таблице появится безымянная вещь.
 */
export const shortProductName = (item: ShortNameSource): string => {
  const raw = (item.product || '').trim();

  const fabric =
    (item.material || '').trim() ||
    FABRICS.find((f) => raw.toLowerCase().includes(f.toLowerCase())) ||
    '';

  let size = '';
  if (item.width && item.height) {
    size = `${item.width}x${item.height}`;
  } else {
    const m = raw.match(SIZE_RE);
    if (m) size = `${m[1]}x${m[2]}`;
  }

  const short = [fabric, size].filter(Boolean).join(' ').trim();
  return short || raw || '—';
};

export default shortProductName;
