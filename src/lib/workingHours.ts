/**
 * Ночной перерыв: с 24:00 до 5:00 производство не работает.
 *
 * В это время в системе никого нет, но открытые на планшетах вкладки продолжали
 * опрашивать сервер каждую минуту до самого утра. За пять часов это тысячи запросов
 * в пустоту — и они оплачиваются как обычная работа.
 *
 * Ночью опрос не выключается совсем, а замедляется: если кто-то всё же зашёл (админ
 * из дома, сверхурочная смена), данные он получит — просто чуть реже. Полное отключение
 * означало бы «зашёл ночью и смотришь на замерший экран».
 */

/** Час начала ночного перерыва (включительно). */
const NIGHT_FROM = 0;
/** Час окончания перерыва: с 5:00 цех уже может работать. */
const NIGHT_TO = 5;

/** Сейчас ночной перерыв? Считаем по времени устройства — люди и планшеты в одном часовом поясе. */
export const isNightTime = (date = new Date()): boolean => {
  const hour = date.getHours();
  return hour >= NIGHT_FROM && hour < NIGHT_TO;
};

/**
 * Во сколько раз реже опрашивать сервер ночью.
 *
 * Опрос раз в минуту превращается в опрос раз в 10 минут: нагрузка падает в десять
 * раз, а человек, зашедший ночью, всё равно видит живые данные.
 */
export const NIGHT_SLOWDOWN = 10;

/**
 * Интервал опроса с учётом ночного перерыва.
 *
 * @param intervalMs обычный интервал в рабочее время
 */
export const withNightSlowdown = (intervalMs: number): number =>
  isNightTime() ? intervalMs * NIGHT_SLOWDOWN : intervalMs;

export default isNightTime;
