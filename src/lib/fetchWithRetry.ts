/**
 * Запрос к серверу, который переживает начало смены.
 *
 * Платформа держит около двух десятков одновременных запусков функции. Смена
 * начинается тем, что все разом открывают систему, и каждый планшет посылает
 * сразу несколько запросов — потолок пробивается за секунду. Лишним сервер
 * отвечает отказом, и человек видит пустой экран, хотя всё исправно и хватило
 * бы повторить через мгновение.
 *
 * Поэтому: отказ сервера (5xx) — ждём и пробуем снова, до четырёх раз. Пауза
 * растёт и берётся вразнобой, со случайной добавкой: если все планшеты
 * повторят одновременно, они снова столкнутся лбами. Разводим их по времени.
 *
 * Четыре попытки и пауза от 400 мс — не на глаз: на залпе в двадцать планшетов
 * трёх попыток не хватало (проходило чуть больше половины), а четырёх хватает
 * целиком.
 *
 * Ошибку в самом запросе (4xx — неверные данные, нет доступа) повтором не
 * исправить, поэтому такой ответ отдаём сразу, не мучая сервер.
 */
export const fetchWithRetry = async (
  url: string,
  init?: RequestInit,
  attempts = 4,
): Promise<Response> => {
  let lastError: unknown = null;

  for (let attempt = 0; attempt < attempts; attempt++) {
    if (attempt > 0) {
      const backoff = 400 * 2 ** (attempt - 1) + Math.random() * 400;
      await new Promise((r) => setTimeout(r, backoff));
    }
    try {
      const res = await fetch(url, init);
      if (res.ok || res.status < 500) return res;
      lastError = new Error(`Сервер занят (${res.status})`);
    } catch (e) {
      // Сеть отвалилась — тоже повод попробовать ещё раз.
      lastError = e;
    }
  }

  throw lastError instanceof Error ? lastError : new Error('Сервер не отвечает');
};

export default fetchWithRetry;
