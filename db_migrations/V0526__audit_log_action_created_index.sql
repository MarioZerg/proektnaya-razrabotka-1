-- Индекс для быстрой очистки служебных записей журнала.
--
-- Журнал пишет строку на КАЖДЫЙ запуск планировщика: 15 заданий круглосуточно
-- дают около тысячи записей в сутки. Эти отметки нужны ровно для одного —
-- показать на странице планировщика, когда задание отработало в последний раз.
-- Читать их старше пары недель незачем.
--
-- Индекс по действию и дате: без него и очистка, и сама страница планировщика
-- («когда последний раз отработало задание X») перебирают весь журнал целиком.
CREATE INDEX IF NOT EXISTS idx_audit_log_action_created
  ON audit_log (action, created_at DESC);
