-- Возврат тестового перемещения.
--
-- При проверке запрета перекладки забронированных вещей одна вещь успела переехать
-- на другую полку до того, как защита вступила в силу. Возвращаем её на исходную
-- «ФБО полку», иначе сборщик пойдёт по списку подбора и не найдёт вещь на месте.
UPDATE goods_warehouse
SET shelf_id = (SELECT id FROM shelves WHERE name = 'ФБО полка' LIMIT 1)
WHERE storage_barcode = '000653485';
