-- Возврат с маркетплейса ошибочно попал в поток «Разложить по полкам».
--
-- Вещь «Лен 300x265» (стикер GW-001279) приехала с OZON как возврат покупателя, но
-- оказалась в статусе awaiting_shelf. Этот статус — для ДРУГОГО потока: вещей, от
-- которых клиент отказался прямо в цехе. Их судьба ясна, им нужна только полка.
--
-- Возврату же сначала нужно решение кладовщика: годная вещь — на полку, мятая или
-- с дефектом — в цех на осмотр. Проходя мимо разбора, вещь с дефектом встала бы на
-- полку как годная и уехала следующему покупателю.
--
-- Возвращаем её в поток возвратов (mp_return). Причина попадания уже устранена:
-- теперь при укладке с разбора вещь сразу встаёт на конкретную полку, минуя
-- промежуточный статус.
--
-- Правим ТОЛЬКО вещи, пришедшие как возврат (receive_reason='return'): отказы из
-- цеха остаются на месте.

UPDATE goods_warehouse
SET status = 'mp_return'
WHERE status = 'awaiting_shelf'
  AND receive_reason = 'return';
