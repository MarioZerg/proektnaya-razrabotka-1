-- Уборка тестовых приёмок.
--
-- При проверке ручной приёмки на склад завелись две служебные вещи «Бамбук 200x220»
-- (WH-00002 и WH-00003). Реального товара за ними нет — помечаем их утерянными, чтобы
-- они не всплыли в подборе под заказ и кладовщик не пошёл искать их по полкам.
UPDATE goods_warehouse
SET status = 'lost',
    lost_reason = 'Тестовая приёмка, товара физически нет',
    lost_at = now()
WHERE storage_barcode IN ('GW-722486', 'GW-722487');
