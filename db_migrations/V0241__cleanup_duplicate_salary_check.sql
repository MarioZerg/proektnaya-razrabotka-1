-- Снимаем тестовую запись проверки (сумма была 0, на зарплату не влияла).
-- Данные не удаляем: помечаем описание как отменённую проверку и обнуляем привязку
-- к смене, чтобы запись не мешала дневному индексу.
UPDATE salary_accruals
SET description = 'ПРОВЕРКА-ДУБЛЯ (отменена)',
    type = 'check_removed',
    amount = 0
WHERE description = 'ПРОВЕРКА-ДУБЛЯ смена 1' AND amount = 0;