-- Тестовая смена 243 для проверки начисления оклада при автозакрытии.
--
-- Сдвигаем время открытия на утро, иначе ночной обход её не тронет: смены, открытые
-- уже после конца рабочего дня, он намеренно пропускает. Цех проставляем, потому что
-- ставка оклада берётся из тарифов цеха.
UPDATE shift_sessions
SET opened_at = (CURRENT_DATE + time '05:00') - interval '3 hours',
    workshop_id = (SELECT id FROM workshops WHERE name = 'Цех №1')
WHERE id = 243;