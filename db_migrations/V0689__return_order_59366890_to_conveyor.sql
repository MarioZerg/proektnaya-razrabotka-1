-- ЗАКАЗ 59366890-0007-1 ВОЗВРАЩАЕТСЯ НА КОНВЕЙЕР.
--
-- ЧТО СЛУЧИЛОСЬ. 16 сентября к нам вернулась вещь «Мрамор 200x265» по отменённому
-- заказу 0135920274-0553-3 и легла на полку под стикером GW-731772. 20 сентября
-- автоподбор закрыл ею этот заказ: sewing_status стал «Со склада», вещь ушла в
-- поставку 1353 и помечена shipped.
--
-- ПОЧЕМУ ЭТО ТУПИК. OZON до сих пор держит отправление в awaiting_deliver — то есть
-- ждёт его от нас. Вещь при этом уже уехала, и закрыть заказ нечем: на конвейере он
-- никогда не был (в журнале по нему нет ни одной записи цеха), ярлык печатать не на
-- что, а товар висит на маркетплейсе без движения.
--
-- РЕШЕНИЕ. Отдаём заказ в производство заново: цех сошьёт новую вещь и отгрузит её
-- по живому ярлыку OZON. Возврат GW-731772 не трогаем — он уже отгружен в поставке,
-- это закрытая история.
--
-- ЧТО ИМЕННО СБРАСЫВАЕМ:
--   · sewing_status → «Новый» — заказ встаёт в очередь на раскрой;
--   · status → «Новый» — «Отгружен» здесь неправда, отгрузки по нему не было;
--   · fulfilled_from_stock_id → NULL — без этого очередь раскроя заказ не возьмёт:
--     в выборке стоит условие fulfilled_from_stock_id IS NULL.
--
-- Поля цеха и исполнителей уже пусты (cut_at, taken_at, sewn_at, packed_at — NULL),
-- трогать их не нужно: заказ действительно не проходил ни одного этапа.

UPDATE orders
SET sewing_status = 'Новый',
    status = 'Новый',
    fulfilled_from_stock_id = NULL
WHERE id = 100492
  AND order_number = '59366890-0007-1';

-- Снимаем мёртвую бронь с вещи. Она уже отгружена (status='shipped'), и ссылка на
-- заказ, который мы сейчас отправили шить заново, только мешает: склад показывал бы
-- вещь как зарезервированную под живой заказ.
--
-- order_id (98870 — тот заказ, ПО КОТОРОМУ вещь вернулась) оставляем: это история
-- происхождения возврата, её переписывать нельзя.
UPDATE goods_warehouse
SET reserved_order_id = NULL
WHERE id = 10445
  AND reserved_order_id = 100492;

-- Отметка в журнале: без неё в истории заказа осталась бы дыра — вещь была «Со
-- склада», стала «Новый», и непонятно кто и почему это сделал.
INSERT INTO audit_log (user_id, user_name, category, action, entity_type, entity_id, description)
VALUES (
    NULL, 'Система', 'orders', 'return_to_conveyor', 'order', 100492,
    'Заказ 59366890-0007-1 возвращён на конвейер: вещь со склада GW-731772 уже '
    'отгружена в поставке 1353, а OZON ждёт отправление (awaiting_deliver). '
    'Снята привязка к складу, заказ отдан в раскрой заново'
);
