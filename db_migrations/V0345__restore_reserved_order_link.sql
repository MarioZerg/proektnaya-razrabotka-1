-- Восстанавливаем связь вещи с заказом, под который она собрана.
--
-- При возврате вещи из поставки система снимает резерв — это правильно для настоящего
-- возврата, но здесь вещь убирали из поставки только ради проверки сканирования.
-- Без резерва вещь не связана с заказом 0140003248-0530-1-1: кладовщик не сможет
-- перепечатать по ней ярлык маркетплейса, а заказ будет выглядеть несобранным.
UPDATE goods_warehouse
SET reserved_order_id = (
      SELECT id FROM orders WHERE order_number = '0140003248-0530-1-1' LIMIT 1
    ),
    matched_at = COALESCE(matched_at, now())
WHERE storage_barcode = '000651067'
  AND reserved_order_id IS NULL;
