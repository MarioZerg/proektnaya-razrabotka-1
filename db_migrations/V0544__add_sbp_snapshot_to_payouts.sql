-- КУДА УШЛИ ДЕНЬГИ: снимок реквизитов в момент выплаты.
--
-- Номер СБП живёт в профиле сотрудника и может смениться: человек поменял банк
-- или телефон. Тогда по старым выплатам уже не ответить на вопрос «на какой
-- номер ушли деньги в марте» — в профиле лежит новый.
--
-- Поэтому при выплате записываем реквизиты рядом с суммой. Это не дубль
-- профиля, а исторический факт: так было на момент перевода.
ALTER TABLE salary_payouts
ADD COLUMN IF NOT EXISTS sbp_phone VARCHAR(30),
ADD COLUMN IF NOT EXISTS sbp_bank VARCHAR(120);

COMMENT ON COLUMN salary_payouts.sbp_phone IS
'Номер СБП на момент выплаты — снимок, профиль мог измениться позже';