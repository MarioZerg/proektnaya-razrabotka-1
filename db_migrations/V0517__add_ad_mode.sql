-- Режим расчёта ДРР по площадке.
--
-- Зачем. Wildberries отдаёт расход рекламы по каждому товару, и раньше мы
-- так и считали: продвигали позицию — она и платит. Звучит справедливо, но
-- на практике даёт дикий разброс: у одной шторы ДРР 888%, у соседнего
-- размера той же ткани — ноль. Сравнивать размеры между собой становится
-- невозможно, а решение «поднять цену» принимается по случайной цифре.
--
-- OZON списывает рекламу общей суммой, и там у всех товаров один процент —
-- картина ровная и понятная.
--
-- Что делаем. Разрешаем считать ДРР по Wildberries так же: одним процентом
-- на весь ассортимент. Владелец выбирает режим сам и может задать процент
-- вручную, если хочет заложить план, а не факт.
ALTER TABLE marketplace_tariffs
    -- Как считать ДРР: 'item' — по каждому товару (факт площадки),
    -- 'shared' — единый процент на весь ассортимент.
    ADD COLUMN IF NOT EXISTS ad_mode VARCHAR(10) NOT NULL DEFAULT 'item';

COMMENT ON COLUMN marketplace_tariffs.ad_mode IS
    'Режим ДРР: item — по каждому товару отдельно, shared — единый процент '
    'на весь ассортимент, как на OZON';

-- Wildberries по умолчанию переводим на общий процент: разброс по товарам
-- мешал сравнивать размеры между собой.
UPDATE marketplace_tariffs SET ad_mode = 'shared'
WHERE marketplace_code = 'wildberries';
