-- ПЕРЕДАЧА ОТМЕНЁННОГО КРОЯ ЖИВОМУ ЗАКАЗУ.
--
-- Покупатель отменяет заказ уже после раскроя: ткань разрезана по его размеру и
-- обратно в рулон не вернётся. Такой крой висит на вешалке во вкладке
-- «Отменённые с кроем», и швеи дошивают его на склад хранения.
--
-- Но если приходит НОВЫЙ заказ ровно того же размера и материала — шить его с
-- нуля незачем: подходящий крой уже висит в цехе. Передаём крой новому заказу,
-- и на склад ничего лишнего не уезжает.
--
-- ДВЕ ССЫЛКИ, А НЕ ОДНА — НАМЕРЕННО.
--
-- На вешалке висит БИРКА СО СТАРЫМ НОМЕРОМ, и перепечатать её некому: заказы
-- приходят круглосуточно. Поэтому связь нужна в обе стороны:
--   * cut_from_order_id  — у нового заказа: по нему на экране показываем швее
--     «крой с биркой 47688307-0541-1», и по нему же терминал находит новый
--     заказ, когда упаковщица сканирует старую бирку;
--   * cut_given_to_order_id — у отменённого: по нему он уходит из вкладки
--     «Отменённые с кроем». Крой больше не висит ничей — он стал новым заказом.
--
-- Выводить вторую ссылку из первой нельзя: список заказов на экране обрезан по
-- объёму, и нового заказа в нём может просто не оказаться — тогда отменённый
-- навсегда остался бы висеть в списке «доделать».
ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS cut_from_order_id INTEGER REFERENCES orders(id),
  ADD COLUMN IF NOT EXISTS cut_given_to_order_id INTEGER REFERENCES orders(id);

-- Поиск свободного отменённого кроя идёт по товару и цеху на каждом новом
-- заказе FBS — это горячий путь загрузки заказов с маркетплейса.
CREATE INDEX IF NOT EXISTS idx_orders_cancelled_cut_free
  ON orders (product, workshop_id)
  WHERE sewing_status = 'Раскроено' AND cut_given_to_order_id IS NULL;

-- По этой ссылке терминал ищет заказ, отсканировав старую бирку.
CREATE INDEX IF NOT EXISTS idx_orders_cut_from
  ON orders (cut_from_order_id)
  WHERE cut_from_order_id IS NOT NULL;
