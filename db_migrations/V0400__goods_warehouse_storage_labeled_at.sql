-- Отметка, что упаковщица РЕАЛЬНО напечатала и наклеила стикер хранения на вещь.
--
-- Проблема: счётчик «Разложить по полкам» показывал 6, кладовщик шёл в цех — а вещей
-- там нет. Потому что вещь заводилась на склад в момент закрытия заказа на терминале,
-- то есть ДО того, как упаковщица напечатала стикер и физически отложила вещь в
-- контейнер. Печать могла не сработать (кончилась бумага, принтер занят, вылетела
-- ошибка) — а счётчик уже звал кладовщика за товаром, которого ещё нет.
--
-- Теперь в счётчик попадают только вещи с проставленной датой в storage_labeled_at:
-- стикер напечатан, наклеен, вещь лежит в контейнере и её реально можно забрать.
ALTER TABLE goods_warehouse
ADD COLUMN IF NOT EXISTS storage_labeled_at TIMESTAMP;

-- Вещам, которые уже лежат в цехе со вчера и раньше, отметку проставляем задним
-- числом: они прошли старым путём, стикер на них есть, и терять их из работы нельзя.
UPDATE goods_warehouse
SET storage_labeled_at = received_at
WHERE status = 'awaiting_shelf'
  AND storage_labeled_at IS NULL
  AND storage_barcode IS NOT NULL;

COMMENT ON COLUMN goods_warehouse.storage_labeled_at IS
  'Когда упаковщица напечатала стикер хранения. Пока пусто — вещь ещё не готова к забору кладовщиком';
