-- Демонстрационный аккаунт «Швея (оверлок)» для тестового входа администратора.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ ЗАПИСЬ, А НЕ ГАЛОЧКА ЖИВОЙ ШВЕЕ.
-- Оверлок — это не отдельная должность, а допуск: галочка can_overlock в карточке
-- швеи. Она открывает вкладку «Оверлок» на конвейере и меняет расчёт зарплаты
-- (вещь после оверлока оплачивается по другому тарифу). Поставить эту галочку
-- работающей швее ради теста нельзя — у неё сразу изменится доступ и деньги.
-- Поэтому заводим отдельного демо-сотрудника.
--
-- Вход по паролю у него невозможен: хэш и соль — заглушки, а сам аккаунт нужен
-- только для кнопки тестового входа у администратора (там пароль не проверяется).
INSERT INTO users (
    login, password_hash, password_salt, full_name, role,
    workshop, shift_number, can_overlock, is_active, salary
)
SELECT
    'demo_sewer_overlock',
    'demo-no-login', 'demo-no-login',
    'Швея (оверлок) — тестовый',
    'sewer',
    'Цех №1',
    1,
    true,
    true,
    0
WHERE NOT EXISTS (SELECT 1 FROM users WHERE login = 'demo_sewer_overlock');