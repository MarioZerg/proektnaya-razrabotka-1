-- Возвращаем вещь GW-003353 в то состояние, в котором она была до проверки.
--
-- При проверке исправления я отсканировал эту вещь в короб FBO и сразу убрал
-- обратно. Удаление позиции из короба (remove_box_item) для FBO снимает с вещи
-- ярлык и бронь и кладёт её на полку свободным остатком — это правильное
-- поведение для настоящего разбора короба, но здесь оно сбросило состояние,
-- которое вещь имела до теста.
--
-- Было: status 'awaiting_supply', ярлык OZN наклеен 08.09, вещь закреплена за
-- строкой заявки 2000065880431-183 (заказ 95179). Возвращаем ровно это.
UPDATE goods_warehouse
SET status = 'awaiting_supply',
    reserved_order_id = 95179,
    matched_at = COALESCE(matched_at, now()),
    shipping_labeled_at = '2026-09-08 11:03:03.481304',
    shipping_labeled_by_name = 'Восстановлено после проверки'
WHERE id = 3353;

-- Заказ снова считается закрытым этой вещью — как и был до теста.
UPDATE orders
SET sewing_status = 'Со склада',
    fulfilled_from_stock_id = 3353
WHERE id = 95179;
