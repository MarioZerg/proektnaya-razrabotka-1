-- Цех, который занимается перепаковкой конкретной вещи.
--
-- Раньше экран перепаковки показывал ВСЕ вещи со статусом 'repacking' — один общий
-- список на все киоски. Упаковщица цеха №1 и упаковщица цеха №2 видели одни и те же
-- строки: обе шли искать вещь, которая физически лежит только в одном цехе, и обе
-- могли отчитаться по ней. Работа дублировалась, а оплата за перепаковку начислялась
-- тому, кто успел нажать первым.
--
-- Теперь вещь закрепляется за цехом: чей киоск её отсканировал — тот и работает.
-- NULL означает «ещё не распределена»: такая вещь видна всем цехам, но закрепится
-- за первым, кто её отсканирует.
ALTER TABLE t_p86119184_proektnaya_razrabotk.goods_warehouse
    ADD COLUMN IF NOT EXISTS repack_workshop_id INTEGER;

-- Индекс под счётчик на киоске: «сколько вещей ждёт перепаковки в моём цехе».
-- Счётчик дёргается при каждом открытии экрана, поэтому запрос должен быть мгновенным.
CREATE INDEX IF NOT EXISTS idx_gw_repack_workshop
    ON t_p86119184_proektnaya_razrabotk.goods_warehouse (repack_workshop_id)
    WHERE status = 'repacking';
