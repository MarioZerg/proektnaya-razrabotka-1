-- Возврат заказов, взятых при проверке добора по одному.
--
-- Проверяли новую логику кнопки «Взять 1 заказ» на живом закройщике: у Марии
-- было 7 заказов на раскрое, добрали до предела в 20. Эти 13 заказов она не
-- просила — возвращаем их в общую очередь, чтобы не мешали работе и достались
-- тому, кто реально возьмёт их в раскрой.
--
-- Трогаем только НЕраскроенные (sewing_status = 'На раскрое'): если она успела
-- какой-то раскроить, он останется за ней вместе с выработкой.
UPDATE orders
SET sewing_status = 'Новый',
    assigned_user_id = NULL,
    cutter_user_id = NULL
WHERE id IN (88090, 88089, 88086, 88085, 88084, 88083,
             88078, 88077, 88076, 88073, 88072, 88066, 88063)
  AND assigned_user_id = 34
  AND sewing_status = 'На раскрое';
