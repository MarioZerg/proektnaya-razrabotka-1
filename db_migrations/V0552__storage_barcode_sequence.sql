-- Складской код вещи (GW-…) выдаёт САМА БАЗА, а не расчёт «максимум плюс один».
--
-- ЧТО БЫЛО СЛОМАНО.
-- Код генерировался так: прочитать все существующие коды, найти максимум,
-- прибавить единицу. При этом код обязан быть уникальным.
--
-- Когда два терминала закрывают заказы почти одновременно, оба читают базу до
-- того, как первый успел записать свою строку, — и оба получают ОДИН И ТОТ ЖЕ
-- номер. Второй падает на уникальности, и вместе с ним обрывается вся операция
-- закрытия заказа: складская запись не создаётся, зарплата швее и упаковщице не
-- начисляется, в журнале не остаётся даже следа. Упаковка при этом уже списана,
-- а статус «Готовые» проставлен — заказ выглядит закрытым, но человек за него
-- денег не получил. Так потерялась оплата по заказу 55691968-0274-5, и так же
-- 12 августа подряд ушли семь заказов.
--
-- Счётчик базы (sequence) свободен от этой беды: он выдаёт номер атомарно,
-- двум запросам одно и то же значение достаться не может в принципе.
--
-- Стартуем с запасом от текущего максимума: коды уже ушли далеко вперёд
-- (GW-727939), и начать с нуля значило бы налететь на занятые номера.
CREATE SEQUENCE IF NOT EXISTS goods_warehouse_storage_seq;

SELECT setval(
    'goods_warehouse_storage_seq',
    GREATEST(
        (SELECT COALESCE(MAX(NULLIF(regexp_replace(storage_barcode, '\D', '', 'g'), '')::bigint), 0)
           FROM goods_warehouse
          WHERE storage_barcode LIKE 'GW-%'),
        1
    ) + 100
);
