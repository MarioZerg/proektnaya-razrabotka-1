-- Отметка «день акции уже посчитан».
--
-- Нужна для дня, в который цель не взял никто: без такой отметки система пересчитывала
-- бы этот день при каждом обращении к зарплате — впустую и бесконечно. Держим её
-- отдельной таблицей, а не фиктивной строкой в sewer_daily_bonus: там каждая запись
-- обязана ссылаться на живого сотрудника.
CREATE TABLE IF NOT EXISTS sewer_daily_settled (
    challenge_date DATE PRIMARY KEY,
    settled_at TIMESTAMP NOT NULL DEFAULT now()
);
