-- Неубиваемое исходное количество позиции приёмки.
--
-- ЧТО СЛОМАЛОСЬ. При подтверждении приёмки код делил количество позиции на число
-- рулонов и ЗАПИСЫВАЛ результат обратно в ту же строку (quantity = per_roll_qty).
-- Пока подтверждение проходит один раз — всё честно. Но приёмка #325 сорвалась на
-- ошибке и осталась в статусе «Новый»: каждое следующее нажатие «Принять» делило
-- уже поделённое. 1200 → 150 → 18.75 → 2.344. Ровно эти «2.34 штуки» и увидел
-- пользователь вместо пачек по 1200.
--
-- ЧТО ДЕЛАЕМ. Заводим отдельную колонку с исходным количеством, которое НИКОГДА
-- не перезаписывается. Деление на рулоны всегда считается от неё, поэтому сколько
-- бы раз подтверждение ни повторилось — результат один и тот же.
ALTER TABLE shipment_items ADD COLUMN IF NOT EXISTS total_quantity NUMERIC(12,3) NULL;

-- Заполняем историю: у настоящих позиций (number_rolls заполнен кладовщиком)
-- исходное количество — это то, что сейчас лежит в quantity.
UPDATE shipment_items
SET total_quantity = quantity
WHERE total_quantity IS NULL
  AND number_rolls IS NOT NULL
  AND quantity IS NOT NULL;
