-- Отметка «эту вещь кладовщик реально взял в руки и подтвердил сканером».
--
-- ЗАЧЕМ. Вещи одного размера лежат на полке вперемешку и физически не отличаются:
-- «Вуаль 300x250» — она и есть «Вуаль 300x250», под каким бы номером ни числилась.
-- Кладовщик берёт любую подходящую, и система должна переносить подбор на ту,
-- что у него в руках, а не гонять его искать конкретный номер.
--
-- Но у свободного переноса есть обратная сторона, на которую уже наступали:
-- подбор просто переезжал с вещи на вещь, количество не менялось, и сканер
-- бесконечно отвечал «нужная». Человек пикал десятый рулон подряд и каждый раз
-- слышал успех, хотя нужна была одна штука.
--
-- Эта отметка закрывает потребность: как только вещь подтверждена сканером,
-- заказ под ней считается набранным, и перенести его на следующую такую же
-- вещь уже нельзя. Нужно 2 штуки — сканер даст ровно 2 успеха.
--
-- Снимается вместе с резервом: вещь освободили — отметка тоже уходит.
ALTER TABLE goods_warehouse
    ADD COLUMN IF NOT EXISTS picked_confirmed_at TIMESTAMP,
    ADD COLUMN IF NOT EXISTS picked_confirmed_by INTEGER;

-- Быстро находить «такой же товар, ещё не подтверждённый» при обходе стеллажа.
CREATE INDEX IF NOT EXISTS goods_warehouse_picked_confirmed_idx
    ON goods_warehouse (picked_confirmed_at)
    WHERE picked_confirmed_at IS NULL;
