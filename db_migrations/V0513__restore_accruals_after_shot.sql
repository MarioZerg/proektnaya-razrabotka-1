-- Возвращаем пробные недели в аннулированные после проверки внешнего вида.
--
-- Проверено: у каждого отчёта своя метка площадки (OZON, Wildberries,
-- Яндекс Маркет) и средняя маржа за период — 30–32%. Раньше во всех отчётах
-- жёстко писалось «OZON», хотя расчёт шёл по разным площадкам.
--
-- Пробная сумма 99 999 ₽ по неделе 03–09.08 остаётся: она подтверждает, что
-- выплаченный отчёт пересчёт не трогает.
UPDATE manager_accruals
SET status = 'cancelled',
    cancelled_at = now(),
    cancel_reason = 'Пробный расчёт при настройке. Эти недели оплачиваются вручную'
WHERE user_id = 32 AND period_start < DATE '2026-08-24';
