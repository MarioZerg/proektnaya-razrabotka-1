-- Норма недостачи в рулонах: без неё штрафы не считались НИ РАЗУ.
--
-- Как устроен расчёт: часть недостачи нормальна (поставщик мотает с погрешностью),
-- и её размер задан в карточке поставщика. Штраф берётся только за то, что вышло
-- за норму. Норма копируется в рулон в момент приёмки — чтобы позже изменение
-- условий у поставщика не переписывало задним числом уже закрытые рулоны.
--
-- Проблема: у всех 598 активных рулонов это поле пустое. Расчёт штрафа в таком
-- случае молча возвращает «У поставщика не задана норма недостачи» и не считает
-- ничего. За всё время накопилось 2111 закрытых рулонов с недостачей и НОЛЬ
-- начислений — недостача просто списывалась в никуда.
--
-- Проставляем норму из карточки поставщика. Где у поставщика норма не задана
-- (WB, Мегатюль — это возвраты и разовые приходы) — ставим 5%, рабочую норму,
-- по которой и закладывались ткань и тесьма.
--
-- Трогаем только рулоны в работе: закрытые — это история, их пересчёт задним
-- числом создал бы штрафы за смены, которые давно приняты и оплачены.

UPDATE rolls r
SET shortage_norm_percent = COALESCE(s.shortage_norm_percent, 5.0)
FROM suppliers s
WHERE s.id = r.supplier_id
  AND r.status <> 'completed'
  AND r.shortage_norm_percent IS NULL;

-- Рулоны без поставщика (заведены вручную при переносе данных) — та же рабочая норма.
UPDATE rolls
SET shortage_norm_percent = 5.0
WHERE status <> 'completed' AND shortage_norm_percent IS NULL;
