-- Снимаем со склада вещь 000694687 — её заведут вручную заново.
--
-- Вещь была подобрана под заказ WB 5449702943, отстикерована и переведена в «На поставке».
-- Но Wildberries закрыл это сборочное задание у себя: стикер для него больше не выдаётся,
-- в поставку вещь не уедет, а на складе она числилась занятой под мёртвый заказ.
--
-- Записи не удаляем — история операций по вещи должна остаться целой. Помечаем списанной
-- с понятной причиной и снимаем резерв, чтобы вещь исчезла из подбора, счётчиков и
-- фильтра «На поставке». Физически товар на месте: кладовщик заведёт его как новую
-- позицию через «Добавить товары вручную» и получит свежий стикер хранения.
UPDATE goods_warehouse
SET status = 'lost',
    lost_at = now(),
    lost_reason = 'Снят со склада: заказ WB 5449702943 закрыт маркетплейсом, '
                  || 'стикер не выдаётся. Товар заводится вручную заново',
    reserved_order_id = NULL,
    matched_at = NULL,
    shipping_labeled_at = NULL
WHERE storage_barcode = '000694687';

-- Заказ больше не считается закрытым складом: вещи под него нет.
UPDATE orders
SET fulfilled_from_stock_id = NULL
WHERE order_number = '5449702943'
  AND fulfilled_from_stock_id IS NOT NULL;
