-- НДС в юнит-экономике.
--
-- С 2026 года упрощенцы с доходом выше лимита платят НДС. Считать его как ещё
-- один процент от цены нельзя: НДС уже сидит ВНУТРИ цены покупателя, а доход
-- по УСН по закону считается БЕЗ НДС. Поэтому храним ставку отдельно и в
-- расчёте сначала вынимаем НДС из цены, а налог УСН берём с остатка.
--
-- vat_percent = 0 означает «освобождены от НДС» — расчёт как раньше.
ALTER TABLE unit_economics_settings
    ADD COLUMN IF NOT EXISTS vat_percent NUMERIC(6,2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN unit_economics_settings.vat_percent IS
    'Ставка НДС, %. 0 — освобождение. При УСН: 5, 7 или 22';

-- Фактическая цена покупателя — база всего расчёта.
--
-- Раньше считали от цены карточки, но покупатель платит меньше: площадка режет
-- цену акциями и баллами. Налог с цены витрины завышал расходы, а прибыль
-- показывал не ту, что есть на самом деле.
COMMENT ON COLUMN marketplace_prices.price_with_marketplace_discount IS
    'Фактическая цена покупателя после акций площадки — база расчёта налога';
