-- Возврат доначислений закройщикам на дни фактической работы.
--
-- Вчера доначисление за пропущенные раскрои (V0357) записалось с датой по умолчанию —
-- днём внесения, 12.08. Из-за этого работа, сделанная 10 и 11 августа, попала в смену
-- 12-го: у закройщиков разъехалась выработка по дням, а в отчёте за смену появились
-- чужие деньги.
--
-- accrued_for — это дата, ЗА которую начислено, и она должна совпадать с днём раскроя
-- (orders.cut_at). Приводим её в соответствие.
--
-- Затрагивает 129 начислений на 4630 ₽ у двух закройщиков. Ни одно не выплачено
-- (paid_at IS NULL) — суммы не меняются, меняется только день, к которому они отнесены.
UPDATE salary_accruals sa
SET accrued_for = o.cut_at::date
FROM orders o
WHERE o.id = sa.order_id
  AND sa.type = 'cutter_cut'
  AND sa.paid_at IS NULL
  AND o.cut_at >= '2026-08-10'
  AND sa.accrued_for <> o.cut_at::date;
