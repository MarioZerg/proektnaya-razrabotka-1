-- Восстановление затёртого количества в приёмке #325.
--
-- ЧТО ПРОИЗОШЛО.
-- Приёмка от 10.09.2026 (Синьон Яна + Ореховская Мануфактура) при подтверждении
-- упала на питоновской ошибке int(None). Обработчик ловил только ошибки базы,
-- поэтому отката не случилось: рулоны остались, а приёмка — в статусе «Новый».
-- Каждое следующее нажатие «Принять» добавляло на склад новую порцию материала
-- и заново делило количество в позиции на число рулонов.
--
-- Позиция 1893 (Пакет 25х30, 8 рулонов): должно быть 9600 шт в позиции
-- (8 рулонов по 1200 шт). После четырёх сорвавшихся прогонов в ней осталось
-- 2.344 — это 1200, поделённое на 8 четыре раза подряд.
--
-- Лишние рулоны и порождённые строки удалять миграцией нельзя и не нужно:
-- исправленный код приёмки убирает их сам при следующем подтверждении.
-- Здесь возвращаем только цифру, которую восстановить автоматически невозможно.
UPDATE shipment_items SET quantity = 9600 WHERE id = 1893 AND shipment_id = 325;
