-- Обнуляем счётчик «На поставку»: 475 вещей уже увезли на OZON.
--
-- Эти вещи попали в статус 'awaiting_supply' при переносе истории: система завела им
-- складские записи задним числом, хотя физически короба давно уехали. По данным OZON
-- 456 из них уже в доставке, 6 ждут отгрузки, 13 отменены покупателями.
--
-- По решению владельца списываем все 475 подчистую: счётчик должен показывать реальный
-- остаток в цехе, а не историю. Отмеченные отменёнными тоже списываем — если такие вещи
-- физически найдутся на складе, кладовщик заведёт их заново приёмкой.
--
-- Заказы не трогаем: их статусы ведёт маркетплейс, а не склад.
UPDATE goods_warehouse
SET status = 'shipped',
    shipped_at = COALESCE(shipped_at, now())
WHERE status = 'awaiting_supply'
  AND NOT EXISTS (
    SELECT 1 FROM marketplace_supply_items msi
    WHERE msi.goods_warehouse_id = goods_warehouse.id
  );
