-- Вещь распущена обратно в материал и лежит метрами на рулоне.
--
-- ЗАЧЕМ. Упаковщица при перепаковке иногда перекраивает вещь, и годный кусок
-- ткани возвращается на рулон. Физически вещи после этого не существует —
-- есть метры материала. Но в системе она оставалась «на перепаковке», и это
-- давало сразу две дыры:
--   1) тот же кусок можно было вернуть на рулон повторно, сколько угодно раз —
--      остаток рулона рос из воздуха, а на инвентаризации не сходился;
--   2) упаковщица потом нажимала на этой же вещи «Переупаковано» и получала
--      оплату за товар, которого уже нет.
--
-- Отдельный статус закрывает обе: вещь уходит с перепаковки и в работу больше
-- не попадает. Оплата за такую вещь не начисляется — упаковщица получает
-- только за перепаковку годного товара.
ALTER TABLE goods_warehouse
    ADD COLUMN IF NOT EXISTS returned_to_roll_at TIMESTAMP,
    ADD COLUMN IF NOT EXISTS returned_to_roll_id INTEGER;

COMMENT ON COLUMN goods_warehouse.returned_to_roll_at IS
    'Когда вещь распустили в материал и вернули на рулон';
COMMENT ON COLUMN goods_warehouse.returned_to_roll_id IS
    'На какой рулон легли метры от этой вещи';

CREATE INDEX IF NOT EXISTS goods_warehouse_returned_to_roll_idx
    ON goods_warehouse (returned_to_roll_id)
    WHERE returned_to_roll_id IS NOT NULL;
