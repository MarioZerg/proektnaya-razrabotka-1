-- Индексы под «Взять заказ в работу»: швеи не могли брать работу.
--
-- ЧТО БЫЛО. На каждое нажатие «Взять заказ» функция проверяет лимиты швеи и
-- считает накопленный таймаут. Все эти проверки ищут заказы по assigned_user_id
-- и sewer_user_id, а индексов по этим полям не было вовсе. В таблице 10 500
-- заказов, поэтому каждая проверка означала полный перебор таблицы — и не одна,
-- а несколько за один вызов. Функция переставала укладываться в свои 5 секунд и
-- падала с таймаутом: швея видела ошибку вместо заказа.
--
-- К концу смены становилось хуже: чем больше заказов швея уже взяла, тем
-- тяжелее считался её таймаут — поэтому «взять заказ» отваливалось именно в
-- разгар работы, а с утра всё работало.

-- Лимит незакрытых заказов: «сколько у швеи В работе и на Стикеровке».
-- Частичный индекс — нас интересуют только эти два статуса, остальные 10 тысяч
-- строк в индекс не попадают, он остаётся маленьким и быстрым.
CREATE INDEX IF NOT EXISTS idx_orders_assigned_open
    ON orders (assigned_user_id)
    WHERE sewing_status IN ('В работе', 'Стикеровка');

CREATE INDEX IF NOT EXISTS idx_orders_sewer_open
    ON orders (sewer_user_id)
    WHERE sewing_status IN ('В работе', 'Стикеровка');

-- Накопительный таймаут и дневной лимит метража: «что швея взяла за смену».
-- Ищется по assigned_user_id + taken_at, поэтому индекс составной.
CREATE INDEX IF NOT EXISTS idx_orders_assigned_taken_at
    ON orders (assigned_user_id, taken_at)
    WHERE taken_at IS NOT NULL;

-- Сама выдача заказа: очередь «Раскроено» по цеху смены.
CREATE INDEX IF NOT EXISTS idx_orders_queue_cut
    ON orders (workshop_id, order_type, marketplace_created_at, cut_at)
    WHERE sewing_status = 'Раскроено';
