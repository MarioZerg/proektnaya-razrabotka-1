-- ОВЕРЛОК — ОДНА МАШИНА НА ЦЕХ, И ОЧЕРЕДЬ ДОЛЖНА ЭТО УЧИТЫВАТЬ.
--
-- ЧТО БЫЛО НЕ ТАК. Вещи под обмётку лежат в очереди «Оверлок», и взять их мог
-- кто угодно и сколько угодно. Оверлок в цехе физически ОДИН: если за него сели
-- три швеи, две стоят рядом и ждут, пока освободится машина, — а их заказы уже
-- числятся «в работе» и никому другому не достанутся. Работа встаёт на ровном
-- месте, хотя в цехе есть прямострочка, которую можно шить прямо сейчас.
--
-- КАК ДОЛЖНО БЫТЬ. За оверлоком работает ОДНА швея и держит не больше двух вещей.
-- Пока она их не обметала, очередь оверлока для остальных закрыта — они молча
-- получают обычную работу (в прямострочке вещи под оверлок и так не выдаются,
-- пока край не обметан). Обметала и сдала — слот свободен, следующие две вещи
-- берёт кто угодно.
--
-- ЗАЧЕМ СВОИ ПОЛЯ ВРЕМЕНИ. У обмётки свой темп: он не зависит от ширины так,
-- как пошив, и считается от момента, когда швея села за машину. Складывать его
-- с таймером прямострочки (taken_at) нельзя — это разные этапы одной вещи, и
-- вещь проходит их по очереди.

-- Когда швея взяла вещь на обмётку. От этой отметки идёт таймер оверлока.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS overlock_taken_at TIMESTAMP NULL;

-- Номер вещи «на руках» у оверлочницы: 0 — первая, 1 — вторая.
--
-- Нужен по той же причине, что sew_stagger_index в пошиве: две вещи взяты почти
-- подряд, время на обмётку у них одинаковое, и таймеры кончаются в одну секунду.
-- Второй вещи добавляем сдвиг, чтобы обмётка шла ровным потоком, а не пачкой.
-- Номер фиксируется при взятии и не прыгает, когда первую вещь уже сдали.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS overlock_stagger_index INTEGER NOT NULL DEFAULT 0;

-- Быстрый ответ на вопрос «кто сейчас за оверлоком в этом цехе»: запрос идёт на
-- каждое взятие вещи на обмётку и на каждую отрисовку очереди.
CREATE INDEX IF NOT EXISTS idx_orders_overlock_in_work
    ON orders (workshop_id, overlock_user_id)
    WHERE overlock_user_id IS NOT NULL AND overlocked_at IS NULL;

-- НАСТРОЙКИ. Ставим глобально (system_settings) — цеха наследуют их автоматически.
--
-- Время на обмётку 3 минуты для ВСЕХ ширин: в отличие от пошива, обмётка края
-- почти не зависит от размера полотна — машина идёт по краю с одной скоростью.
-- Разбивка по ширинам всё равно оставлена: если окажется, что широкие вещи
-- обмётываются дольше, значение правится в настройках цеха без правки кода.
INSERT INTO system_settings (key, value) VALUES
    ('overlock_timeout_200', '3'),
    ('overlock_timeout_300', '3'),
    ('overlock_timeout_400', '3'),
    ('overlock_timeout_500', '3'),
    ('overlock_timeout_600', '3'),
    ('overlock_timeout_700', '3'),
    ('overlock_timeout_800', '3'),
    -- Сдвиг второй вещи: +3 минуты к её собственным 3. То есть первая вещь
    -- открывается к сдаче через 3 минуты, вторая — через 6.
    ('overlock_stagger_minutes', '3'),
    -- Сколько вещей оверлочница держит на руках одновременно.
    ('max_overlock_orders_to_seamstress', '2')
ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;

-- Прописываем те же значения в каждый цех явно: в карточке цеха админ должен
-- видеть цифры, а не пустое поле с подписью «как в общих».
INSERT INTO workshop_settings (workshop_id, key, value)
SELECT w.id, s.key, s.value
FROM workshops w
CROSS JOIN (VALUES
    ('overlock_timeout_200', '3'),
    ('overlock_timeout_300', '3'),
    ('overlock_timeout_400', '3'),
    ('overlock_timeout_500', '3'),
    ('overlock_timeout_600', '3'),
    ('overlock_timeout_700', '3'),
    ('overlock_timeout_800', '3'),
    ('overlock_stagger_minutes', '3'),
    ('max_overlock_orders_to_seamstress', '2')
) AS s(key, value)
ON CONFLICT (workshop_id, key) DO UPDATE SET value = EXCLUDED.value;
