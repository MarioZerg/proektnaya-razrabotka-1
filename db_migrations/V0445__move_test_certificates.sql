-- Тестовые заглушки (kino-1.pdf, kino-2.pdf) — не настоящие билеты, выдать их
-- сотруднику нельзя. Удалять строку не даём себе права, поэтому «гасим» её:
-- помечаем как выданную несуществующей покупке, чтобы она не попала в остаток.
--
-- Проще: переносим их на служебный скрытый товар «Проверка магазина», который
-- в витрине не показывается.
UPDATE variki_certificates
SET item_id = (SELECT id FROM variki_shop_items WHERE title = 'Проверка магазина'),
    file_name = '[тест] ' || file_name
WHERE file_name IN ('kino-1.pdf', 'kino-2.pdf');
