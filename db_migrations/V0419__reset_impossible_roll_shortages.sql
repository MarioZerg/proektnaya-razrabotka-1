-- Сброс заведомо ошибочных недостач по рулонам.
--
-- ЧТО ПРОИЗОШЛО. При закрытии рулона недостача вводится руками на терминале, и в
-- трёх случаях цифра оказалась больше, чем физически могло не хватить:
--
--   1-004776  в рулоне было 50.0 п.м., заявлено 97.0 (в заказы ушло 42.6)
--   1-004790  в рулоне было 50.0 п.м., заявлено 96.0 (в заказы ушло 19.25)
--   1-004823  в рулоне было 51.5 п.м., заявлено 37.0 (в заказы ушло 39.6 —
--             то есть недостача вместе с расходом превышает сам рулон)
--
-- Не хватать может максимум столько, сколько в рулоне оставалось. Значения больше
-- начального метража — это опечатка при вводе (лишняя цифра, сантиметры вместо
-- метров), а не реальная недостача.
--
-- ЧЕМ МЕШАЛО. Такие цифры попадают в статистику недостач по материалам: по «Сетке»
-- максимальная недостача показывалась как 194% от рулона, что искажало и средний
-- процент, и будущие нормы списания, которые по этой статистике задаются.
--
-- ПОЧЕМУ БЕЗОПАСНО. Штрафы по этим рулонам не начислялись: penalty_total = 0
-- (администратор списал на поставщика), записей удержаний в salary_accruals нет.
-- Деньги сотрудников правка не затрагивает — только чистит статистику.
--
-- Ставим 0: «недостача не зафиксирована». Сами рулоны остаются закрытыми, их
-- история и расход по заказам не меняются.
UPDATE rolls
SET shortage_quantity = 0
WHERE id IN (4776, 4790, 4823)
  AND penalty_total = 0
  AND NOT EXISTS (
    SELECT 1 FROM salary_accruals sa WHERE sa.roll_id = rolls.id
  );
