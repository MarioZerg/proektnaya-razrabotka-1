-- Помечаем ТЕСТОВУЮ запись брака, созданную при проверке нового экрана «Брак из рулона».
--
-- В ходе проверки цепочки «скан рулона → списание → стикер → приём кладовщиком» был
-- оформлен брак DF-000009 (рулон 1-004691, Бамбук, 2 м). Реального брака не было.
-- Удалять записи нельзя, поэтому помечаем её прямо в комментарии: так она не будет
-- выглядеть настоящим браком закройщика в отчётах и её видно, чтобы убрать вручную.
UPDATE material_defects
SET comment = 'ТЕСТОВАЯ ЗАПИСЬ (проверка системы) — реального брака не было'
WHERE barcode = 'DF-000009';
