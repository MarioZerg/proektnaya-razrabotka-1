-- Сбрасываем указатель загрузки заказов OZON FBS на начало списка.
--
-- Указатель дорос до 1200 и застрял: функция обрывалась по таймауту уже ПОСЛЕ того,
-- как сдвинула его на следующие 50 отправлений, поэтому пропущенные заказы не
-- забирались никогда. Причина устранена в коде (указатель теперь сдвигается только
-- после реального создания заказов), но накопленный сдвиг надо обнулить вручную —
-- иначе загрузка так и продолжит начинать с 1200-й позиции и не увидит те заказы,
-- что уже потерялись.
--
-- После сброса ближайшие запуски пройдут список с начала и подберут всё, что не
-- попало на конвейер. Повторов не будет: заказы, которые уже есть, отсекаются
-- проверкой по номеру отправления.
UPDATE system_settings SET value = '0', updated_at = now()
WHERE key = 'ozon_sync_offset';
