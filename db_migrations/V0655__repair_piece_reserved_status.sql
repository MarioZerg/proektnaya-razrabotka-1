-- КУСОК С ПЕРЕШИВА ЗАКРЕПЛЯЕТСЯ ЗА ЗАКАЗОМ, А НЕ СПИСЫВАЕТСЯ СРАЗУ.
--
-- ЧТО БЫЛО НЕ ТАК. Закройщица нажимала «Взять» — кусок мгновенно уходил в
-- status='used' и пропадал из перешива навсегда. При этом в карточке заказа
-- рядом по-прежнему висел выбор рулона: ткань уже взята с перешива, а система
-- предлагает отрезать ещё и от рулона. Передумать было нельзя — кусок из
-- списка перешива уже исчез, вернуть его было нечем, и он просто терялся.
--
-- ТЕПЕРЬ МЕЖДУ «available» И «used» ЕСТЬ ПРОМЕЖУТОЧНОЕ СОСТОЯНИЕ 'reserved':
--   * кусок закреплён за конкретным заказом и не виден другим закройщицам;
--   * его видно в карточке заказа, и оттуда же можно ОТКРЕПИТЬ — кусок
--     возвращается в перешив как available и снова доступен всем;
--   * в 'used' он переходит только в момент раскроя, когда ткань реально
--     разрезали. Тогда назад дороги нет — это уже не кусок, а крой.
--
-- Структуру таблицы менять не нужно: status — VARCHAR(20), used_order_id уже
-- есть. Нужен только быстрый поиск «какой кусок закреплён за этим заказом» —
-- его делает раскрой на каждой вещи.
CREATE INDEX IF NOT EXISTS idx_repair_pieces_reserved
    ON repair_fabric_pieces (used_order_id)
    WHERE status = 'reserved';

COMMENT ON COLUMN repair_fabric_pieces.status IS
    'available — лежит в цехе и доступен всем; reserved — закреплён за заказом (used_order_id), можно открепить обратно; used — израсходован при раскрое; written_off — списан администратором.';
