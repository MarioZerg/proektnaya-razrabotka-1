-- Возврат 18 заказов WB в их настоящее состояние: они ОТГРУЖЕНЫ.
--
-- Что произошло. Поставку 1215 закрыли на стороне WB — короб уехал на маркетплейс.
-- WB перевёл её сборочные задания в состояние «выполнено» (supplierStatus=complete)
-- и убрал их из поставки: у него в ней ноль заказов.
--
-- Вчера это было прочитано как «WB выкинул задания, заказы потерялись», и заказы
-- вернули в очередь на отгрузку (накопитель 1218). Это оказалось неверно: WB считает
-- их уже отгруженными и на попытку положить в новую поставку отвечает отказом 409 —
-- ту самую ошибку и увидел кладовщик при сканировании.
--
-- Правильное состояние: заказы отгружены, поставка 1215 выполнена, вещи со склада
-- сняты. Возвращаем всё как есть на стороне WB.
UPDATE t_p86119184_proektnaya_razrabotk.wb_supply_orders w
SET supply_id = 1215
FROM t_p86119184_proektnaya_razrabotk.orders o
WHERE o.id = w.order_id AND w.supply_id = 1218
  AND o.order_number IN ('5480968018','5481065336','5483173784','5484355925','5484677298',
    '5484955042','5486555839','5486578928','5487579852','5487786540','5488895401','5489574276',
    '5489574277','5489574278','5490736616','5490736617','5490771281','5490922438');

UPDATE t_p86119184_proektnaya_razrabotk.orders
