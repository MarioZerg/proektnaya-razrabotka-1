-- Фактическое перечисление на расчётный счёт.
--
-- Зачем. Вознаграждение менеджера считалось от «начисленного» — суммы, которую
-- мы сами складывали из заказов, комиссии, услуг и логистики. Это оказалось
-- неверно по двум причинам.
--
-- Первая: менеджеру платят процент с ДЕНЕГ, пришедших на счёт, а не с валового
-- расчёта по отчёту. Она и прикрепляет отчёты о перечислениях.
--
-- Вторая: в составе услуг площадка проводит агентское вознаграждение
-- (MarketplaceServiseItemAgencyFeeForSale) — техническую проводку на миллионы,
-- которая деньгами не является. За июль она добавила +7 938 644 ₽, и итог
-- раздулся с 6,6 млн до 17,1 млн.
--
-- В детализации отчёта есть готовое поле payments — ровно сумма перевода на
-- расчётный счёт. Её и храним: она не требует наших вычислений и совпадает
-- с банковской выпиской.
ALTER TABLE marketplace_payouts
    ADD COLUMN IF NOT EXISTS transferred_amount NUMERIC(14, 2),
    ADD COLUMN IF NOT EXISTS begin_balance NUMERIC(14, 2),
    ADD COLUMN IF NOT EXISTS agency_fee NUMERIC(14, 2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN marketplace_payouts.transferred_amount IS
    'Фактически перечислено на расчётный счёт — база процента менеджера';
COMMENT ON COLUMN marketplace_payouts.agency_fee IS
    'Агентское вознаграждение: техническая проводка, деньгами не является';
