-- Статус «На сборке» — только для вещей, подобранных под заказ.
--
-- Смысл статуса: вещь снята с полки под конкретное отправление, за ней идёт кладовщик.
-- Если заказа за вещью нет, а статус «На сборке» стоит, кладовщик ищет её по списку
-- подбора и не находит — время потеряно, отправление под вопросом. Такие «зависшие»
-- вещи физически на складе не находятся, поэтому честно помечаем их утерянными.
UPDATE goods_warehouse
SET status = 'lost',
    lost_reason = COALESCE(lost_reason, 'Числилась на сборке без заказа — не найдена на складе'),
    lost_at = COALESCE(lost_at, now())
WHERE status = 'picking'
  AND reserved_order_id IS NULL;

-- Защита на уровне базы: впредь вещь физически не сможет попасть в «На сборке» без
-- заказа. Любая ошибка в коде теперь упрётся в это правило, а не разойдётся по складу.
ALTER TABLE goods_warehouse
    ADD CONSTRAINT chk_picking_requires_order
    CHECK (status <> 'picking' OR reserved_order_id IS NOT NULL);
