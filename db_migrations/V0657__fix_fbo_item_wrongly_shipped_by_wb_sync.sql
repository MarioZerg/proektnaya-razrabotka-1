-- Возвращаем в поставку FBO вещь, ошибочно помеченную отгруженной.
--
-- ЧТО ПРОИЗОШЛО. Вещь GW-723267 (Шифон 200x255) сшили под WB-заказ 5473775779,
-- покупатель его отменил, вещь легла на полку свободным остатком. Позже менеджер
-- набрал её в заявку OZON FBO 2000065880431 (поставка 1307), и она лежит в коробе
-- несобранной поставки.
--
-- 21.09 в 11:49 планировщик WB (проверка статусов) обрабатывал отмену того самого
-- старого заказа и пометил вещь отгруженной: условие поиска было
-- «order_id = заказ ИЛИ reserved_order_id = заказ», без оглядки на то, что вещь
-- давно служит другому заказу. В списке товаров поставки FBO появился статус
-- «Отгружен» посреди сборки, хотя поставка никуда не уезжала.
--
-- Причина закрыта в коде (backend/wb_fbs/index.py): теперь при наличии резерва
-- вещь принадлежит ТОЛЬКО заказу из резерва.
--
-- Здесь возвращаем запись в то состояние, в котором она должна быть: вещь ждёт
-- отгрузки в составе поставки FBO. Отметку об отгрузке снимаем — вещь физически
-- лежит в коробе у нас.
UPDATE goods_warehouse
SET status = 'awaiting_supply',
    shipped_at = NULL
WHERE id = 1607
  AND status = 'shipped'
  AND EXISTS (
      SELECT 1
      FROM marketplace_supply_items msi
      JOIN marketplace_supplies s ON s.id = msi.supply_id
      WHERE msi.goods_warehouse_id = goods_warehouse.id
        AND s.status NOT IN ('Выполнена', 'Отменена')
  );
