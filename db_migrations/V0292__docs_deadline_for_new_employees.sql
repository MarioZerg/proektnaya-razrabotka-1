-- Срок на загрузку документов для новых сотрудников.
--
-- Счётчик останавливается, когда админ проверил данные (personal_data_verified).
-- Но если сотрудник всё загрузил и ждёт проверки, а админ в отпуске — блокировать
-- человека нельзя: он свою часть выполнил. Поэтому срок замирает на момент
-- загрузки последнего скана и возобновляется только если админ документы отклонил.
ALTER TABLE users
  -- До какого момента нужно загрузить документы. NULL — срок не назначен
  -- (действующие сотрудники: требуем документы только с новых).
  ADD COLUMN IF NOT EXISTS docs_deadline TIMESTAMP,
  -- Момент, когда сотрудник загрузил полный комплект и ждёт проверки.
  -- Пока стоит эта отметка, срок не течёт — очередь за администратором.
  ADD COLUMN IF NOT EXISTS docs_submitted_at TIMESTAMP,
  -- Админ отклонил документы: причина показывается сотруднику,
  -- срок назначается заново.
  ADD COLUMN IF NOT EXISTS docs_rejected_reason TEXT,
  ADD COLUMN IF NOT EXISTS docs_rejected_at TIMESTAMP,
  -- Срок вышел, документов нет — человека возвращает на экран профиля,
  -- снять блокировку может только администратор.
  ADD COLUMN IF NOT EXISTS docs_blocked BOOLEAN NOT NULL DEFAULT false;

-- Действующим сотрудникам срок не назначаем: документы с них собираются вручную.
-- Ставим отметку, что требование к ним не относится, чтобы новая логика
-- не заблокировала людей, которые давно работают.
UPDATE users
SET docs_deadline = NULL
WHERE docs_deadline IS NULL;
