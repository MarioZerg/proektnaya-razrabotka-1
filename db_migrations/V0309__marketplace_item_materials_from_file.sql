-- Источник: файл «расходы.txt» — 56 рецептов (8 тканей x 7 ширин).
-- Рецепт задан префиксом артикула (vyal2, len8, ...): он определяет ткань и ширину,
-- а высота на расход не влияет — под один префикс попадают все высоты (220-295 см).
-- Расход ткани и тесьмы = ширина изделия + припуск (2.05 при ширине 200 см и т.д.).

-- Карточка vyal8_295 была заполнена вручную раньше и содержала пакет 35х40, тогда как
-- в файле для vyal8 указан 30х35. Переводим её на значение из файла, иначе у товара
-- оказалось бы два разных пакета сразу.
UPDATE marketplace_item_materials mim
SET material_id = 11
FROM marketplace_items mi
WHERE mi.id = mim.marketplace_item_id
  AND regexp_replace(mi.sku, '_.*$', '') = 'vyal8'
  AND mim.material_id = 12;

