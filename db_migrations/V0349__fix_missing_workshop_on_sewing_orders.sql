-- Проставляем цех заказам, которые ушли в пошив без него.
--
-- Заказы FBO попадают в пошив, минуя раскрой (ткань уже готова), и раньше цех у них
-- оставался пустым. Зарплата швеи считается по ставке ЦЕХА ЗАКАЗА: нет цеха — нет
-- ставки — начисление молча не создаётся. Привезенцева Елена отшила 23 заказа
-- 10.08 и не получила за них ничего, а в отчётах выглядела как «не работавшая».
--
-- Причина уже устранена в коде (цех проставляется при взятии заказа в работу).
-- Здесь чиним заказы, которые успели уйти в пошив до исправления: берём штатный
-- цех самой швеи. Начисление создастся штатно, когда упаковщик закроет заказ.
--
-- Трогаем ТОЛЬКО незакрытые заказы (пошив ещё не оплачен): у закрытых заказов
-- зарплата уже посчитана, и смена цеха задним числом исказила бы историю.

UPDATE orders o
SET workshop_id = w.id
FROM users u
JOIN workshops w ON w.name = u.workshop
WHERE o.assigned_user_id = u.id
  AND o.workshop_id IS NULL
  AND o.sewing_status IN ('В работе', 'Стикеровка');
