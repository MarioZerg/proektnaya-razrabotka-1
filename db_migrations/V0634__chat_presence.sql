-- Кто сейчас в чате и кто набирает сообщение.
--
-- Без этого чат выглядел мёртвым: человек написал вопрос и не понимает, есть ли
-- вообще кто-то на смене у планшета — ждать ответ или идти в цех ногами. Теперь
-- видно и тех, кто смотрит в чат, и тех, кто прямо сейчас печатает ответ.
--
-- Отметка ставится тем же запросом, которым чат забирает новые сообщения, —
-- отдельных обращений к серверу «я тут» не появляется, а они оплачиваются.
CREATE TABLE chat_presence (
    user_id INTEGER PRIMARY KEY REFERENCES users(id),
    -- Когда чат последний раз спрашивал новые сообщения. Свежая отметка — человек в сети.
    last_seen_at TIMESTAMP NOT NULL DEFAULT now(),
    -- Когда в поле ввода последний раз печатали. Живёт несколько секунд и гаснет само:
    -- отдельного «перестал печатать» нет, иначе закрытая вкладка оставила бы
    -- вечное «Лена печатает...».
    typing_at TIMESTAMP NULL
);

-- Список «в сети» читается при каждом опросе чата, поэтому отбор по времени
-- должен идти по индексу, а не перебором всей таблицы.
CREATE INDEX idx_chat_presence_last_seen ON chat_presence (last_seen_at DESC);
