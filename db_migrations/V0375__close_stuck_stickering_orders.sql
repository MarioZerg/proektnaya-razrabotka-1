-- Два заказа подвисли на стикеровке: кладовщик забрал вещи и застикеровал их вручную,
-- мимо терминала, поэтому система не довела их до «Готовых».
--
--   77281 «70527570-1291-5» (FBS, Шаркунова) — на OZON уже в доставке, вещь уехала.
--   77923 «119959612-102»   (FBO, Морозова)  — лежит в поставке FBO №1167.
--
-- Доводим их вручную ровно так, как это делает терминал стикеровки.

-- 1. Дата сдачи вещи швеёй. Обычно её ставит терминал, здесь она осталась пустой —
--    а по ней считается метраж швеи в зарплатном отчёте. Без неё работа за август
--    просто не попала бы в расчёт. Берём момент раскроя как нижнюю границу — вещь
--    сшита позже него, но в том же периоде.
UPDATE orders SET sewn_at = COALESCE(sewn_at, now()) WHERE id IN (77281, 77923);

-- 2. Переводим в «Готовые».
UPDATE orders SET sewing_status = 'Готовые' WHERE id IN (77281, 77923);

-- 3. FBS-заказ уже едет к покупателю (ozon_status = delivering) — закрываем его как
--    отгруженный, чтобы он не ждал сканирования в поставку, которого не будет.
UPDATE orders
SET status = 'Отгружен', completed_at = COALESCE(completed_at, now())
WHERE id = 77281 AND status <> 'Отменён';

-- 4. Зарплата швеям за пошив: терминал начисляет её в момент стикеровки, здесь этот
--    шаг обошли, и женщины остались без денег за реально сделанную работу.
--    Ставки взяты из тарифов цеха №1 по ширине изделия, как в обычном расчёте.
INSERT INTO salary_accruals (user_id, type, amount, order_id, description)
VALUES
  (21, 'sewer_piece', 51.00, 77281, 'Пошив заказа #70527570-1291-5 (200 см)'),
  (20, 'sewer_piece', 89.20, 77923, 'Пошив заказа #119959612-102 (400 см)')
ON CONFLICT (order_id, type) WHERE order_id IS NOT NULL DO NOTHING;
