-- Индекс под самую частую проверку склада: «эта вещь уже в активной поставке?»
--
-- ЗАЧЕМ. Условие NOT EXISTS (... JOIN marketplace_supplies ms ... WHERE
-- ms.status NOT IN ('Выполнена','Отменена')) встречается в коде складa больше
-- десяти раз: в списке вещей, в подборе под заказ, в карточке товара, в разборе
-- зависших. Оно выполняется на КАЖДУЮ строку списка.
--
-- Фильтр идёт по статусу поставки, а индекса по статусу не было вовсе — базе
-- приходилось лезть в таблицу за статусом для каждой проверки. Активных
-- поставок единицы, завершённых — сотни, поэтому частичный индекс по активным
-- получается крошечным и отвечает мгновенно.
CREATE INDEX IF NOT EXISTS idx_supplies_active
    ON marketplace_supplies (id)
    WHERE COALESCE(status, '') NOT IN ('Выполнена', 'Отменена');

ANALYZE marketplace_supplies;
