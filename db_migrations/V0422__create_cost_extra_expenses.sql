-- ДОПОЛНИТЕЛЬНЫЕ РАСХОДЫ НА ЕДИНИЦУ ТОВАРА.
--
-- Кроме ткани и сдельной работы цеха есть траты, которые нельзя привязать к
-- конкретной вещи напрямую, но которые всё равно в ней сидят:
--
--   «Коробка для отправки»   — 250 ₽ на 30 вещей;
--   «Зарплата кладовщика»    — 60 000 ₽ на 4000 вещей в месяц;
--   «Зарплата менеджера»     — 50 000 ₽ на 4000 вещей;
--   «Уборщица»               — 20 000 ₽ на 4000 вещей.
--
-- Владелец сам решает, что и на сколько штук делить: система эти числа вывести не
-- может. Поэтому храним как список строк, где у каждой — название, сумма и делитель.
-- На себестоимость одной вещи ложится amount / per_items.
--
-- Раньше для этого было одно поле overhead_per_item в cost_settings: владельцу
-- приходилось считать всю сумму в уме и вбивать итог, а из чего он сложился —
-- нигде не оставалось. Теперь каждая статья видна отдельно и правится по одной.
CREATE TABLE IF NOT EXISTS cost_extra_expenses (
    id SERIAL PRIMARY KEY,
    -- Что это за расход: «Коробка на отправку», «Зарплата кладовщика».
    name TEXT NOT NULL,
    -- Сколько денег, руб.
    amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    -- На сколько штук товара делим. Меньше 1 быть не может.
    per_items INTEGER NOT NULL DEFAULT 1 CHECK (per_items >= 1),
    -- Пояснение для себя: «оклад 60 000 при плане 4000 штук в месяц».
    note TEXT,
    -- Выключенная строка остаётся в списке, но в расчёт не идёт: сезонные траты
    -- удобнее гасить, чем удалять и заводить заново.
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);
