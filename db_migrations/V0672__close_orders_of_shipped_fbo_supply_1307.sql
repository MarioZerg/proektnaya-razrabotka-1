-- Закрываем заказы уехавшей FBO-заявки 2000065880431 (supply_id = 1307).
--
-- ЧТО СЛУЧИЛОСЬ. Заявку отгрузили на OZON и закрыли 25.09, но её 216 заказов
-- остались в статусе «Новый». Закрытие заявки идёт ОТ СТРОК СОСТАВА
-- (marketplace_supply_items), а к тому моменту состав был почти пуст: при каждом
-- сканировании вещи в короб система удаляет строки состава уже выполненных
-- поставок, и за две недели от 216 строк осталась одна.
--
-- Вторая половина проблемы: у 179 заказов стоял sewing_status = 'Со склада' без
-- ссылки на вещь. Такой заказ невидим с обеих сторон — в цех не уходит (статус не
-- «Новый»), в подборе не показывается (вещи нет). Именно они всплывали на панели
-- администратора как «зависшие отправления», по одному, по мере работы склада.
--
-- ПОЧЕМУ ЗАКРЫВАЕМ, А НЕ ВОЗВРАЩАЕМ В ЦЕХ. Товар физически уехал на склад OZON
-- 25.09. Вернуть заказы в пошив значит раскроить ткань и сшить второй экземпляр
-- того, что уже отгружено, — потраченный материал и работа цеха впустую.
--
-- Дата закрытия — 25.09.2026 14:27, момент фактического закрытия заявки
-- (marketplace_supplies.completed_at), а не сегодняшняя: иначе отчёты по
-- отгрузкам покажут заказы в неверном периоде.

UPDATE t_p86119184_proektnaya_razrabotk.orders o
SET status = 'Отгружен',
    completed_at = COALESCE(o.completed_at, s.completed_at),
    -- Заказы «Со склада» без вещи приводим к честному виду: вещь их больше не
    -- держит, а заказ закрыт отгрузкой заявки.
    fulfilled_from_stock_id = NULL
FROM t_p86119184_proektnaya_razrabotk.marketplace_supplies s
WHERE s.id = o.supply_id
  AND o.supply_id = 1307
  AND COALESCE(s.status, '') = 'Выполнена'
  AND COALESCE(o.status, '') NOT IN ('Отгружен', 'Доставлен', 'Отменён');
