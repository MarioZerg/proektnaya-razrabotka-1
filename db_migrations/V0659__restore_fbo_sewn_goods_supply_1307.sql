-- Восстанавливаем складские записи FBO-вещей, сшитых в цехе под заявку 1307.
--
-- ЧТО ПРОИЗОШЛО. Терминал упаковщицы при закрытии заказа заводил складскую
-- запись только для FBS ("elif order_type == 'FBS'"). Заказ, сшитый в цехе ПОД
-- ЗАЯВКУ FBO, проходил раскрой, пошив и стикеровку, уходил в «Готовые» — а
-- записи о вещи на складе не создавалось вовсе.
--
-- Из-за этого кладовщик сканировал ярлык OZN в короб и получал «на складе нет
-- свободных вещей этого товара»: система искала вещь среди лежащих на полках,
-- а сшитой в цехе для неё не существовало. Так зависли 34 заказа заявки
-- 2000065880431 (Ярославль), включая 2000065880431-217 (Мрамор 700x255).
--
-- Причина закрыта в коде (backend/kiosk/index.py): FBO теперь заводит запись
-- наравне с FBS.
--
-- Здесь восстанавливаем то, что должен был создать терминал в момент
-- стикеровки. Вещи физически лежат в цехе в контейнере.
--
-- Берём ТОЛЬКО активную заявку 1307. Поставки 1167 и 1168 уже выполнены —
-- их вещи давно уехали на площадку, и заводить их на склад сейчас значило бы
-- создать товар, которого нет.
--
-- Статус 'awaiting_supply' — вещь не на полке, а «на поставку»: ждёт, когда
-- кладовщик отсканирует её в короб.
-- shipping_labeled_at — ярлык OZN упаковщица наклеила при стикеровке.
-- reserved_order_id — закрепляем вещь за своим заказом заявки, иначе товар
-- FBO обезличен и в короб могла бы уйти соседняя штука того же артикула.
INSERT INTO goods_warehouse (
    order_id, reserved_order_id, status, storage_barcode,
    receive_reason, shipping_labeled_at, matched_at, received_at
)
SELECT
    o.id,
    o.id,
    'awaiting_supply',
    'GW-' || lpad(nextval('goods_warehouse_id_seq')::text, 6, '0'),
    'fbs_ready',
    o.packed_at,
    o.packed_at,
    o.packed_at
FROM orders o
WHERE o.supply_id = 1307
  AND o.order_type = 'FBO'
  AND o.sewing_status = 'Готовые'
  AND o.packed_at IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM goods_warehouse g WHERE g.order_id = o.id);
