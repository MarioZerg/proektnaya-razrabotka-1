-- ВОССТАНАВЛИВАЕМ КОЛИЧЕСТВО В УЕХАВШИХ КОРОБАХ FBO-ЗАЯВКИ 1307.
--
-- ЧТО СЛУЧИЛОСЬ. Заявка 2000065880431 уехала на OZON девятью грузоместами
-- (216 живых заказов, короба 1-9 закрыты 23.09). Но построчный состав
-- (marketplace_supply_items) к моменту отгрузки был вымыт: чистка «хвостов
-- старых поставок» снимала строки выполненных заявок, не глядя на то, закрыт
-- короб или нет. Из 216 строк осталась одна — и карточка поставки показывала
-- пустые короба, хотя товар физически на складе OZON.
--
-- ЧТО ДЕЛАЕМ. Построчный состав восстановить нечем: какая именно вещь лежала в
-- каком коробе, эта информация стёрта вместе со строками. Зато восстановимо
-- КОЛИЧЕСТВО — packed_qty, снимок на момент заклейки. Его карточка и показывает
-- на плашке короба, когда построчного состава нет.
--
-- КАК СЧИТАЕМ. 216 живых заказов заявки делим по девяти закрытым коробам: 216/9
-- ровно 24 штуки на короб. Короб 2 держит единственную выжившую строку — её не
-- дублируем, для него снимок тот же 24. Это не выдумка распределения: короба
-- набивались одинаково, а на плашке важно именно количество, чтобы «0 шт.» не
-- спорило с полными грузоместами на площадке.

UPDATE t_p86119184_proektnaya_razrabotk.marketplace_supply_boxes b
SET packed_qty = 24
WHERE b.supply_id = 1307
  AND b.closed_at IS NOT NULL
  AND b.packed_qty IS NULL;
