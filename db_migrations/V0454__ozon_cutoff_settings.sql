-- Настройки отсечки OZON: после указанного времени заказы OZON уходят в конец очереди.
--
-- Машина на ПВЗ уезжает раз в день (12:30), и вещь, сшитая позже отсечки, на неё уже
-- не попадёт — пролежит до завтра. Заказы WB и Яндекса от этой машины не зависят,
-- поэтому во второй половине дня выгоднее сначала закрывать именно их.
--
-- Это ПОРЯДОК, а не запрет: если заказов WB и Яндекса нет, цех продолжает шить OZON
-- как обычно — простоя не возникает.
--
-- По умолчанию правило ВЫКЛЮЧЕНО: включает и настраивает администратор в карточке цеха,
-- чтобы изменение не поменяло работу цехов внезапно.
INSERT INTO system_settings (key, value)
VALUES ('ozon_cutoff_enabled', 'false')
ON CONFLICT (key) DO NOTHING;

INSERT INTO system_settings (key, value)
VALUES ('ozon_cutoff_time', '11:00')
ON CONFLICT (key) DO NOTHING;
