-- ВОЗВРАТ РУЛОНА 2-004033 В РАБОТУ.
--
-- Рулон был закрыт проверочным вызовом при поиске причины, по которой цех не мог
-- закрывать рулоны. Проверка подтвердила, что починка работает, но сам рулон
-- закрывать было нельзя: решение о закрытии и о недостаче принимает швея.
-- Возвращаем его ровно в то состояние, в котором он был до проверки.
--
-- shortage_quantity не обнуляем в NULL: у столбца стоит NOT NULL, а до проверки
-- там был ноль — недостачу по рулону никто не заявлял.
UPDATE rolls
SET status = 'in_workshop',
    completed_at = NULL,
    shortage_quantity = 0,
    remaining_at_close = NULL,
    closed_by_user_id = NULL,
    closed_by_name = NULL,
    remaining_quantity = 33.650
WHERE id = 4033;
