-- В системе маркетплейс Яндекса кодируется как 'Yandex' (так его ждут фильтры и цветовые
-- метки в интерфейсе). Тестовые заказы были созданы с русским названием — приводим к
-- единому виду, чтобы они корректно отображались и фильтровались.
UPDATE orders SET marketplace = 'Yandex' WHERE marketplace = 'Яндекс';
