-- Компенсации площадки в базе начисления менеджера.
--
-- Что это. Площадка возмещает продавцу деньги: за потерянный или испорченный
-- товар, за брак по своей вине, выкупает невозвратные позиции. Это выручка,
-- она приходит на расчётный счёт — значит, входит в базу вознаграждения.
--
-- Почему отдельным полем. В недельном отчёте компенсации сидят внутри общих
-- статей, отделить их там нельзя. Зато они видны в списке операций как
-- отдельные типы. Собираем их оттуда и храним рядом с выплатой — так в отчёте
-- менеджера видно, сколько из базы пришло компенсациями.
ALTER TABLE marketplace_payouts
    ADD COLUMN IF NOT EXISTS compensation_amount NUMERIC(14, 2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN marketplace_payouts.compensation_amount IS
    'Компенсации и выкупы площадкой за период: возмещения за утерю, брак '
    'и порчу товара. Входят в базу вознаграждения менеджера';

ALTER TABLE manager_accruals
    ADD COLUMN IF NOT EXISTS compensation_amount NUMERIC(14, 2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN manager_accruals.compensation_amount IS
    'Сколько в базе начисления пришло компенсациями площадки';
