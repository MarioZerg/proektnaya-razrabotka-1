-- ТЕСТОВЫЙ ЦЕХ ДЛЯ ПРОВЕРКИ ТЕРМИНАЛА И РУЛОНОВ.
--
-- Отдельный цех, а не реальные №1/№2: любые проверки движения материала и заказов
-- идут по своим рулонам и своим заказам. На боевые остатки, зарплату и поставки
-- это не влияет никак — всё фильтруется по workshop_id.
--
-- Признак «тестовый» зашит прямо в имя: если такой цех однажды всплывёт в отчёте,
-- сразу видно, что это не производство.

INSERT INTO workshops (name)
SELECT 'Тестовый цех (QA)'
WHERE NOT EXISTS (SELECT 1 FROM workshops WHERE name = 'Тестовый цех (QA)');
