-- РАЗОВАЯ ПРЕМИЯ сотруднику: назначенная сумма, которая падает на баланс в
-- конкретный день и БОЛЬШЕ НИКОГДА не повторяется.
--
-- Почему отдельная таблица, а не ручное начисление в день X: премию обещают
-- заранее и показывают сотруднику виджетом с таймером, а деньги должны прийти
-- ровно в назначенную дату, даже если в этот день администратора нет на месте.
-- Планировщика у платформы нет, поэтому начисление выполняется при обращении к
-- зарплатной функции в день выплаты (так же, как месячная премия швей).
--
-- От повторного начисления защищает paid_at: он проставляется тем же UPDATE,
-- который выбирает строки к оплате (UPDATE ... WHERE paid_at IS NULL RETURNING),
-- поэтому параллельные обращения не смогут заплатить дважды.
CREATE TABLE IF NOT EXISTS one_time_awards (
    id SERIAL PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    -- Ключ акции: одна премия на сотрудника в рамках одной акции.
    award_key VARCHAR(60) NOT NULL,
    title VARCHAR(200) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    -- Дата, когда деньги должны упасть на баланс (по Москве).
    pay_on DATE NOT NULL,
    -- За что премия: список достижений для карточки на главной (JSON-массив строк).
    highlights JSONB NOT NULL DEFAULT '[]'::jsonb,
    -- Заполняется в момент начисления. Пока пусто — премия ещё впереди, виджет
    -- висит с таймером. Проставлено — виджет исчезает, деньги в балансе.
    paid_at TIMESTAMP NULL,
    accrual_id INTEGER NULL REFERENCES salary_accruals(id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (user_id, award_key)
);

CREATE INDEX IF NOT EXISTS idx_one_time_awards_pending
    ON one_time_awards (pay_on) WHERE paid_at IS NULL;

