-- Возвращаем в общую очередь 7 заказов, которые я взял на швею при проверке перехода
-- между цехами. Реально их никто не раскраивал — снимаем исполнителя и возвращаем
-- статус «Новый», чтобы заказы снова были доступны всем.
UPDATE orders
SET sewing_status = 'Новый', assigned_user_id = NULL, taken_at = NULL
WHERE id IN (54, 55, 944, 963, 977, 1074, 1076)
  AND assigned_user_id = 3
  AND sewing_status = 'На раскрое';