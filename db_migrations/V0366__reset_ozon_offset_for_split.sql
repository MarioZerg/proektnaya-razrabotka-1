-- Сбрасываем указатель загрузки OZON FBS, чтобы новый механизм деления отправлений
-- прошёл по списку с начала.
--
-- Многотоварные отправления, загруженные ДО появления деления, остаются неразделёнными:
-- делить их задним числом нельзя — часть вещей уже в работе, а деление необратимо.
-- Новые же отправления с этого момента будут разбиваться на отдельные посылки,
-- каждая со своим номером от OZON.
UPDATE system_settings SET value = '0', updated_at = now()
WHERE key = 'ozon_sync_offset';
