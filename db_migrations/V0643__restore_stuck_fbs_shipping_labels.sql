-- Возврат в отгрузку FBS-вещей, у которых потерялась отметка о ярлыке отправления.
--
-- ЧТО СЛУЧИЛОСЬ.
--
-- Вещь, сшитая под FBS-заказ, выходит из цеха уже заклеенной ярлыком покупателя:
-- у такой складской записи receive_reason='fbs_ready' и проставлен
-- shipping_labeled_at. Отметку могли снять при разборе/удалении поставки или при
-- отмене, которая потом не подтвердилась. Ярлык при этом физически остался на
-- пакете, но система считала вещь неотстикерованной.
--
-- Дальше начиналась мёртвая петля. В поставку вещь не сканировалась — система
-- говорила «ярлык не наклеен». В очередь стикеровки заказ не возвращался:
-- отправление на площадке уже в статусе awaiting_deliver («ожидает отгрузки»), и
-- второй ярлык OZON не выдаёт. Терминал предлагал сдать вещь на склад и печатал
-- складской стикер GW — живое отправление уезжало на полку хранения, а заказ
-- висел «готов к отгрузке» до просрочки.
--
-- Причины устранены в коде (см. keep_fbs_label, восстановление отметки при скане
-- в поставку и запрет сдавать FBS-вещь на склад). Здесь возвращаем в работу те
-- вещи, которые уже застряли.
--
-- Трогаем только заведомо живые отправления: заказ не отменён, не отгружен, не
-- доставлен и не уехал к покупателю. Статус 'awaiting_supply' означает «ярлык
-- наклеен, вещь ждёт короба» — ровно то, что происходит с ней физически.
UPDATE goods_warehouse gw
SET shipping_labeled_at = COALESCE(gw.shipping_labeled_at, now()),
    status = 'awaiting_supply',
    -- Полка такой вещи не нужна: она лежит не на стеллаже, а в контейнере
    -- к отгрузке. Оставленная полка делала бы её видимой как свободный остаток.
    shelf_id = NULL
FROM orders ro
WHERE ro.id = COALESCE(gw.reserved_order_id, gw.order_id)
  AND COALESCE(gw.receive_reason, '') = 'fbs_ready'
  AND gw.shipping_labeled_at IS NULL
  AND gw.shipped_at IS NULL
  AND gw.status NOT IN ('lost', 'to_dispose', 'shipped')
  AND COALESCE(ro.order_type, '') = 'FBS'
  AND COALESCE(ro.status, '') NOT IN ('Отменён', 'Отгружен', 'Доставлен')
  AND COALESCE(ro.ozon_status, '') NOT IN
      ('delivering', 'delivered', 'cancelled', 'not_accepted', 'driver_pickup')
  AND COALESCE(ro.ym_status, '') NOT ILIKE 'cancel%';
