-- Снимаем замки, оставшиеся от отладки выгрузки продаж.
--
-- Замок делает шаг цепочки неповторимым и живёт полчаса. Во время настройки
-- трёхмесячной выгрузки шаги запускались вручную, и теперь эти метки мешают
-- запустить сбор начисто: система считает работу уже выполненной.
--
-- Сдвигаем их в прошлое — обычная уборка по времени сотрёт их при первом же
-- запуске, а новая цепочка пойдёт с чистого листа.
UPDATE sync_chain_lock
SET started_at = now() - interval '2 hours'
WHERE job = 'ozon_sales';
