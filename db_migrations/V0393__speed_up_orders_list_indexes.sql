-- Ускоряем список заказов — самый тяжёлый запрос в системе (2,2–2,6 секунды).
--
-- Что тормозит: для КАЖДОЙ строки списка (а их около 800) выполняется подзапрос
-- «сколько ткани уходит на изделие» — он ищет карточку товара по связке
-- материал + ширина + высота. Индекса на эту связку нет, поэтому каждый раз
-- перебирается вся таблица товаров (875 строк). Итого около 700 000 лишних
-- сравнений на один показ списка заказов.
--
-- Список заказов открывается при каждом заходе на главную и на страницу заказов,
-- то есть сотни раз в день — это главный расход вычислительного времени.
CREATE INDEX IF NOT EXISTS idx_marketplace_items_material_size
    ON marketplace_items (material, width, height);

-- Тот же подзапрос джойнит состав изделия по товару — ускоряем и его.
CREATE INDEX IF NOT EXISTS idx_mim_item
    ON marketplace_item_materials (marketplace_item_id);

-- Свежая история заказов: CTE recent_closed каждый раз сортирует закрытые заказы
-- по убыванию номера. Частичный индекс покрывает ровно этот случай.
CREATE INDEX IF NOT EXISTS idx_orders_closed_recent
    ON orders (id DESC)
    WHERE sewing_status IN ('Готовые', 'Со склада');

-- Расход материала по рулону (карточка рулона, проверка недостачи на терминале).
CREATE INDEX IF NOT EXISTS idx_omu_roll
    ON order_material_usage (roll_id);
