-- Откат тестовой стикеровки GW-726091.
--
-- При проверке нового сканера подбора я отметил на этой вещи ярлык отправления.
-- Физически ярлык никто не печатал и не клеил, а кладовщик увидел бы вещь в
-- списке «ждёт отправки на поставку» и искал бы несуществующую наклейку.
-- Возвращаем вещь в обычный подбор: заказ за ней сохраняется.
UPDATE goods_warehouse
SET shipping_labeled_at = NULL,
    shipping_labeled_by = NULL,
    shipping_labeled_by_name = NULL
WHERE storage_barcode = 'GW-726091'
  AND shipped_at IS NULL;
