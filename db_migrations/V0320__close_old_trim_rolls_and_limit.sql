-- 1. Закрываем старые коробки тесьмы 6 см, оставляем две самые свежие по дате.
--
-- В цехе висели шесть открытых коробок тесьмы 6 см, из них четыре давно закрыты
-- физически — они только засоряли швеям список выбора. По решению владельца
-- оставляем строго по дате: 2-004702 (20.07) и 2-004679 (17.07, целая 1500 м).
--
-- Остатки списываем в недостачу: коробок физически нет, а остаток по ним числился.
-- Отдельно отмечаем, что решение по недостаче уже принято (penalty_total = 0) —
-- иначе они всплывут очередью штрафов на дашборде.
UPDATE rolls
SET status = 'completed',
    completed_at = now(),
    shortage_quantity = remaining_quantity,
    remaining_quantity = 0,
    penalty_total = 0,
    closed_by_name = 'Инвентаризация'
WHERE id IN (4024, 4666, 4667, 4677)
  AND status = 'in_workshop';

-- 2. Лимит открытых коробок тесьмы на смену.
--
-- Швеи могут держать в работе не больше двух коробок КАЖДОГО вида тесьмы на цех+смену:
-- пока не закроют одну, третью принимать нельзя. Иначе коробки копятся вскрытыми,
-- остатки теряются, а список выбора превращается в свалку.
INSERT INTO t_p86119184_proektnaya_razrabotk.system_settings (key, value)
VALUES ('max_open_trim_rolls_per_shift', '2')
ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
