-- Закрываем зависшие вещи, отстикерованные, но не отправленные на поставку.
--
-- В окне «Сборка товара с полок» не было завершающего шага: кладовщик печатал стикер
-- отправления, закрывал окно — и вещь навсегда оставалась в статусе «На сборке».
-- Работа выглядела незакрытой, а кладовщик видел товары, которые давно собраны.
--
-- Кнопку «Готово — на поставку» добавили. Здесь доводим до конца те вещи, что уже
-- отстикерованы: ярлык маркетплейса на них наклеен, значит они собраны и ждут поставку.
UPDATE goods_warehouse
SET status = 'awaiting_supply'
WHERE status = 'picking'
  AND shipping_labeled_at IS NOT NULL
  AND reserved_order_id IS NOT NULL;
