-- Признак демонстрационного аккаунта.
--
-- Демо-сотрудник нужен только для кнопки тестового входа администратора: на нём
-- смотрят, как выглядит система глазами роли. Работать он не работает, зарплату
-- не получает, смены не открывает.
--
-- Без явной пометки такой аккаунт попадал бы во все рабочие списки — управление
-- сменами, зарплатную ведомость, отчёты по выработке — и мешался бы там как
-- «сотрудник, который никогда ничего не делает». Флагом мы его оттуда убираем,
-- оставляя только там, где он и нужен: в списке тестовых входов.
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_demo BOOLEAN NOT NULL DEFAULT false;

UPDATE users SET is_demo = true WHERE login = 'demo_sewer_overlock';