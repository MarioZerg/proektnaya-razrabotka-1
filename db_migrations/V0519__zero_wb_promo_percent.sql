-- Обнуляем запасной процент рекламы по Wildberries.
--
-- Предыдущая правка выключила расчёт по факту, но в поле «Продвижение, %»
-- осталось запасное значение 10% — и расчёт честно продолжил снимать его с
-- каждой вещи: 217 ₽ с «Бамбука 200».
--
-- Запасное значение нужно, когда площадка ещё не отдала факт. Здесь другой
-- случай: рекламы нет вовсе, и правильная цифра — ноль.
UPDATE marketplace_tariffs
SET promo_percent = 0,
    updated_at = now()
WHERE marketplace_code = 'wildberries';
