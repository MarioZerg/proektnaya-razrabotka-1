-- Запоминаем операцию генерации этикетки короба на стороне OZON.
--
-- ЗАЧЕМ. Этикетка у OZON готовится асинхронно: /v1/cargoes-label/create
-- возвращает operation_id, а файл появляется через несколько секунд.
--
-- Раньше КАЖДОЕ нажатие «Получить этикетку» создавало НОВУЮ операцию и тут же
-- проверяло её один раз — она, разумеется, была ещё IN_PROGRESS. Кладовщик жал
-- снова, снова создавалась новая операция, и так по кругу: файл не забирался
-- никогда, а частые вызовы упирались в лимит частоты OZON (ошибка 429).
--
-- Теперь operation_id сохраняется: повторное нажатие ПРОВЕРЯЕТ уже запущенную
-- операцию вместо создания новой. Это и даёт файл, и не бьётся о лимит.
ALTER TABLE marketplace_supply_boxes
    ADD COLUMN IF NOT EXISTS ozon_label_operation_id TEXT;

COMMENT ON COLUMN marketplace_supply_boxes.ozon_label_operation_id IS
    'operation_id генерации этикетки в OZON. Позволяет дождаться готовности файла за несколько заходов, не плодя операции.';
