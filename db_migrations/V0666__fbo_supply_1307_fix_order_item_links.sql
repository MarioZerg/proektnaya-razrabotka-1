-- ПОСТАВКА FBO #1307: чиним односторонние связи «заказ ↔ вещь».
--
-- ЧТО БЫЛО. 11 заказов-штук заявки OZON 2000065880431 висят в статусе «Новый»,
-- хотя их вещи давно лежат в заклеенных коробах и уехали с поставкой.
--
-- ПОЧЕМУ ТАК ВЫШЛО. Товар FBO обезличен: в короб годится любая вещь нужного
-- артикула. Кладовщик сканировал вещи, сшитые когда-то под ОТМЕНЁННЫЕ
-- отправления FBS и лежавшие на полке свободным остатком. При таком скане
-- система привязывала вещь к заказу-штуке заявки, но только с ОДНОЙ стороны:
-- в вещь писала «ты едешь под заказ N», а самому заказу об этом не сообщала.
--
-- Пример: заказ 2000065880431-74 (Мрамор 200x250) — вещь GW-724535 лежит в
-- коробе №3, закрытом 21.09, поле reserved_order_id у неё заполнено, а у
-- заказа fulfilled_from_stock_id пустой и статус «Новый».
--
-- ЧЕМ ЭТО МЕШАЛО:
--   * прогресс пошива врал: 205 из 216 вместо честных 216 из 216;
--   * заказ формально числился недоделанным — от повторного раскроя его
--     спасала лишь защита «на заказ уже закреплена вещь»;
--   * на экране состава поставки товар был в коробе, а заказ «не начат».
--
-- Причина устранена в backend/marketplace_supplies: скан в короб FBO теперь
-- проставляет связь с обеих сторон. Здесь до+чиняем то, что уже накопилось.
--
-- ЧТО ДЕЛАЕМ. Закрываем заказ той вещью, которая реально за ним закреплена и
-- лежит в коробе этой же поставки: ставим ссылку и статус «Со склада».
-- Фактически работа выполнена — не встала только отметка.
UPDATE orders o
SET fulfilled_from_stock_id = g.id,
    sewing_status = 'Со склада'
FROM goods_warehouse g
JOIN marketplace_supply_items msi ON msi.goods_warehouse_id = g.id
WHERE g.reserved_order_id = o.id
  -- Вещь лежит в коробе ТОЙ ЖЕ поставки, что и заказ.
  AND msi.supply_id = o.supply_id
  AND msi.box_id IS NOT NULL
  AND o.supply_id = 1307
  AND o.fulfilled_from_stock_id IS NULL
  -- Работу цеха не переписываем: раскроенное и сшитое идёт своим путём.
  AND o.sewing_status = 'Новый'
  AND COALESCE(o.status, '') <> 'Отменён';
