-- РАЗВОДИМ ПО ВРЕМЕНИ ВЕЩИ, КОТОРЫЕ ШВЕЯ ДЕРЖИТ В РАБОТЕ ОДНОВРЕМЕННО.
--
-- Время на пошив считается по ширине изделия (timeout_200…800) от момента взятия.
-- Швея берёт два заказа почти подряд, ширина у них часто одна и та же — значит и
-- таймеры кончаются практически в одну секунду. Обе вещи становятся «готовы к сдаче»
-- одновременно, швея жмёт две кнопки подряд, и на стикеровку прилетает пачка. Участок
-- стикеровки получает рывок вместо ровного потока.
--
-- Поэтому каждой следующей вещи, взятой сверх уже имеющихся в работе, добавляем
-- фиксированный сдвиг: первая вещь идёт со своим временем по ширине, вторая — со
-- своим плюс сдвиг, третья — плюс два сдвига. Номер вещи «на руках» фиксируем прямо
-- в заказе на момент взятия, чтобы отсчёт не прыгал, когда соседняя вещь уже сдана.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS sew_stagger_index INTEGER NOT NULL DEFAULT 0;

-- Размер сдвига в МИНУТАХ. Настраивается глобально и переопределяется по цеху,
-- как и остальные тайминги пошива. 0 — сдвиг выключен, всё как раньше.
INSERT INTO system_settings (key, value) VALUES ('sewing_stagger_minutes', '5')
ON CONFLICT (key) DO NOTHING;