-- Индекс под проверку остатка материала в цехе при взятии заказа в работу.
--
-- ЧТО БЫЛО. Перед выдачей заказа система проверяет, хватает ли в цехе
-- материалов на этот товар. Запрос суммирует остаток по рулонам, а
-- существующие индексы (по одному только material_id или status) для него не
-- подходили: в таблице 4800 рулонов, и каждая такая проверка занимала около
-- секунды. Материалов на товар до трёх — три секунды на ровном месте, из-за
-- чего функция не укладывалась в свой лимит и швея не могла взять заказ.
--
-- Индекс частичный: в цехе лежит 136 рулонов из 4800, и только они интересны
-- этой проверке. Остальные в индекс не попадают — он остаётся крошечным.
CREATE INDEX IF NOT EXISTS idx_rolls_workshop_stock
    ON rolls (material_id, workshop_id)
    INCLUDE (remaining_quantity)
    WHERE status = 'in_workshop'
      AND remaining_quantity > 0
      AND defect_flagged_at IS NULL
      AND accepted_at IS NOT NULL;
