-- Возвращаем две вещи в рабочее состояние после ПРОВЕРКИ сканера поставки.
--
-- Проверяя добавление в короб, я отсканировал вещи GW-723759 (заказ 29626990-0586-1)
-- и GW-723815 (заказ 72037003-0023-1) и сразу убрал их обратно — физически в короб их
-- никто не клал. Штатная отмена позиции вернула вещи на полку: сняла ярлык, связь с
-- заказом и статус.
--
-- Но вещи РЕАЛЬНО отстикерованы и лежат у кладовщика, а оба отправления живы на OZON
-- (проверено напрямую: статус awaiting_deliver — ждут отгрузки). Возвращаем им то
-- состояние, в котором они были: ярлык наклеен, заказ закреплён, статус «ждёт поставки».
UPDATE goods_warehouse
SET status = 'awaiting_supply',
    reserved_order_id = 81586,
    shipping_labeled_at = '2026-08-15 14:10:00.952411',
    matched_at = COALESCE(matched_at, now())
WHERE id = 2169;

UPDATE goods_warehouse
SET status = 'awaiting_supply',
    reserved_order_id = 81626,
    shipping_labeled_at = '2026-08-15 13:49:33.894033',
    matched_at = COALESCE(matched_at, now())
WHERE id = 2225;

-- Связь обязана быть ВЗАИМНОЙ: заказ тоже указывает на свою вещь, иначе она снова
-- выпадет из работы как «осиротевшая». И заказ закрывается складом, а не пошивом —
-- иначе цех сошьёт второй экземпляр на то же отправление.
UPDATE orders SET fulfilled_from_stock_id = 2169, sewing_status = 'Со склада'
WHERE id = 81586;

UPDATE orders SET fulfilled_from_stock_id = 2225, sewing_status = 'Со склада'
WHERE id = 81626;
