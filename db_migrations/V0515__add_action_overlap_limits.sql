-- Защита от наложения акций и равномерное распределение.
--
-- Две проблемы, которые надо закрыть.
--
-- ПЕРВАЯ — наложение. Товар может участвовать в нескольких акциях сразу, и
-- скидки складываются: цена уходит ниже расчётной, а прибыль превращается в
-- убыток задним числом. Сейчас в «Эластичном бустинге» уже 445 товаров, и
-- часть из них площадка зовёт в другие акции.
--
-- ВТОРАЯ — весь ассортимент в одной акции. Если завести всё разом, для
-- следующей хорошей акции не останется ничего: товар уже занят и цена его
-- срезана. Оставляем запас.
ALTER TABLE pricing_strategy
    -- Максимум акций на один товар одновременно. Единица означает
    -- «никаких наложений»: одна акция — одна скидка.
    ADD COLUMN IF NOT EXISTS max_actions_per_item INTEGER NOT NULL DEFAULT 1,
    -- Какую долю ассортимента разрешено держать в акциях. Остаток бережём
    -- для будущих предложений площадки.
    ADD COLUMN IF NOT EXISTS max_items_in_actions_percent NUMERIC(5, 2)
        NOT NULL DEFAULT 60;

COMMENT ON COLUMN pricing_strategy.max_actions_per_item IS
    'Сколько акций одновременно допускается на один товар. 1 — без наложений';
COMMENT ON COLUMN pricing_strategy.max_items_in_actions_percent IS
    'Какую долю ассортимента можно держать в акциях, %. Остальное — запас '
    'для следующих хороших предложений площадки';
