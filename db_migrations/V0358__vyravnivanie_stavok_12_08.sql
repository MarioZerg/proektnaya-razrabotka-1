-- Выравнивание ставок Мрамора и Сетки внутри 12.08.2026.
--
-- Тарифы на эти ткани в Цехе №1 подняли с 10 до 15 ₽ 12.08.2026 в 18:23.
-- Начисление считается в момент раскроя, поэтому заказы, раскроенные утром того же
-- дня, остались по 10 ₽, а доначисленные вечером — уже по 15 ₽. Внутри одного дня
-- за одну и ту же работу выходили разные деньги у разных людей.
--
-- Поднимаем утренние начисления за 12.08 до 15 ₽. Дни 10–11.08 НЕ трогаем:
-- по решению владельца новая ставка действует только с 12 числа.
--
-- Затрагивает 53 начисления двух закройщиков, доплата 725 ₽.
-- Ни одно из них не выплачено (paid_at IS NULL) — правка безопасна.
UPDATE salary_accruals sa
SET amount = ROUND((o.width / 100.0) * 15.00, 2)
FROM orders o
WHERE o.id = sa.order_id
  AND sa.type = 'cutter_cut'
  AND sa.paid_at IS NULL
  AND o.material IN ('Мрамор', 'Сетка')
  AND o.workshop_id = 1
  AND o.cut_at >= '2026-08-12'
  AND o.cut_at < '2026-08-13'
  AND sa.amount < ROUND((o.width / 100.0) * 15.00, 2);
