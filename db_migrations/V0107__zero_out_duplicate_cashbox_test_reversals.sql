-- Обнуляем задвоенные тестовые записи возврата в кассу (id=3, id=4), оставшиеся от
-- неудачных прогонов на старой версии кода. Обнуляем сумму, чтобы они не влияли на баланс кассы.
UPDATE cash_box_transactions
SET amount = 0, description = '[Дубль от тестового прогона, аннулирован] ' || description
WHERE id IN (3, 4);