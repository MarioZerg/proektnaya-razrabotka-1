-- Проставляем код связки вещам, которые его не получили.
--
-- Связка — заказ Яндекса из нескольких вещей под ОДНИМ ярлыком площадки.
-- Собрать поставку этим ярлыком нельзя: он одинаковый на всех вещах, поэтому
-- у каждой вещи должен быть свой код YM-<заказ>-<номер вещи>.
--
-- Код проставлялся только при стикеровке вещи со склада, а заказы из цеха
-- закрываются на терминале упаковщицы — там его не ставили. У новых связок
-- кода не оказалось: в строке товара пропала кнопка стикера, а упаковщице
-- нечего было наклеить. Дозаполняем задним числом, чтобы уже сшитые вещи
-- можно было собрать в поставку.
UPDATE goods_warehouse gw
SET bundle_barcode = o.group_key || '-' || COALESCE(o.group_position, 1)
FROM orders o
WHERE o.id = COALESCE(gw.reserved_order_id, gw.order_id)
  AND gw.bundle_barcode IS NULL
  AND o.group_key IS NOT NULL
  AND COALESCE(o.group_size, 1) > 1
  AND gw.status NOT IN ('shipped', 'lost');
