-- Возвращаем в работу два заказа, ошибочно снятых с конвейера 15.09.2026.
--
-- ЧТО ПРОИЗОШЛО. При снятии заказа система сначала отменяет отправление на
-- площадке и только потом помечает его снятым у себя. OZON обе отмены НЕ принял,
-- но ответ с отказом содержал слово «cancel» (в названии поля запроса), а старый
-- код считал любой такой ответ успешной отменой. В результате отправления остались
-- живыми на OZON (статус awaiting_packaging — покупатель ждёт товар), а у нас
-- заказы легли в «Отменён» и пропали из работы. Подбор со склада отменённые
-- заказы не берёт, поэтому шифон на полках под них не резервировался.
--
-- Статус на площадке перепроверен: оба отправления в awaiting_packaging.
--
-- Возвращаем ровно в начало конвейера: этап «Новый», без исполнителя и цеха.
-- Раскрой и пошив по ним не начинались — снять можно было только нетронутый заказ.
UPDATE orders
SET status = 'Новый',
    sewing_status = 'Новый',
    cancelled_at = NULL,
    assigned_user_id = NULL,
    workshop_id = NULL,
    cut_at = NULL,
    taken_at = NULL
WHERE id IN (98923, 98939)
  AND ozon_status = 'awaiting_packaging';
