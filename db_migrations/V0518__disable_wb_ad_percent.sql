-- Отключаем ДРР по Wildberries: рекламы там сейчас нет.
--
-- Последний расчёт рекламы по WB — от 21 августа, кампании с тех пор
-- остановлены. Пока цифра висела в расчёте, она забирала до 21% выручки с
-- каждой вещи и делала прибыльные позиции убыточными на бумаге.
--
-- Ставим ноль и выключаем «считать по факту»: расчёт перестанет подставлять
-- устаревший процент. Когда реклама снова пойдёт, достаточно нажать
-- «Обновить рекламу» и включить факт обратно.
UPDATE marketplace_tariffs
SET promo_percent = 0,
    promo_from_fact = false,
    promo_fact_percent = NULL,
    updated_at = now()
WHERE marketplace_code = 'wildberries';

-- Расчёты по товарам обнуляем, а не удаляем: история трат остаётся, но в
-- текущую экономику остановленные кампании больше не попадают.
UPDATE marketplace_ad_spend
SET ad_percent = 0
WHERE marketplace_code = 'wildberries';
