-- Возвращаем настройки после проверки защиты закрытых отчётов.
--
-- Проверено: при пересчёте выплаченный отчёт (помеченный суммой 99 999 ₽)
-- остался нетронутым, а остальные пересчитались заново и получили среднюю
-- маржу за период — 30–32% по OZON и WB.
--
-- Значит правило работает: если позже опустим цены и товар станет убыточным,
-- уже закрытые периоды это не затронет — деньги задним числом не удерживаются.
UPDATE manager_commission_settings SET accrue_from = DATE '2026-08-24';

UPDATE manager_accruals
SET status = 'cancelled',
    cancelled_at = now(),
    paid_at = NULL,
    salary_accrual_id = NULL,
    cancel_reason = 'Пробный расчёт при настройке. Эти недели оплачиваются вручную'
WHERE user_id = 32 AND period_start < DATE '2026-08-24';
