-- Начисление ждёт, пока деньги реально уйдут с площадки на расчётный счёт.
--
-- Зачем. Сумма к перечислению появляется в отчёте сразу, но какое-то время
-- лежит на балансе площадки. Пока деньги не в банке получателя, платить с них
-- процент не с чего: показывать менеджеру «к выплате» такую сумму — обещать
-- то, чего у компании ещё нет.
--
-- Как определяем поступление. API OZON статус перевода не отдаёт — проверено
-- на трёх эндпоинтах. Зато в отчёте видно движение денег: у недель, деньги за
-- которые уже ушли на счёт (июль), заполнена сумма вывода, а у августовских,
-- висящих на балансе, она пустая. По её появлению и определяем поступление.
--
-- Новый статус: 'pending' — отчёт сформирован, начисление посчитано и видно
-- менеджеру, но в баланс «к выплате» оно не входит.
ALTER TABLE manager_accruals
    ADD COLUMN IF NOT EXISTS paid_out_at TIMESTAMP;

COMMENT ON COLUMN manager_accruals.paid_out_at IS
    'Когда площадка перевела деньги за период на расчётный счёт. '
    'Пока пусто — начисление в статусе pending и в баланс не входит';

-- Отметка о поступлении на самой выплате площадки: заполняется синхронизацией,
-- когда по неделе появляется сумма вывода на расчётный счёт.
ALTER TABLE marketplace_payouts
    ADD COLUMN IF NOT EXISTS transferred_at TIMESTAMP;

COMMENT ON COLUMN marketplace_payouts.transferred_at IS
    'Когда деньги за период ушли с баланса площадки в банк получателя';
