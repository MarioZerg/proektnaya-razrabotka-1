-- Возвращаем на рулон 2 метра, списанные ТЕСТОВЫМ браком DF-000009 при проверке
-- нового экрана «Брак из рулона». Реального брака не было — метраж должен вернуться,
-- иначе остаток рулона разойдётся с тем, что физически лежит в цехе.
UPDATE rolls
SET remaining_quantity = remaining_quantity + 2
WHERE id = 4691;
