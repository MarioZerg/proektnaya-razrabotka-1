-- Лимит заказов на руках у швеи: 2 вместо 30.
--
-- Механика сменилась: раньше темп задавал накопительный таймаут на взятие, и лимит в
-- 30 заказов был просто верхней границей — упереться в него было почти невозможно.
-- Теперь темп задаёт таймер пошива на каждой вещи, а лимит стал рабочим инструментом:
-- швея держит 2 вещи, отшивает их по времени и добирает следующие.
--
-- Глобальное значение (system_settings = 80) тоже приводим к 2: оно применяется, когда
-- у цеха своей настройки нет, и расхождение в сорок раз однажды выстрелит.

UPDATE workshop_settings
SET value = '2', updated_at = now()
WHERE key = 'max_quantity_orders_to_seamstress';

UPDATE system_settings
SET value = '2'
WHERE key = 'max_quantity_orders_to_seamstress';
