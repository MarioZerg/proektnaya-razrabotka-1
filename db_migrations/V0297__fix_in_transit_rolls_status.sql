-- В старой системе был статус «отправлен в цех» (shipped_to_workshop) — рулон уже
-- выдан, но кладовщик ещё не подтвердил передачу. В нашей системе такого состояния
-- нет: рулон либо на складе, либо в цехе.
--
-- При переносе эти 5 рулонов получили статус in_transit, которого система не знает,
-- и страница рулонов на нём падала с ошибкой.
--
-- Переводим их в «в цехе»: цех и смена у всех указаны, физически рулоны именно там.
UPDATE rolls
SET status = 'in_workshop'
WHERE status = 'in_transit'
  AND workshop_id IS NOT NULL
  AND shift_number IS NOT NULL;

-- Подстраховка: если у какого-то рулона «в пути» не окажется цеха, вернём его
-- на склад — иначе он нарушит правило «в цехе обязателен цех и смена».
UPDATE rolls
SET status = 'in_storage', workshop_id = NULL, shift_number = NULL
WHERE status = 'in_transit';
