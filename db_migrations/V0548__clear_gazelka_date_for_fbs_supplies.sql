-- Убираем отметку о Газельке у поставок FBS.
--
-- Газелька возит только FBO — на склад маркетплейса. Поставка FBS едет в пункт
-- приёма напрямую, никакого перевозчика в этом пути нет.
--
-- При переводе поставки в «Отгрузку» дата ставилась обеим схемам подряд, без
-- разбора типа. В списке из-за этого у FBS висело «В Газельку 28.08» —
-- перевозка, которой не было. Номера Газельки при этом не было ни у одной:
-- проставлялась только дата, что и подтверждает случайность записи.
--
-- Сам факт и время отгрузки у этих поставок сохранены в ship_to_marketplace_at
-- и completed_at, так что ничего не теряется.
UPDATE marketplace_supplies
   SET ship_to_gazelka_at = NULL
 WHERE type = 'FBS'
   AND ship_to_gazelka_at IS NOT NULL
   AND gazelka_id IS NULL;