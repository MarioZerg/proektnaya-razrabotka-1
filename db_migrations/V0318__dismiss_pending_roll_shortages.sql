-- Разбираем накопившуюся очередь недостач по закрытым рулонам.
--
-- На дашборде висели 2078 рулонов, ждущих решения администратора: удержать деньги с
-- закройщика или списать недостачу на поставщика. Разбирать такую очередь вручную
-- нереально, а карточка перекрывала весь дашборд.
--
-- По решению владельца списываем ВСЕ накопленные недостачи на поставщика: penalty_total = 0
-- означает «решение принято, штраф не начисляется». Ни один сотрудник не будет оштрафован,
-- уже начисленные штрафы не затрагиваются (у них penalty_total заполнен и NULL-фильтр их
-- не берёт). Новые закрытые рулоны с недостачей будут появляться в карточке как обычно.
UPDATE rolls
SET penalty_total = 0
WHERE status = 'completed'
  AND penalty_total IS NULL
  AND COALESCE(shortage_quantity, 0) > 0;
