-- Чиним односторонние связи, оставленные переносом подбора.
--
-- Сканер подбора умеет переносить работу на ту вещь, что реально в руках у кладовщика:
-- она встаёт «На сборку», а прежняя возвращается на полку. Но заказ при этом продолжал
-- указывать на СТАРУЮ вещь. Связь становилась односторонней, стикеровка такую пару
-- отвергала — кладовщик печатал ярлык, а отправить товар не мог: работа висела в подборе.
--
-- Разворачиваем заказ на ту вещь, которая реально за ним закреплена.
UPDATE orders o
SET fulfilled_from_stock_id = gw.id
FROM goods_warehouse gw
WHERE gw.reserved_order_id = o.id
  AND gw.status = 'picking'
  AND gw.shipped_at IS NULL
  AND o.sewing_status = 'Со склада'
  AND o.fulfilled_from_stock_id IS DISTINCT FROM gw.id;
