-- Помечаем утерянной складскую запись, созданную при проверке приёмки возвратов.
--
-- Возврат 44470904-0672-1 (штрихкод ii15847049514) сканировали, чтобы убедиться, что
-- кнопки «Сразу упаковщице» и «Взять на разбор» работают. Физически эта вещь на склад
-- не поступала — убираем её из воронки осмотра, чтобы кладовщик не искал по цеху то,
-- чего нет. Данные не удаляем: история операций должна остаться целой.
UPDATE goods_warehouse
SET status = 'lost',
    lost_at = now(),
    lost_reason = 'Техническая проверка приёмки возвратов, вещь на склад не поступала'
WHERE storage_barcode = 'GW-722778'
  AND status IN ('checking', 'repacking');
