-- СВЯЗЬ ОСТАТКА НЕДОПЛАТЫ С ВЫПЛАТОЙ, КОТОРАЯ ЕГО ПОРОДИЛА.
--
-- Появилась частичная выплата: админ платит меньше начисленного, а разница
-- переносится на следующий расчёт отдельной строкой начисления.
--
-- Если такую выплату потом отменить, её период вернётся в «невыплаченные»
-- целиком — вместе с уже перенесённым остатком. Сумма к выплате задвоилась бы:
-- и весь период, и остаток по нему же.
--
-- Поле показывает, какой выплатой создан остаток, чтобы при её отмене остаток
-- можно было аннулировать. Обычные начисления его не заполняют — там NULL.
ALTER TABLE salary_accruals
    ADD COLUMN IF NOT EXISTS carry_from_payout_id INTEGER;

COMMENT ON COLUMN salary_accruals.carry_from_payout_id IS
    'Остаток недоплаты, перенесённый на следующий период этой выплатой. '
    'При отмене выплаты такая строка аннулируется, иначе сумма задвоится.';
