-- Помечаем списанной тестовую запись, созданную при проверке защиты ручного приёма.
--
-- Проверяли, что приём НЕ блокируется товаром на стикеровке (вещь уже сшита и
-- доедет до склада сама). Проверка прошла, но создала настоящую запись на складе —
-- реального товара за ней нет. Удалять записи склада нельзя (в них история), поэтому
-- помечаем как списанную с явной причиной: в остатках она больше не числится.
UPDATE goods_warehouse
SET status = 'disposed',
    shelf_id = NULL,
    dispose_reason = 'Тестовая запись при проверке защиты ручного приёма — товара нет',
    disposed_at = now()
WHERE storage_barcode = 'GW-732350';
