-- 1. Исправляем статус перенесённых заказов.
--
-- Система работает со статусом «Готовые», а при переносе из старой базы записалось
-- «Готов». Из-за этого 143 заказа не попадали ни на вкладку «Готовые» на конвейере,
-- ни в сборку поставки FBS — они были невидимы для системы.
UPDATE orders
SET sewing_status = 'Готовые'
WHERE sewing_status = 'Готов';

-- 2. Возвращаем в работу заказы, уже собранные на стороне OZON.
--
-- Это отправления в статусе awaiting_deliver: они собраны и ждут передачи в доставку.
-- Шить их не нужно, но отгружать придётся — поэтому показываем их как готовые,
-- чтобы кладовщик собрал из них поставку FBS и видел реальную картину.
UPDATE orders
SET sewing_status = 'Готовые',
    status = 'Готов'
WHERE marketplace = 'OZON'
  AND ozon_status = 'awaiting_deliver'
  AND sewing_status = 'Отменён';
