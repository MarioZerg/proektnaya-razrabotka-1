-- Возврат тестовой поставки 1275 в исходный статус.
--
-- При проверке разбора модуля поставок её перевели в «На сборке», чтобы убедиться,
-- что предохранитель ЭТрН по-прежнему не выпускает машину без подписанной накладной.
-- Проверка пройдена, статус возвращаем — поставка снова открытая.
UPDATE marketplace_supplies
SET status = 'Открытая'
WHERE id = 1275 AND status = 'На сборке';