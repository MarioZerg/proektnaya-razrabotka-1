-- МАТЕРИАЛ ПРИНАДЛЕЖИТ МАГАЗИНАМ, И ОБРАБОТКА КРАЯ У КАЖДОГО СВОЯ.
--
-- Цех общий, но ассортимент у МЕГАТЮЛЬ и ДЮНЫ разный: часть тканей идёт только
-- в один магазин, часть — в оба. Держать это в голове закройщика нельзя: он
-- видит в списке ткань, которой у этого магазина нет, и режет не то.
--
-- Главное — ОБРАБОТКА БОКОВОГО ШВА У ОДНОЙ И ТОЙ ЖЕ ТКАНИ РАЗНАЯ.
-- В МЕГАТЮЛЬ вуаль обмётывают на оверлоке (это отдельный этап и отдельное
-- начисление), а в ДЮНЕ та же вуаль шьётся обычной прямострочкой. Признак
-- requires_overlock висел на самом материале — один на всех, — и развести это
-- было нечем: приходилось заводить вторую карточку ткани с тем же названием.
--
-- Поэтому признак переезжает в связку «материал + магазин».
CREATE TABLE IF NOT EXISTS material_shops (
    id SERIAL PRIMARY KEY,
    material_id INTEGER NOT NULL REFERENCES materials(id),
    shop_id INTEGER NOT NULL REFERENCES shops(id),
    -- Нужен ли оверлок ИМЕННО В ЭТОМ магазине. Та же ткань в соседнем магазине
    -- может шиться обычным швом — там будет своя строка со своим значением.
    requires_overlock BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

-- Пара «материал + магазин» одна: две строки на один магазин — это ошибка ввода,
-- а не сценарий, и она молча ломала бы признак оверлока.
CREATE UNIQUE INDEX IF NOT EXISTS material_shops_uniq
    ON material_shops (material_id, shop_id);

-- По магазину выбирают список материалов на экранах раскроя и приёмки.
CREATE INDEX IF NOT EXISTS material_shops_shop_idx ON material_shops (shop_id);

-- ПЕРЕНОС ТОГО, ЧТО УЖЕ НАСТРОЕНО.
--
-- Ткани, у которых стоял общий признак оверлока, раздаём всем активным магазинам
-- с тем же признаком: до этой правки обмётка работала одинаково везде, и менять
-- поведение цеха молча нельзя — иначе завтра вещь уедет швее необмётанной.
--
-- Материалы БЕЗ признака не трогаем вовсе: пустой список магазинов означает
-- «подходит всем». Так все существующие ткани остаются рабочими, а разделение
-- админ включает точечно — там, где оно действительно нужно.
INSERT INTO material_shops (material_id, shop_id, requires_overlock)
SELECT m.id, s.id, true
FROM materials m
CROSS JOIN shops s
WHERE m.requires_overlock = true
  AND s.is_active = true
ON CONFLICT (material_id, shop_id) DO NOTHING;
