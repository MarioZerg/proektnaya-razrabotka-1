-- Баланс зарплаты у новичков открывается через 2 недели после регистрации.
-- Храним конкретную дату открытия, а не считаем от created_at, по двум причинам:
--   1) уже работающие сотрудники НЕ должны внезапно потерять доступ к своей зарплате —
--      им ставим дату в прошлом, то есть открыто сразу;
--   2) администратор при необходимости может открыть доступ конкретному человеку раньше.
ALTER TABLE users ADD COLUMN IF NOT EXISTS salary_unlock_at TIMESTAMP;

-- Всем, кто уже заведён в системе, зарплата остаётся открытой.
UPDATE users SET salary_unlock_at = now() - INTERVAL '1 day' WHERE salary_unlock_at IS NULL;

-- Новые сотрудники по умолчанию получают доступ через 14 дней после регистрации.
ALTER TABLE users ALTER COLUMN salary_unlock_at SET DEFAULT (now() + INTERVAL '14 days');