-- Отключаем демо-аккаунт «Швея (оверлок)».
--
-- Отдельная роль для оверлока не нужна: это галочка-допуск в карточке швеи, а не
-- должность. Чтобы посмотреть такой режим, администратор ставит допуск живой швее
-- и входит в её аккаунт из раздела «Сотрудники» — заводить ради этого отдельного
-- сотрудника избыточно.
--
-- Запись не удаляем (данные не трём), а гасим: из списков входа и из справочника
-- сотрудников она пропадает.
UPDATE users
SET is_active = false,
    can_overlock = false,
    full_name = 'Швея (оверлок) — служебная запись, не используется'
WHERE login = 'demo_sewer_overlock';