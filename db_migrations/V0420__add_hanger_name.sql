-- Названия вешалок вместо голых номеров.
--
-- ЗАЧЕМ. В цехе вешалки различают не по номерам, а по приметам: «синяя у окна»,
-- «длинная», «стойка А». Заставлять администратора придумывать номер там, где у
-- вешалки есть живое имя, — лишний шаг и лишний повод перепутать.
--
-- ПОЧЕМУ НЕ ЗАМЕНЯЕМ НОМЕР. На номер вешалки уже ссылаются тысячи заказов
-- (orders.hanger_number) и «последняя вешалка» закройщика (users.last_hanger_number).
-- Ломать эту связь нельзя: у всех раскроенных заказов пропала бы вешалка. Поэтому
-- номер остаётся внутренним признаком (и назначается сам), а рядом появляется имя,
-- которое видит человек.
--
-- Пустое имя = вешалка без названия, показывается как раньше: «№ 12».
ALTER TABLE hangers ADD COLUMN IF NOT EXISTS name TEXT;
