-- В журнале робота колонка margin_fbs больше не про маржу: робот перестал
-- на неё смотреть и ведёт цены к простой цели «поднять на N%». Теперь в этом
-- поле — сдвиг цен от точки старта на момент решения.
--
-- Переименовываем, чтобы имя не врало: читать «маржа» и видеть проценты
-- подъёма — верный способ однажды запутаться.
ALTER TABLE price_robot_runs RENAME COLUMN margin_fbs TO drift_percent;

COMMENT ON COLUMN price_robot_runs.drift_percent IS
    'На сколько процентов цены были подняты от старта на момент этого шага';