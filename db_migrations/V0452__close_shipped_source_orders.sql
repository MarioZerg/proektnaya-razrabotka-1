-- Закрываем заказы, чья вещь физически уже уехала к покупателю.
--
-- Пока вещь подбирают с полки, заказ-ИСТОЧНИК (тот, по которому вещь попала на
-- склад) остаётся «Новым»: при отгрузке закрывался только заказ покупателя
-- (reserved_order_id), а order_id — нет.
--
-- Из-за этого на складе висели две противоречивые строки: «GW-724770 отгружен»
-- и рядом «WH-00517 новый». Кладовщик не понимал, где вещь, и не мог отличить
-- реальную работу от призрачной. В самом коде причину уже устранили — здесь
-- разбираем накопившееся.
--
-- Трогаем ТОЛЬКО те заказы, у которых вещь имеет статус 'shipped' и
-- проставленную дату отгрузки: товар точно уехал, ждать по нему нечего.
-- Отменённые заказы не трогаем — у них своя история.
UPDATE orders o
SET status = 'Отгружен',
    completed_at = COALESCE(o.completed_at, g.shipped_at, now())
FROM goods_warehouse g
WHERE g.order_id = o.id
  AND g.status = 'shipped'
  AND g.shipped_at IS NOT NULL
  AND o.status = 'Новый';
