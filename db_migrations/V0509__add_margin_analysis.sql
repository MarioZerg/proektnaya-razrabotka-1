-- Анализ маржинальности в отчёте менеджера.
--
-- Правило: вознаграждение платится только за товары, которые принесли доход.
-- Убыточные из базы вычитаются. Но в отчёте до сих пор была одна сухая цифра
-- вычета — непонятно, ЧТО именно ушло в минус и почему.
--
-- Сохраняем разбор: сколько товаров продано, у скольких маржа отрицательная,
-- какая средняя маржа за период и какие позиции хуже всех. Тогда менеджер
-- видит не «удержали N рублей», а конкретный список, с которым можно работать.
ALTER TABLE manager_accruals
    -- Средняя маржа по проданному за период, в процентах.
    ADD COLUMN IF NOT EXISTS avg_margin NUMERIC(6, 2),
    -- Разбор убыточных позиций: что именно ушло в минус и на сколько.
    ADD COLUMN IF NOT EXISTS loss_details JSONB;

COMMENT ON COLUMN manager_accruals.avg_margin IS
    'Средняя маржинальность проданного за период';
COMMENT ON COLUMN manager_accruals.loss_details IS
    'Разбор убыточных позиций: ткань, ширина, цена, убыток с вещи, штук';

-- Начисление фиксируется на момент закрытия отчёта и потом не пересчитывается.
COMMENT ON COLUMN manager_accruals.paid_at IS
    'Когда вознаграждение передано в зарплату. Заполнено — отчёт закрыт: '
    'пересчёт его не трогает, даже если цены и себестоимость позже изменятся';
