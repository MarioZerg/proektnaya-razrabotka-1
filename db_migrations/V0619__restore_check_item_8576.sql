-- Возврат проверочной вещи GW-729907 в исходное состояние.
--
-- При проверке сценария «скан отменённого заказа в поставку» вещь 8576 была
-- переведена из 'shipped' в 'in_stock' и положена на полку 3. Это боевая запись,
-- поэтому возвращаем ей прежний вид.
--
-- Заказ 97533259-0204-1 отменён покупателем (ozon_status='cancelled'), а вещь
-- числилась отгруженной — это ровно тот случай, ради которого правка и делалась.
-- Кладовщик разберёт её штатным путём: пикнет в поставку, получит окно отмены,
-- напечатает стикер и выберет полку.
UPDATE goods_warehouse
SET status = 'shipped',
    shipped_at = '2026-09-08 12:00:00',
    shelf_id = NULL
WHERE id = 8576 AND storage_barcode = 'GW-729907';
