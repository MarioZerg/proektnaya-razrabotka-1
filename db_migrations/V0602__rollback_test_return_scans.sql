-- Откат двух ТЕСТОВЫХ приёмок возврата, сделанных при проверке сканера WB/Яндекса.
--
-- При проверке распознавания кодов две реальные вещи были приняты как возвраты,
-- хотя физически их с ПВЗ никто не привозил. Возвращаем исходное состояние, иначе
-- кладовщик пойдёт искать несуществующие возвраты, а вещи выпадут из поставок.
--
-- Обе вещи были застикерованы и ждали поставку (awaiting_supply):
--   GW-729582 — Яндекс, заказ YM-61355128771-1, закрыт после стикеровки;
--   GW-729778 — WB, заказ 5689198197, закрыт вещью со склада.
-- Удалять записи нельзя (запрет на удаление данных), поэтому возвращаем им
-- прежний статус — в возвратах они больше не числятся.

UPDATE goods_warehouse
SET status = 'awaiting_supply',
    receive_reason = 'cancelled',
    shelf_id = NULL
WHERE storage_barcode IN ('GW-729582', 'GW-729778')
  AND status = 'mp_return';
