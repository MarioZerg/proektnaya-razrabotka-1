-- Инвентаризация №2 создана при проверке доступа администратора, реального
-- пересчёта в ней не было. Отменяем, чтобы она не занимала место активной и
-- не блокировала запуск настоящего пересчёта.
UPDATE stocktakes
SET status = 'cancelled',
    reject_reason = 'Проверка доступа, пересчёт не проводился'
WHERE id = 2 AND status = 'in_progress';
