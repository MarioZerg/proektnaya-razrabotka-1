-- Проставляем полку вещам, которые числятся «На хранении», но без полки.
--
-- ЗАЧЕМ. Подбор со склада берёт только вещи с заполненным shelf_id: пока вещь
-- не принята на конкретную полку, для системы её на складе нет. Из-за этого
-- 70 вещей были невидимы — заказы по ним уходили в пошив, хотя товар лежал
-- на стеллаже. Часть этих записей висит с середины августа.
--
-- Полку ставим одну на всех — «1» (id 17), чтобы их легко было найти одним
-- фильтром и разложить по местам при ближайшей инвентаризации.
UPDATE goods_warehouse
SET shelf_id = 17
WHERE status = 'in_stock'
  AND shelf_id IS NULL;
