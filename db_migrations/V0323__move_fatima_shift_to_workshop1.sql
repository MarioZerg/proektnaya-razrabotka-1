-- Переносим смену Фатимы в цех №1, смену 2.
--
-- Фатима физически работает в цехе №1 гостем, но смену открыла на терминале цеха №2.
-- Очередь заказов и материал привязаны к цеху смены, поэтому ей не выдавалось ни одного
-- заказа: все 56 раскроенных лежат в цехе №1.
--
-- Смену не пересоздаём: время прихода (05:51) должно сохраниться, иначе сотрудник
-- потеряет отработанные часы и опоздание/переработка посчитаются неверно.
UPDATE shift_sessions
SET workshop_id = 1,
    shift_number = 2
WHERE user_id = 25
  AND closed_at IS NULL;
