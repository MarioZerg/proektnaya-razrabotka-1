-- Журнал сбоев приложения.
--
-- ЗАЧЕМ. До сих пор ошибки в браузере сотрудника нигде не сохранялись: они
-- жили только в консоли на его планшете. Сотрудник говорил «не работает», а
-- разобраться было нечем — воспроизвести чужой сбой почти невозможно.
--
-- Теперь каждая ошибка приходит сюда: что упало, на какой странице, кто
-- работал. Этого достаточно, чтобы найти причину, не подходя к планшету.
--
-- Персональных данных здесь нет: только имя и роль сотрудника, чтобы понять,
-- на чьём экране и в каком разделе сломалось.
CREATE TABLE IF NOT EXISTS app_errors (
    id BIGSERIAL PRIMARY KEY,
    occurred_at TIMESTAMP NOT NULL DEFAULT now(),
    -- Откуда пришло: frontend (браузер сотрудника) или backend (функция).
    source TEXT NOT NULL DEFAULT 'frontend',
    -- Насколько серьёзно: error — упало, warn — сработало, но неправильно.
    level TEXT NOT NULL DEFAULT 'error',
    message TEXT NOT NULL,
    -- Где именно в коде. Помогает выйти на нужный файл без догадок.
    stack TEXT,
    -- Страница, на которой сотрудник был в момент сбоя.
    page TEXT,
    user_id INTEGER,
    user_name TEXT,
    user_role TEXT,
    -- Браузер и устройство: часть сбоев случается только на старых планшетах.
    user_agent TEXT,
    -- Версия приложения: сразу видно, появилась ошибка с последним обновлением
    -- или живёт давно.
    app_version TEXT
);

-- Разбор всегда начинается со свежих ошибок, поэтому сортировка по времени
-- вниз — основной путь чтения.
CREATE INDEX IF NOT EXISTS idx_app_errors_occurred ON app_errors (occurred_at DESC);

-- Отдельно ищем по тексту ошибки: одна и та же поломка повторяется у разных
-- сотрудников, и важно понять, массовая она или единичная.
CREATE INDEX IF NOT EXISTS idx_app_errors_message ON app_errors (message);
