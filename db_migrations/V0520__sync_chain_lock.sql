-- Замок для цепочки загрузки заказов.
--
-- Загрузка, упершись в свой пятисекундный лимит, зовёт себя снова и
-- доделывает остаток. Но запрос «не дожидаясь ответа» оказался ненадёжен:
-- обрыв по таймауту выглядит как неудача, и вызов повторяется. Один запуск
-- превращался в два, два в четыре — за минуту набежало три десятка.
--
-- Замок делает шаг цепочки неповторимым: номер шага уникален, и второй
-- запуск с тем же номером просто не запишется и сразу выйдет.
CREATE TABLE IF NOT EXISTS sync_chain_lock (
    id BIGSERIAL PRIMARY KEY,
    -- Что именно продолжаем: загрузку заказов или деление отправлений.
    job TEXT NOT NULL,
    -- Номер шага. Пара «задание + шаг» и есть замок.
    step INT NOT NULL,
    started_at TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT sync_chain_lock_uniq UNIQUE (job, step)
);

-- Старые замки чистим по времени: цепочка живёт минуты, а не часы.
CREATE INDEX IF NOT EXISTS idx_sync_chain_lock_started
    ON sync_chain_lock (started_at);
