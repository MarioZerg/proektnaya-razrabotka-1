-- Срок действия сертификата: в какой промежуток подарок доступен к покупке.
--
-- Сертификаты часто выдаются партнёром на конкретный сезон: например, билеты в
-- аквапарк действуют до конца лета. Купленный после этой даты сертификат
-- сотрудник уже не использует, а варики потратит впустую.
--
-- Обе даты необязательные и работают независимо:
--   оба NULL         — бессрочно, продаётся всегда;
--   заполнено «с»    — раньше этой даты купить нельзя (акция ещё не началась);
--   заполнено «по»   — позже этой даты купить нельзя (сертификаты сгорели).
ALTER TABLE variki_shop_items ADD COLUMN IF NOT EXISTS valid_from DATE NULL;
ALTER TABLE variki_shop_items ADD COLUMN IF NOT EXISTS valid_to DATE NULL;

COMMENT ON COLUMN variki_shop_items.valid_from IS
 'С какой даты подарок доступен к покупке. NULL — без ограничения.';
COMMENT ON COLUMN variki_shop_items.valid_to IS
 'По какую дату включительно подарок доступен к покупке. NULL — бессрочно.';
