-- Запоминаем операцию СОЗДАНИЯ грузоместа на OZON.
--
-- ЗАЧЕМ. Создание грузоместа асинхронное: /v1/cargoes/create отдаёт
-- operation_id, а номер места (cargo_id) приходит позже, отдельным запросом.
--
-- У облачной функции всего 5 секунд, а ожидание результата занимало до 22.
-- Функция обрывалась по таймауту ПОСЛЕ того, как место на площадке уже
-- создано, но ДО того, как cargo_id записан коробу. Итог: на OZON висит
-- грузоместо, о котором мы не знаем, — сирота с полным товарным составом.
-- Кладовщик жал «Закрыть короб» снова, появлялось ещё одно место, и заявка
-- показывала два одинаковых короба с разными штрихкодами.
--
-- Теперь operation_id сохраняется СРАЗУ после создания. Даже если функция
-- оборвётся, следующий заход не создаёт новое место, а забирает номер уже
-- созданного и привязывает его к коробу.
ALTER TABLE marketplace_supply_boxes
    ADD COLUMN IF NOT EXISTS ozon_create_operation_id TEXT;

COMMENT ON COLUMN marketplace_supply_boxes.ozon_create_operation_id IS
    'operation_id создания грузоместа в OZON. Позволяет забрать cargo_id после обрыва по таймауту и не плодить грузоместа-сироты.';
