-- ЗАФИКСИРОВАННОЕ НА 15:00 КОЛИЧЕСТВО РАБОТЫ ДЛЯ ЗАДАНИЙ СМЕНЫ.
--
-- Кладовщик собирает не КОНКРЕТНЫЕ вещи, а НУЖНОЕ КОЛИЧЕСТВО: вещи одного
-- размера на полке одинаковы, годится любая подходящая. Но раньше задание
-- считалось по конкретным записям — и стоило кладовщику взять с полки другую
-- такую же вещь, как система переставляла ей время подбора, запись выпадала
-- из среза «до 15:00», и счётчик прыгал. Человек начинал сканировать всё
-- подряд, лишь бы попасть в те самые штуки, что заложены в счётчик.
--
-- Теперь в 15:00 количество замораживается: «собрать N штук». Дальше засчитываем
-- ЛЮБУЮ собранную вещь, а новая работа, пришедшая после отсечки, в это число
-- уже не добавляется и смену не держит.
--
-- Привязка к ДАТЕ (московской), а не к смене: у кладовщиков смены разные, а
-- работа на складе общая. Завтра — новая дата, новое число, список с нуля.
CREATE TABLE IF NOT EXISTS storekeeper_task_cutoff (
    id SERIAL PRIMARY KEY,
    task_key VARCHAR(64) NOT NULL,
    snap_date DATE NOT NULL,
    target_count INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT storekeeper_task_cutoff_uniq UNIQUE (task_key, snap_date)
);
