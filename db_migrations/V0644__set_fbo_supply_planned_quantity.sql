-- План поставки для уже импортированных заявок OZON FBO.
--
-- ЗАЧЕМ. total_quantity_marketplace — это сколько штук мы обещали привезти по
-- заявке. По нему проверяется, собрана ли поставка целиком: пока в коробах
-- меньше, кладовщику нельзя закрывать сборку.
--
-- При импорте заявки поле НЕ ЗАПОЛНЯЛОСЬ вообще (исправлено в коде), поэтому
-- проверка недовоза молча пропускала любую поставку: кнопка «Поставка
-- собрана» горела при 32 вещах из 249, и на площадку уехал бы недовоз.
--
-- Здесь проставляем план уже существующим поставкам — по числу заказов,
-- созданных из состава заявки. Каждая штука заявки заводится отдельным
-- заказом, поэтому их количество и есть план.
--
-- Отменённые заказы не считаем: их из заявки убрали, привозить нечего.
-- Трогаем только незавершённые поставки — у закрытых состав менять незачем.
UPDATE marketplace_supplies s
SET total_quantity_marketplace = sub.cnt
FROM (
    SELECT o.supply_id, COUNT(*) AS cnt
    FROM orders o
    WHERE o.supply_id IS NOT NULL
      AND COALESCE(o.status, '') <> 'Отменён'
    GROUP BY o.supply_id
) AS sub
WHERE s.id = sub.supply_id
  AND s.type = 'FBO'
  AND s.total_quantity_marketplace IS NULL
  AND s.status NOT IN ('Выполнена', 'Отменена');
