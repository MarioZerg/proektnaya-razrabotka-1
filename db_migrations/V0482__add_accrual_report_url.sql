-- Ссылка на PDF-отчёт недели.
--
-- Зачем. Менеджер прикрепляла отчёты вручную и называла сумму текстом —
-- проверить расчёт было нечем. Теперь документ формируется сам: в нём видно
-- базу, ставку, количество вещей и все возвраты, снявшие часть начисления.
--
-- Файл кладём в облако и храним ссылку: пересобирать PDF при каждом открытии
-- страницы незачем, а сам документ должен оставаться неизменным — на него
-- ссылаются при выплате.
ALTER TABLE manager_accruals
    ADD COLUMN IF NOT EXISTS report_url TEXT,
    ADD COLUMN IF NOT EXISTS report_built_at TIMESTAMP;

COMMENT ON COLUMN manager_accruals.report_url IS
    'PDF-отчёт за неделю: фиксирует расчёт вознаграждения';
