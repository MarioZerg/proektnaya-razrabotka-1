-- Подобранные со склада вещи переводим в статус «На сборке».
--
-- Вещь, подобранная под заказ FBS, — это уже конкретное отправление, за которым идёт
-- кладовщик, а не свободный остаток на полке. Раньше такие вещи продолжали числиться
-- «На хранении»: в списке склада они выглядели доступным товаром, их можно было
-- посчитать свободными или переложить, хотя за ними уже закреплён заказ.
--
-- Переводим накопившиеся вещи (около полусотни) в «На сборке» — дальше новый подбор
-- ставит этот статус сразу при бронировании.
UPDATE goods_warehouse
SET status = 'picking'
WHERE status = 'in_stock'
  AND reserved_order_id IS NOT NULL;
