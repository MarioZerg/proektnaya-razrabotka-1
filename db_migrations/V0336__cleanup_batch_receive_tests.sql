-- Уборка тестовых приёмок после починки приёма партии.
--
-- При проверке ручной приёмки партиями завелись служебные вещи (id 750–766, стикеры
-- GW-722514…GW-722530) плюс более ранние тестовые записи. Реального товара за ними нет:
-- если оставить, кладовщик пойдёт искать их по полкам, а подбор под заказ упрётся
-- в несуществующую вещь. Помечаем утерянными.
UPDATE goods_warehouse
SET status = 'lost',
    lost_reason = 'Тестовая приёмка, товара физически нет',
    lost_at = now(),
    shelf_id = NULL
WHERE id BETWEEN 750 AND 766
  AND reserved_order_id IS NULL
  AND status <> 'lost';
