-- Рулон в пути: отгружен кладовщиком, но цехом ещё не принят.
--
-- Раньше рулон становился доступен цеху сразу после отправки: он числился в остатках
-- и его можно было пустить в раскрой, хотя физически он мог ещё ехать или вовсе
-- не доехать. Подтверждение приёмки было формальностью и ни на что не влияло.
--
-- Теперь до подтверждения рулон считается «в пути»: в остатках цеха он показывается
-- отдельно и в раскрой не идёт. Смена сначала пересчитывает привезённое и принимает
-- заявку — только после этого материал можно резать.
ALTER TABLE t_p86119184_proektnaya_razrabotk.rolls
    ADD COLUMN IF NOT EXISTS accepted_at TIMESTAMP;

COMMENT ON COLUMN t_p86119184_proektnaya_razrabotk.rolls.accepted_at IS
    'Когда цех подтвердил приёмку рулона. NULL при status=in_workshop — рулон в пути, использовать нельзя';

-- Рулоны, которые уже лежат в цехах, считаем принятыми: они там давно и работа по ним
-- идёт. Иначе после обновления смена не смогла бы резать материал, который уже в цеху.
UPDATE t_p86119184_proektnaya_razrabotk.rolls
SET accepted_at = COALESCE(accepted_at, now())
WHERE status = 'in_workshop' AND accepted_at IS NULL;
