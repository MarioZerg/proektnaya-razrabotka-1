-- Техническая инвентаризация №1 не должна мешать работе.
--
-- В статусе 'rejected' она считается незакрытой и блокирует запуск настоящего
-- пересчёта. Отдельный статус 'cancelled' выводит её из работы, но оставляет
-- в истории — молча удалять записи об операциях со складом нельзя.

UPDATE stocktakes
SET status = 'cancelled',
    reject_reason = 'Техническая проверка механизма. Списание отменено, товар возвращён на склад'
WHERE id = 1;

COMMENT ON COLUMN stocktakes.status IS
 'in_progress — кладовщик считает; pending_approval — закрыта, ждёт админа; approved — админ подтвердил (недостачи списаны); rejected — админ вернул на пересчёт; cancelled — отменена, в работе не участвует.';
