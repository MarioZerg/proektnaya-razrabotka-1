-- НАДБАВКА НА НЕДОСТАЧИ МАТЕРИАЛОВ.
--
-- Часть ткани, тесьмы, пакетов и этикеток не доходит до готовой вещи: обрезки,
-- брак, пересорт, потери при раскрое. Эти метры и штуки оплачены, но в изделии
-- их нет — значит, себестоимость занижена, а прибыль на бумаге выше реальной.
--
-- Считаем надбавку процентом от стоимости материалов и показываем отдельной
-- строкой: видно, сколько именно уносят потери, и процент можно поправить,
-- когда инвентаризация покажет настоящую цифру.
ALTER TABLE cost_settings
ADD COLUMN IF NOT EXISTS shortage_percent NUMERIC(5,2) NOT NULL DEFAULT 5;

COMMENT ON COLUMN cost_settings.shortage_percent IS
'Надбавка на недостачи материалов, % от стоимости ткани, тесьмы и упаковки';