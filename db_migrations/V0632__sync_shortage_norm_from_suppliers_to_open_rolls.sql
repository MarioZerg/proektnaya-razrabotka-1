-- Протягиваем действующие нормы недостачи поставщиков в нерешённые рулоны.
--
-- Норма лежит копией на рулоне (снимок на момент приёмки), чтобы уже начисленные
-- удержания не переигрывались задним числом. Но снимок заморозил и те рулоны, по
-- которым решения ещё не было: норму у поставщика подняли до 7%, а склад, цех и
-- очередь недостач продолжали считать по старым 5-6%.
--
-- Правим только там, где деньги не тронуты: penalty_total IS NULL — штраф не
-- начислен и недостача не прощена. Рулоны с уже принятым решением не трогаем.
UPDATE rolls r
SET shortage_norm_percent = s.shortage_norm_percent
FROM suppliers s
WHERE s.id = r.supplier_id
  AND r.penalty_total IS NULL
  AND r.shortage_norm_percent IS DISTINCT FROM s.shortage_norm_percent;
