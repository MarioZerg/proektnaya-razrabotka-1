-- Потолок доли рекламных расходов (ДРР).
--
-- Зачем. Реклама на Wildberries вышла из-под контроля: общая ДРР 21,6%, а по
-- отдельным позициям — сотни процентов. На Бамбук 3 потрачено 15 270 ₽
-- рекламы при выручке 1 720 ₽: каждая продажа стоила дороже самой шторы.
-- Из 257 733 ₽ рекламного бюджета 246 336 ₽ ушло на позиции с ДРР выше 12%.
--
-- Проблема в том, что заметить это невозможно: кампании живут в кабинете
-- площадки отдельно от экономики, и связь «эта реклама съела всю прибыль»
-- нигде не видна.
--
-- Что делаем. Задаём потолок ДРР. Позиции выше потолка подсвечиваем как
-- перерасход и показываем, сколько денег уходит впустую.
ALTER TABLE pricing_strategy
    -- Потолок доли рекламы в выручке, %. Выше — реклама съедает прибыль.
    ADD COLUMN IF NOT EXISTS max_ad_percent NUMERIC(5, 2) NOT NULL DEFAULT 12;

COMMENT ON COLUMN pricing_strategy.max_ad_percent IS
    'Потолок доли рекламных расходов в выручке, %. Позиции выше считаются '
    'перерасходом: реклама съедает прибыль';
