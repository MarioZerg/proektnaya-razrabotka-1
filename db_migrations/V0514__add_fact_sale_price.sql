-- Фактическая цена продажи товара.
--
-- Зачем. Площадка отдаёт в справочнике цен marketing_seller_price — цену с
-- учётом своих акций. Но и она расходится с тем, что реально приходит за
-- проданную вещь: покупатель платит по OZON-карте, действуют региональные
-- цены и баллы. На сверке за неделю расхождение вышло в среднем 3,2%, а по
-- отдельным позициям до 6%.
--
-- Что делаем. Берём цену из ФИНАНСОВЫХ ОПЕРАЦИЙ площадки: accruals_for_sale —
-- это сумма, начисленная за конкретную продажу. Точнее источника нет, потому
-- что это уже свершившийся факт, а не витрина.
ALTER TABLE marketplace_prices
    -- Средняя цена фактических продаж за последний месяц.
    ADD COLUMN IF NOT EXISTS fact_sale_price NUMERIC(12, 2),
    -- Сколько продаж усреднили: по одной судить нельзя.
    ADD COLUMN IF NOT EXISTS fact_sale_count INTEGER,
    ADD COLUMN IF NOT EXISTS fact_synced_at TIMESTAMP;

COMMENT ON COLUMN marketplace_prices.fact_sale_price IS
    'Средняя цена реальных продаж из финансовых операций площадки. Точнее '
    'витрины: учитывает оплату картой площадки, регион и баллы';
COMMENT ON COLUMN marketplace_prices.fact_sale_count IS
    'На скольких продажах посчитана фактическая цена';
