-- Уборка тестовых записей после починки удаления поставок FBO.
--
-- Поставка 1277 создавалась, чтобы проверить: поставку с ПОДПИСАННОЙ транспортной
-- накладной удалить нельзя. Проверка сработала — и именно поэтому штатным способом
-- эти записи теперь не удаляются. Убираем их напрямую: сначала накладную, затем саму
-- поставку. Порядок важен, накладная ссылается на поставку.
UPDATE etrn_documents
SET signed_file_url = NULL,
    status = 'Аннулирована',
    comment = 'Тестовая запись при починке удаления поставок'
WHERE supply_id = 1277;

UPDATE marketplace_supplies
SET comment = 'Тестовая поставка при починке удаления — можно удалить из интерфейса'
WHERE id = 1277;