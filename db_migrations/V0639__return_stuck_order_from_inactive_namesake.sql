-- Возвращаем в очередь заказ, зависший на карточке неработающей однофамилицы.
--
-- ЧТО ПРОИЗОШЛО. В цехе две швеи с почти одинаковым именем:
--   id 37 — «Беляева Наталия Николаевна» (последняя смена 24.08.2026, больше не выходит)
--   id 46 — «Беляева Наталия»            (работает, смена открыта)
-- В выпадающем списке назначения они выглядели одинаково, и 17.09 админ назначил
-- заказ 0123451984-0088-1 на карточку id 37. Швея видит заказы только своего цеха
-- и только при открытой смене — у id 37 смены нет, поэтому заказ ей не показался.
-- У админа он при этом числился «В работе у Беляевой», и вещь простояла сутки.
--
-- Возвращаем заказ в общую очередь «Раскроено»: крой сделан (cut_at заполнен),
-- шить его не начинали (sewn_at пуст), поэтому следующая свободная швея возьмёт
-- его сама через «Взять заказ».
UPDATE orders
SET sewing_status = 'Раскроено',
    assigned_user_id = NULL,
    taken_at = NULL
WHERE id = 99050
  AND sewing_status = 'В работе'
  AND assigned_user_id = 37
  AND sewn_at IS NULL;
