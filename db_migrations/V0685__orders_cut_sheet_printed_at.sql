-- ОТМЕТКА О ПЕЧАТИ ЛИСТА НА ПЕРЕХВАЧЕННЫЙ КРОЙ.
--
-- Перехват — это когда покупатель отменил заказ уже после раскроя, а следом
-- пришёл новый заказ того же размера: крой отдали ему (orders.cut_from_order_id),
-- шить с нуля не пришлось. Но БИРКА НА ВЕШАЛКЕ ОСТАЛАСЬ ОТ ОТМЕНЁННОГО ЗАКАЗА —
-- перепечатать её в момент перехвата некому, заказы приходят и ночью.
--
-- Пока новый лист не напечатан, вещь едет по цеху с чужим номером: на стикеровке
-- терминал ищет заказ по старой бирке, а швея не понимает, что у неё в руках.
-- Поэтому терминал в цехе НАПОМИНАЕТ ГОЛОСОМ, пока лист не напечатали.
--
-- Эта колонка — единственное, чем «напечатали» отличается от «ещё нет». Без неё
-- терминал бубнил бы про уже напечатанный лист до самой стикеровки.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS cut_sheet_printed_at TIMESTAMP NULL;

-- Терминал спрашивает про перехваты раз в минуту на каждом цехе — выборка должна
-- быть мгновенной и не зависеть от размера таблицы заказов.
CREATE INDEX IF NOT EXISTS idx_orders_intercepted_sheet
    ON orders (workshop_id, sewing_status)
    WHERE cut_from_order_id IS NOT NULL AND cut_sheet_printed_at IS NULL;
