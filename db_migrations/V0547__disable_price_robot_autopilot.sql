-- Выключаем автоматический подъём цен.
--
-- Робот сам поднимал цены по ночам и откатывал их, если видел падение спроса.
-- Спрос он считал по выгрузке продаж, а она может отстать: 28 августа выгрузка
-- стояла с 23-го, робот увидел в базе ноль продаж, счёл это обвалом на 100% и
-- опустил 613 карточек — те самые, что владелец поднял 24-го числа вручную.
--
-- Теперь цены двигает только владелец кнопкой на странице продвижения.
-- Настройки цели и предела остаются: они ограничивают ручной подъём.
UPDATE price_robot_settings
   SET is_active = false
 WHERE is_active = true;