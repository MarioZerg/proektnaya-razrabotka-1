-- Откат проверочного списания.
--
-- При проверке кнопки «Списать метраж» с рулона 2-004678 ушло 2 метра тесьмы.
-- Материал никуда не девался — возвращаем остаток и помечаем запись в журнале
-- как отменённую, чтобы движение не выглядело настоящим расходом.
UPDATE rolls SET remaining_quantity = remaining_quantity + 2 WHERE id = 4678;

UPDATE material_movements
SET movement_type = 'Корректировка',
    reference = 'рулон 2-004678 · отмена проверочного списания · система'
WHERE reference = 'рулон 2-004678 · Проверка механизма · Андрей';

UPDATE audit_log
SET description = 'Проверка механизма списания, отменено (материал возвращён)'
WHERE action = 'roll_write_off'
  AND description = 'Списано 2.0 с рулона 2-004678: Проверка механизма';
