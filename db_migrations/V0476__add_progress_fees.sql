-- Промежуточные статьи удержаний в накопителе постраничного чтения.
--
-- Операции читаются порциями за несколько вызовов, поэтому суммы по статьям
-- тоже нужно копить между вызовами — иначе в базу попадёт только последняя
-- порция страниц, как уже случалось со счётчиком штук.
ALTER TABLE marketplace_sync_progress
    ADD COLUMN IF NOT EXISTS fees JSONB NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN marketplace_sync_progress.fees IS
    'Накопленные удержания по месяцам и статьям за прочитанные страницы';
