-- Обезвреживаем тестовые записи после починки начисления оклада при автозакрытии.
--
-- Смены 243 и 244 заводились вручную для проверки обоих путей закрытия (ночной обход
-- и кнопка сотрудника). Реальной работы за ними нет, но удалять данные напрямую
-- нельзя — поэтому обнуляем сумму, чтобы тестовый оклад не попал в зарплату, и
-- подписываем записи, чтобы их было видно в отчётах как служебные.
UPDATE salary_accruals
SET amount = 0,
    description = 'Служебная запись проверки начислений (не к выплате)'
WHERE shift_session_id IN (243, 244);

-- Сами смены помечаем закрытыми в момент открытия: нулевая длительность,
-- в отчёты по отработанному времени они не попадут.
UPDATE shift_sessions
SET closed_at = opened_at
WHERE id IN (243, 244);