-- Момент, когда вещь РЕАЛЬНО упакована (закрыта стикеровка на терминале).
--
-- Зачем: акция дня считалась по sewn_at — дате, когда швея сдала вещь на стикеровку.
-- Получалось, что метры засчитывались за сам факт сдачи, а упакована вещь или лежит
-- в очереди — на счётчик не влияло. Мотивации упаковать вовремя это не создавало.
-- Теперь считаем по факту упаковки, поэтому нужна отдельная дата.
--
-- Отдельное поле, а не sewn_at: sewn_at — это выработка ШВЕИ (по нему считается её
-- метраж и месячная премия), и подменять его моментом упаковки нельзя.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS packed_at TIMESTAMP NULL;

-- Заполняем историю. Точное время упаковки сохранилось в начислении упаковщице за
-- стикеровку (оно создаётся ровно в момент закрытия) — берём его.
UPDATE orders o
SET packed_at = a.created_at
FROM salary_accruals a
WHERE a.order_id = o.id
  AND a.type = 'packer_stickering'
  AND o.packed_at IS NULL;

-- Остальным готовым вещам, где начисления не было (стикеровал не упаковщик, нулевой
-- тариф, ручное закрытие), проставляем момент появления складской записи: она заводится
-- в ту же секунду, что и закрытие стикеровки.
UPDATE orders o
SET packed_at = g.shipping_labeled_at
FROM goods_warehouse g
WHERE g.order_id = o.id
  AND g.shipping_labeled_at IS NOT NULL
  AND o.packed_at IS NULL
  AND o.sewing_status IN ('Готовые', 'Со склада');

-- Акция дня спрашивает «сколько упаковано за такой-то день» — индекс по дате.
CREATE INDEX IF NOT EXISTS idx_orders_packed_at ON orders(packed_at);
