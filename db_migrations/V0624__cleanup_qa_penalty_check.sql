-- УБОРКА ПОСЛЕ ПРОВЕРКИ ОТМЕНЫ ШТРАФА.
--
-- Временный штраф из V0623 нужен был, чтобы проверить новую кнопку «Отменить
-- штраф», не трогая реальные удержания сотрудников. Проверка прошла, возврат уже
-- удалён обычным способом, а сам штраф числится выплаченным — удалить его
-- напрямую нельзя, поэтому обнуляем сумму и снимаем отметку о выплате.
-- На расчёты он теперь не влияет никак.
UPDATE salary_accruals
SET amount = 0,
    paid_at = NULL,
    payout_id = NULL,
    description = 'QA: служебная запись проверки, в расчётах не участвует'
WHERE description LIKE '%QA-ПРОВЕРКА отмены штрафа%';
