-- Снимаем тестовую карточку возврата GW-729614 (заказ 94433) со склада.
--
-- Запись создал проверочный запрос к приёмке возвратов во время отладки скана
-- стикеров WB: вещь никто не привозил, физически её на складе нет. Заявок и
-- истории возвратов по ней не завелось.
--
-- Удалять строки нельзя, поэтому переводим карточку в 'lost' — этот статус и
-- значит «числилась, но по факту её нет». Из рабочих списков склада и из
-- «Разобрать возвраты» она уходит, и кладовщик не ищет несуществующий товар.
UPDATE goods_warehouse
SET status = 'lost',
    shelf_id = NULL
WHERE id = 8288
  AND storage_barcode = 'GW-729614'
  AND status = 'mp_return';
