-- Отмена штрафа, начисленного при технической проверке конвейера.
--
-- При проверке правила отсечки OZON заказ 87247 был взят в работу от имени швеи и
-- возвращён обратно в раскроенные. Система расценила это как отмену заказа сотрудником
-- и списала 300 руб. Швея к этому непричастна — обнуляем сумму и помечаем строку,
-- чтобы в расчётном листе было видно: удержания нет.
UPDATE salary_accruals
SET amount = 0,
    description = 'Штраф отменён — техническая проверка системы, к сотруднику не относится'
WHERE id = 8010
  AND user_id = 24
  AND type = 'penalty'
  AND order_id = 87247;
