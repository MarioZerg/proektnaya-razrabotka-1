-- Отказываемся от холда: возвраты уже вычтены самой площадкой.
--
-- Почему холд оказался лишним. Площадка вычитает возвраты ПРЯМО В ОТЧЁТЕ:
-- в неделе 10–16.08 заказов на 5 317 223 ₽, возвратов −456 976 ₽, и к переводу
-- выходит 1 490 035 ₽ — уже за вычетом. Наш холд снимал те же возвраты второй
-- раз, своим расчётом по штукам. Менеджер терял деньги дважды за один возврат.
--
-- Как работает теперь. Возврат по старому заказу попадает в БЛИЖАЙШИЙ отчёт и
-- уменьшает сумму к переводу — процент пересчитывается сам, без нашего участия.
-- Начисление подтверждается сразу при появлении отчёта.
--
-- Ранее выпущенные начисления переводим в подтверждённые и возвращаем удержанное:
-- эти суммы были сняты ошибочно.
UPDATE manager_accruals
SET status = 'confirmed',
    confirmed_at = coalesce(confirmed_at, now()),
    returned_units = 0,
    returned_amount = 0,
    cancel_reason = NULL,
    cancelled_at = NULL
WHERE status IN ('hold', 'cancelled');

-- Ноль означает «подтверждать сразу». Поле оставляем: если правила изменятся,
-- достаточно вернуть срок, а не переписывать расчёт.
UPDATE manager_commission_settings SET hold_days = 0;

COMMENT ON COLUMN manager_commission_settings.hold_days IS
    'Дней проверки начисления. 0 — подтверждать сразу: возвраты площадка '
    'вычитает в своих отчётах, повторно снимать их не нужно';
