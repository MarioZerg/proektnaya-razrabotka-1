-- Возвращаем в работу FBS два заказа, ошибочно уехавшие в короб FBO.
--
-- ЧТО ПРОИЗОШЛО. Сканирование ярлыка товара в короб FBO искало на складе ЛЮБУЮ
-- свободную вещь с таким кодом. Вещи одного артикула физически неотличимы, и
-- под это условие попадала вещь, сшитая под конкретное отправление FBS:
-- покупатель её ждёт, ярлык отправления наклеен, заказ жив — а она уезжала в
-- короб FBO на склад площадки.
--
-- Так ушли два заказа (оба «Новый», ozon_status awaiting_deliver, никем не
-- отменённые), сшитые 21.09 и упакованные в короб №8 поставки 1307:
--   * 0112212799-0220-1 — Молния 600x245, вещь GW-732895
--   * 47189664-0235-1   — Лен 400x265,    вещь GW-732906
--
-- Причина закрыта в коде (backend/marketplace_supplies/supplies_actions.py):
-- в короб FBO теперь не отдаётся вещь, за которой стоит ЖИВОЙ заказ FBS.
--
-- ЧТО ДЕЛАЕМ ЗДЕСЬ. Вещи физически лежат в заклеенном коробе №8, который уже
-- заведён грузоместом на OZON, — достать их оттуда сегодня нельзя. Поэтому
-- отправляем сами ЗАКАЗЫ шиться заново: завтра до обеда они уедут своей
-- поставкой FBS.
--
-- Состав короба НЕ трогаем намеренно: короб закрыт, на OZON по нему заведено
-- грузоместо со своей этикеткой. Вынимать позицию из него — значит разойтись с
-- тем, что площадка ждёт по документам, и получить недостачу уже на приёмке
-- FBO. Вещи остаются в поставке как обезличенный товар (для FBO он именно
-- такой), а покупателям FBS уедут новые экземпляры.
--
-- Связь «заказ ↔ уехавшая вещь» разрываем: иначе заказ считается закрытым
-- складом, в очередь на пошив не попадёт и зависнет ровно так же.
UPDATE goods_warehouse
SET reserved_order_id = NULL,
    matched_at = NULL
WHERE id IN (11561, 11572);

UPDATE orders
SET sewing_status = 'Новый',
    -- Снимаем всех исполнителей и отметки конвейера: заказ должен встать в
    -- общую очередь как новый, иначе он останется «в работе» у швеи, которая
    -- его уже сдала, и на экраны цеха не попадёт.
    assigned_user_id = NULL,
    cutter_user_id = NULL,
    sewer_user_id = NULL,
    packer_user_id = NULL,
    cut_at = NULL,
    taken_at = NULL,
    sewn_at = NULL,
    packed_at = NULL,
    overlocked_at = NULL,
    -- Вешалка у нового заказа пустая. Колонка NOT NULL, поэтому ставим 0 —
    -- именно это значение стоит у заказов, ещё не дошедших до раскроя.
    hanger_number = 0,
    -- Заказ больше не закрыт складом: вещь, которая его закрывала, уехала в FBO.
    fulfilled_from_stock_id = NULL
WHERE id IN (100419, 100433);
