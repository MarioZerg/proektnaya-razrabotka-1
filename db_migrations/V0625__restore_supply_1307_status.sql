-- ВОЗВРАТ СТАТУСА ПОСТАВКИ 1307 ПОСЛЕ ПРОВЕРКИ.
--
-- Проверяли починку сканирования FBO: клали вещь в короб и убирали обратно.
-- Первый скан переводит поставку из «Открытая» в «На сборке» — это правильное
-- поведение, но по факту поставку никто не собирал. Возвращаем как было, чтобы
-- кладовщик увидел её в том же состоянии.
UPDATE marketplace_supplies
SET status = 'Открытая'
WHERE id = 1307
  AND status = 'На сборке'
  AND NOT EXISTS (
    SELECT 1 FROM marketplace_supply_items WHERE supply_id = 1307
  );
