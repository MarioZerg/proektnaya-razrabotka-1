-- Пометка тестовых записей, созданных при проверке работы ЭТрН.
--
-- Накладная по поставке 1168 и поставка 1273 заводились для проверки блокировки
-- отгрузки. Удалить их штатными средствами нельзя (поставка не в статусе
-- «Открытая»), поэтому помечаем явно, чтобы они не выглядели рабочими.
UPDATE etrn_documents
SET status = 'Аннулирована',
    comment = 'Тестовая запись при настройке ЭТрН — не использовать'
WHERE supply_id = 1168;

UPDATE marketplace_supplies
SET comment = 'Тестовая поставка при настройке ЭТрН — не использовать'
WHERE id = 1273;