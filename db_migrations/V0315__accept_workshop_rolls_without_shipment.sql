-- Рулоны, лежащие в цехе, но без отметки о приёмке.
--
-- Отметка ставится, когда смена подтверждает привезённую заявку. Но эти рулоны
-- заявкой никогда не везли — их заводили сразу в цех, поэтому подтверждать было
-- нечего и отметка не появлялась никогда. Из-за этого закройщик видел все свои
-- рулоны серыми и не мог закрыть ни один.
--
-- Проставляем приёмку задним числом только тем рулонам, которые физически в цехе
-- и при этом не связаны ни с одной заявкой. Рулоны, реально едущие по заявке,
-- не трогаем — они должны быть подтверждены сменой при получении.
UPDATE rolls r
SET accepted_at = COALESCE(r.created_at, now())
WHERE r.status = 'in_workshop'
  AND r.accepted_at IS NULL
  AND NOT EXISTS (
    SELECT 1 FROM shipment_items si WHERE si.roll_id = r.id
  );
