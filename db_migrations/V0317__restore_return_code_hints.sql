-- Возвращаем подсказки и признак ежедневного обновления кодам ПВЗ.
--
-- Строки кодов были восстановлены пустыми, поэтому у OZON пропала пометка «код
-- обновляется раз в сутки» — без неё система не предупредит, что вчерашний штрихкод
-- на пункте выдачи не примут. Заодно возвращаем подсказки, где брать код в кабинете.
UPDATE t_p86119184_proektnaya_razrabotk.return_pickup_codes
SET hint = 'Личный кабинет Ozon Seller → раздел «Возвраты» → блок «Штрихкод для получения». '
           'Код обновляется раз в сутки: перед поездкой на ПВЗ скопируйте свежий.',
    daily_refresh = true
WHERE marketplace_code = 'ozon';

