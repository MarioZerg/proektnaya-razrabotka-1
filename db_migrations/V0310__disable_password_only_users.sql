-- Отключение учётных записей, заведённых под вход по логину и паролю.
--
-- Вход по паролю убран — в систему заходят только через MAX. У этих троих привязки
-- к MAX нет, значит войти они больше не смогут в принципе. Ни одного заказа и ни одной
-- смены за ними не числится, поэтому рабочие данные не пострадают.
--
-- Записи НЕ удаляем, а гасим: человек пропадает из рабочих списков и терминала, но
-- если кто-то из них выйдет на смену — достаточно включить обратно и привязать MAX,
-- вместо того чтобы заводить сотрудника заново.
--
-- 22 — Шаркунова Надежда Владимировна, 27 — Коротков Кирилл Николаевич,
-- 28 — Привезенцева Елена Александровна.
UPDATE users
SET is_active = false,
    updated_at = now()
WHERE id IN (22, 27, 28);

-- Снимаем утверждение должностей: пока учётка отключена, человек не должен числиться
-- действующей швеёй/кладовщиком в подборе исполнителей и отчётах по цеху.
UPDATE user_roles
SET is_approved = false
WHERE user_id IN (22, 27, 28);
