-- Сохраняем сумму вывода денег с баланса площадки.
--
-- Синхронизация уже вычисляет её из отчёта (движение payments), но никуда
-- не записывает. А это единственный доступный признак того, что деньги ушли
-- с баланса площадки в банк получателя: статус перевода API OZON не отдаёт.
ALTER TABLE marketplace_payouts
    ADD COLUMN IF NOT EXISTS withdrawn_amount NUMERIC(14, 2);

COMMENT ON COLUMN marketplace_payouts.withdrawn_amount IS
    'Выведено с баланса площадки за период. Больше нуля — деньги ушли '
    'на расчётный счёт; пусто или ноль — ещё лежат на балансе OZON';
