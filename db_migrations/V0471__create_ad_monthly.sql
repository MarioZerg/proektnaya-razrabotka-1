-- История рекламных расходов по месяцам.
--
-- Зачем. Сейчас в системе живёт ОДНА цифра ДРР — за последние 30 дней, и она
-- перезаписывается при каждой синхронизации. Сравнить июнь с июлем невозможно:
-- прошлый месяц просто затирается.
--
-- А ключевой вопрос по ассортименту звучит именно так: «выручка по размеру
-- упала — это спрос ушёл или мы просто перестали его рекламировать?». Ответ
-- виден только в паре «выручка + ДРР» за несколько месяцев подряд.
--
-- Поэтому храним расход и оборот по каждому месяцу отдельно. Цифры берутся из
-- финансовых операций площадки, то есть месяц уже закрыт и переписываться не
-- будет — можно спокойно накапливать историю.
CREATE TABLE IF NOT EXISTS marketplace_ad_monthly (
    id SERIAL PRIMARY KEY,
    marketplace_code VARCHAR(40) NOT NULL,
    -- Первое число месяца: ключ периода.
    month DATE NOT NULL,
    -- Потрачено на рекламу за месяц.
    ad_spend NUMERIC(14, 2) NOT NULL DEFAULT 0,
    -- Валовый оборот за месяц: столько продано товара по чекам.
    revenue NUMERIC(14, 2) NOT NULL DEFAULT 0,
    -- ДРР = расход / оборот. Считаем при записи, чтобы не пересчитывать в отчётах.
    ad_percent NUMERIC(6, 2),
    calculated_at TIMESTAMP NOT NULL DEFAULT now()
);

-- Один месяц — одна строка на площадку: повторный расчёт обновляет её, а не
-- плодит дубли, иначе отчёт покажет один и тот же месяц несколько раз.
CREATE UNIQUE INDEX IF NOT EXISTS idx_ad_monthly_uniq
    ON marketplace_ad_monthly (marketplace_code, month);

COMMENT ON TABLE marketplace_ad_monthly IS
    'ДРР по месяцам: без истории нельзя понять, растёт реклама или падает спрос';
