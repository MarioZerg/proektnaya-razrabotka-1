-- Убираем из «Принять осмотренные из цеха» вещи, которые никто не осматривал.
--
-- ЧТО БЫЛО. Кнопка «Вернуть в оборот» (для вещей, зависших под отменёнными
-- заказами) ставила вещи без полки статус 'inspected'. Но 'inspected' означает
-- совсем другое: «упаковщица осмотрела вещь В ЦЕХЕ и наклеила стикер хранения».
-- По этому статусу собирается вкладка «Принять осмотренные из цеха».
--
-- В итоге кладовщик видел там пять вещей, которых в цехе нет и которые никто не
-- осматривал: он шёл забирать тележку, а забирать нечего. Вещи всё это время
-- спокойно лежали на складе — просто без полки.
--
-- Отличить их легко: у настоящего осмотра всегда заполнен inspected_at (его
-- ставит терминал упаковщицы). У этих пяти он пуст — осмотра не было.
--
-- ЧТО ДЕЛАЕМ. Переводим в 'awaiting_shelf' («Ждёт полку») — ровно то, чем они и
-- являются: вещь на складе, ждёт раскладки по полкам, осмотр ей не нужен.
-- Причина устранена в коде: кнопка больше не ставит 'inspected'.
--
-- Вещи не теряются и не списываются: они остаются на складе и попадут в подбор,
-- как только кладовщик разложит их по полкам.
UPDATE goods_warehouse
   SET status = 'awaiting_shelf'
 WHERE status IN ('inspected', 'taken')
   -- Осмотра не было: настоящий осмотр всегда проставляет отметку.
   AND inspected_at IS NULL
   AND taken_at IS NULL
   -- Полки нет — вещь действительно ждёт раскладки.
   AND shelf_id IS NULL
   -- Вещь свободна: не подобрана под заказ и не собрана в отправление.
   AND reserved_order_id IS NULL
   AND shipping_labeled_at IS NULL
   AND shipped_at IS NULL;
