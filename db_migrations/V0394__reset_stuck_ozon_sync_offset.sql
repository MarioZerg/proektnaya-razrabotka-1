-- Сбрасываем застрявший указатель синхронизации OZON FBS.
--
-- Что произошло: синхронизация читает очередь «ожидает сборки» порциями и запоминает,
-- на какой позиции остановилась. Но когда цех собирает заказы, очередь на стороне OZON
-- становится КОРОЧЕ, а запомненная позиция остаётся прежней. Указатель уполз на 1240
-- при том, что в очереди всего 368 отправлений.
--
-- Из-за этого каждые 15 минут система запрашивала у OZON позицию, которой уже нет,
-- получала пустой ответ и ничего не загружала. Новые заказы стоят в НАЧАЛЕ списка —
-- до них дело не доходило вообще. Отсюда и расхождение: в кабинете 368 заказов,
-- в системе — меньше половины.
--
-- Ставим 0: ближайшая синхронизация пойдёт с начала очереди и заберёт всё пропущенное.
-- Дубли исключены — повторные заказы отсекаются по номеру отправления.
INSERT INTO system_settings (key, value)
VALUES ('ozon_sync_offset', '0')
ON CONFLICT (key) DO UPDATE SET value = '0', updated_at = now();
