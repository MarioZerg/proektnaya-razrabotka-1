-- Закрываем заявки возврата, по которым вещь давно разобрана.
--
-- ЧТО СЛУЧИЛОСЬ. Заявка возврата и вещь на складе — две разные записи. Вещи по
-- этим заявкам ещё 17 августа списали (статус «потеряна», причина «товар был
-- вручную добавлен, не определён»), а сами заявки так и остались в состоянии
-- «забрана с ПВЗ, ждёт разбора».
--
-- ЧЕМ ЭТО МЕШАЛО. Плитка на складе считает именно заявки — и показывала 8 штук
-- «возвраты с ПВЗ — разобрать». Кладовщик открывал разбор возвратов, а там
-- пусто: разбирать нечего, вещей уже нет. Работа, которой не существует, висела
-- на видном месте и отвлекала.
--
-- Причина устранена в коде: плитка теперь смотрит и на состояние вещи, а не
-- только на заявку. Здесь закрываем те заявки, что уже зависли.
--
-- Ставим исход 'utilized' — вещь списана, а не разложена по полкам: иначе отчёт
-- по возвратам покажет товар на складе, которого там нет.
UPDATE marketplace_returns r
   SET status = 'processed',
       outcome = COALESCE(r.outcome, 'utilized'),
       outcome_at = COALESCE(r.outcome_at, gw.disposed_at, now())
  FROM goods_warehouse gw
 WHERE gw.id = r.goods_warehouse_id
   AND r.status = 'picked_up'
   -- Только вещи, с которыми работа уже закончена: списаны или отгружены.
   AND gw.status IN ('lost', 'shipped');
