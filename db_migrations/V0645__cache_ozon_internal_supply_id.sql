-- Кешируем supply_id заявки на стороне OZON.
--
-- ЗАЧЕМ. Для работы с грузоместами (создать, удалить, запросить этикетку)
-- нужен ВНУТРЕННИЙ supply_id заявки OZON — он отличается от номера заказа
-- поставки (ozon_supply_order_id), который мы храним.
--
-- Раньше его каждый раз выясняли отдельным запросом к OZON. У облачной
-- функции 5 секунд на всю работу, а один запрос к площадке занимает до 5с
-- сам по себе — лишний поход укладывал операцию в таймаут: короб
-- переоткрывался, а функция обрывалась.
--
-- Значение постоянное на всю жизнь заявки, поэтому запоминаем его один раз
-- при импорте и дальше берём из базы.
ALTER TABLE marketplace_supplies
    ADD COLUMN IF NOT EXISTS ozon_internal_supply_id BIGINT;

COMMENT ON COLUMN marketplace_supplies.ozon_internal_supply_id IS
    'supply_id заявки внутри OZON (для /v1/cargoes/*). Кеш, чтобы не ходить в API за ним каждый раз.';
