-- Выводим из работы FBO-заказы кластеров Воронеж и Новосибирск, которые никто не взял.
--
-- Это остатки импорта от 29.07.2026: строки загрузили файлом, но производство по ним так
-- и не началось. Они висели в «Новых» и искажали планирование — цех видел работу, которой
-- на самом деле нет.
--
-- Физически строки НЕ удаляем: во-первых, удаление данных запрещено правилами платформы,
-- во-вторых, отмена обратима — если выяснится, что заказы нужны, статус можно вернуть.
-- Для цеха результат тот же: отменённые заказы не попадают ни в очередь работы, ни в
-- счётчики на главной.
--
-- Трогаем ТОЛЬКО безопасное подмножество, проверенное отдельными запросами:
--   * sewing_status = 'Новый' — работа не начиналась;
--   * никто не назначен: ни швея, ни закройщик, ни упаковщица;
--   * нет расхода материала, начислений зарплаты, вещей на складе, отзывов и возвратов.
-- Всё, что уже в работе (раскроено, сшито, готово), НЕ трогаем — за этим стоят
-- потраченный материал и оплаченный труд.
--
-- Кластер хранится не в заказе, а в поставке (marketplace_supplies.cluster):
--   1168 — Воронеж, 1167 — Новосибирск.
UPDATE orders
SET status = 'Отменён',
    sewing_status = 'Отменён',
    cancelled_at = COALESCE(cancelled_at, now())
WHERE order_type = 'FBO'
  AND sewing_status = 'Новый'
  AND assigned_user_id IS NULL
  AND cutter_user_id IS NULL
  AND sewer_user_id IS NULL
  AND packer_user_id IS NULL
  AND fulfilled_from_stock_id IS NULL
  AND supply_id IN (
      SELECT id FROM marketplace_supplies WHERE cluster IN ('Воронеж', 'Новосибирск')
  );
