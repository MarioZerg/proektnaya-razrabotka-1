-- Проверка счётчика зависших отправлений: временно возвращаем вещь 6204 в то самое
-- сбойное состояние, из-за которого заказы висели незамеченными (резерв есть,
-- статус остался 'in_stock' вместо 'picking'). Следующей миграцией вернём обратно.
