-- Возвраты, уже лежащие на полках, висели как «Забран, ждёт разбора».
--
-- Кладовщик принимал вещь с пункта выдачи и сразу указывал полку — то есть разбор
-- фактически завершён: решение принято, место определено, стикер наклеен. Но заявка
-- возврата оставалась в статусе picked_up, и вкладка «Забраны, ждут разбора» звала
-- разобрать то, что уже стоит на полке. Двойная работа и неверные цифры.
--
-- Закрываем такие заявки: outcome = 'stored' — вещь на складе.
--
-- Строго по фактам: правим ТОЛЬКО те возвраты, чья вещь реально лежит на полке
-- (status = 'in_stock' И назначена полка). Вещи в перепаковке, в подборе и без
-- полки не трогаем — там разбор действительно ещё не окончен.

UPDATE marketplace_returns r
SET status = 'processed',
    outcome = COALESCE(r.outcome, 'stored')
FROM goods_warehouse gw
WHERE gw.id = r.goods_warehouse_id
  AND r.status = 'picked_up'
  AND gw.status = 'in_stock'
  AND gw.shelf_id IS NOT NULL;
