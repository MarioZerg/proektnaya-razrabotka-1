-- Отмены ПОСЛЕ стикеровки переносим в «Разобрать возвраты».
--
-- ЧТО ЗА ВЕЩИ. Заказ сшили, упаковали и заклеили ярлыком маркетплейса — и уже
-- после этого маркетплейс его отменил. Вещь физически готова и лежит в коробе
-- с ярлыком; в цех она не возвращается, кладовщик встречает её при сборке FBS.
--
-- ПОЧЕМУ НЕ «Принять осмотренные из цеха». Та вкладка — про вещи, которые
-- упаковщица осмотрела В ЦЕХЕ и наклеила на них стикер хранения. Эти вещи
-- никто не осматривал и в цехе их нет: кладовщик шёл забирать тележку, а
-- забирать нечего.
--
-- ПОЧЕМУ ИМЕННО «Разобрать возвраты». Действие с ними ровно такое же, как с
-- возвратом от покупателя: положить на полку и напечатать стикер хранения.
-- Инструмент для этого во вкладке возвратов уже есть — незачем плодить новый.
--
-- Помечаем причиной 'cancelled_labeled', чтобы кладовщик видел разницу: вещь не
-- приехала от покупателя, а отменилась у нас после стикеровки. Осматривать её
-- незачем — она никуда не ездила.
--
-- Причина устранена в коде: кнопка «Вернуть в оборот» больше не ставит статус
-- «Осмотрено». Здесь разбираем вещи, попавшие туда по старому правилу.
UPDATE goods_warehouse
   SET status = 'mp_return',
       receive_reason = 'cancelled_labeled'
 WHERE status IN ('inspected', 'taken', 'awaiting_shelf')
   -- Осмотра в цехе не было: настоящий осмотр всегда ставит отметку.
   AND inspected_at IS NULL
   AND taken_at IS NULL
   -- Стикер хранения не печатали — значит через цех вещь не проходила.
   AND storage_labeled_at IS NULL
   -- Полки нет, вещь свободна и никуда не собрана.
   AND shelf_id IS NULL
   AND reserved_order_id IS NULL
   AND shipping_labeled_at IS NULL
   AND shipped_at IS NULL
   -- Только вещи из нашего цеха по отменённым заказам.
   AND EXISTS (SELECT 1 FROM orders o
                WHERE o.id = goods_warehouse.order_id
                  AND (COALESCE(o.ozon_status, '') LIKE 'cancel%'
                       OR COALESCE(o.status, '') = 'Отменён'));
