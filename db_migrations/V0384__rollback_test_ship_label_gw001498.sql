-- Откат тестовой стикеровки GW-001498.
--
-- Вещь была застикерована проверочным вызовом при диагностике, а физически ярлык на неё
-- никто не клеил. Возвращаем её в подбор, чтобы кладовщик прошёл шаг сам и не отправил
-- в поставку вещь без наклейки.
UPDATE goods_warehouse
SET shipping_labeled_at = NULL
WHERE storage_barcode = 'GW-001498';
