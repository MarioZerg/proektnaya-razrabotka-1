-- Возвращаем в работу FBS заказ 40813268-0081-2, зависший на вещи из короба FBO.
--
-- ЧТО ПРОИЗОШЛО. Вещь GW-724033 (Шифон 200x245) 21.09 уехала в короб №6
-- поставки FBO 2000065880431. Но связь «заказ — вещь» осталась: автоподбор
-- закрепил её за живым FBS-заказом 40813268-0081-2 ещё 20.09, до того как
-- появилась защита. Заказ числится «Со склада», то есть закрытым складом, —
-- в очередь на пошив он не попадает и в подборе не показывается. Кладовщик
-- пошёл бы к полке 10 и не нашёл ничего: вещь в заклеенном коробе, на котором
-- заведено грузоместо OZON.
--
-- Причина закрыта в коде: вещь из живого короба больше не отдаётся ни
-- автоподбору, ни сканеру подбора, ни печати ярлыка (backend/goods_warehouse).
--
-- ПОЧЕМУ В ПОШИВ, А НЕ ДРУГОЙ ВЕЩЬЮ. Свободного Шифона 200x245 на складе нет:
-- все четыре оставшиеся штуки либо тоже в коробах, либо закреплены за строками
-- заявки FBO. Подменить нечем — заказ надо шить.
--
-- Состав короба НЕ трогаем: он закрыт, на OZON по нему заведено грузоместо со
-- своей этикеткой. Вынимать позицию — значит разойтись с документами площадки
-- и получить недостачу уже на приёмке FBO. Для FBO товар обезличен, эта штука
-- там уедет как обычный товар заявки.

-- 1. Разрываем связь вещи с заказом: пока она есть, заказ считается закрытым
--    складом и в пошив не уйдёт.
UPDATE goods_warehouse
SET reserved_order_id = NULL,
    matched_at = NULL
WHERE id = 2444;

-- 2. Живой заказ отправляем шиться заново.
UPDATE orders
SET sewing_status = 'Новый',
    -- Исполнителей и отметки конвейера снимаем: заказ встаёт в общую очередь
    -- как новый. Здесь они и так пусты (заказ закрывали складом, а не шили),
    -- но проставляем явно — чтобы состояние было однозначным.
    assigned_user_id = NULL,
    cutter_user_id = NULL,
    sewer_user_id = NULL,
    packer_user_id = NULL,
    cut_at = NULL,
    taken_at = NULL,
    sewn_at = NULL,
    packed_at = NULL,
    overlocked_at = NULL,
    hanger_number = 0,
    fulfilled_from_stock_id = NULL
WHERE id = 100583;

-- 3. ВТОРАЯ ВИСЯЧАЯ ССЫЛКА НА ТУ ЖЕ ВЕЩЬ.
--
-- Заказ 68845564-0270-1 отменён покупателем на площадке (ozon_status
-- 'cancelled'), но у него остался fulfilled_from_stock_id на вещь 2444 —
-- с 05.09, когда её стикеровали под него. Шить его не нужно: покупатель
-- отказался. Просто убираем мёртвую ссылку, чтобы вещь не числилась
-- закрывающей сразу два заказа.
UPDATE orders
SET fulfilled_from_stock_id = NULL
WHERE id = 93494;
