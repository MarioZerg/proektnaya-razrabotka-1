--
-- Возврат 44470904-0672-1 (стикер GW-722778) прогоняли по всему пути: кладовщик передал
-- его упаковщице, упаковщица нажала «Переупаковано». Физически этой вещи в цехе нет —
-- иначе кладовщик пошёл бы забирать с производства то, чего не существует.
-- Данные не удаляем: история операций должна остаться целой.
UPDATE goods_warehouse
SET status = 'lost',
    lost_at = now(),
    lost_reason = 'Техническая проверка осмотра возвратов, вещь в цех не поступала'
WHERE storage_barcode = 'GW-722778'
  AND status IN ('checking', 'repacking', 'inspected', 'taken');
