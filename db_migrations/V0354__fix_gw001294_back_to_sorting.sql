-- GW-001294 числилась на полке, хотя её туда не клали.
--
-- Вещь пришла возвратом по отправлению 24093106-0247-5. В том же приходе была
-- вторая, очень похожая вещь — 24093106-0247-1 (Молния 200x270), и её кладовщик
-- действительно разобрал. GW-001294 же попала на «ФБО полку» пачкой, вместе с
-- соседями по одной операции укладки, а физически осталась неразобранной.
--
-- Отдельно мешало то, что у неё пустые ткань и размер: карточка возврата
-- привязалась к ОТМЕНЁННОМУ заказу 24093106-0247-5 (source='api'), где эти поля
-- не заполнены. В списке склада такая вещь выглядит безымянной строкой, и найти
-- её глазами почти невозможно — потому и «на складе не числится».
--
-- Возвращаем её в разбор: кладовщик примет решение и уложит заново, уже со
-- стикером хранения.

UPDATE goods_warehouse
SET status = 'mp_return',
    shelf_id = NULL
WHERE storage_barcode = 'GW-001294';

UPDATE marketplace_returns
SET status = 'picked_up',
    outcome = NULL
WHERE goods_warehouse_id = (
    SELECT id FROM goods_warehouse WHERE storage_barcode = 'GW-001294'
);

-- Заодно даём вещи нормальное имя: ткань и размер берём из названия товара
-- возврата, чтобы на разборе её можно было опознать.
UPDATE orders
SET material = 'Молния',
    width = 200,
    height = 270
WHERE id = 79842
  AND material IS NULL;
