-- Бонусная программа для швей: премия за выработку по итогам месяца.
--
-- Условие: 5000 пог.м., сданных на стикеровку за календарный месяц, дают +10 000 ₽
-- на баланс. Первый расчётный период — сентябрь 2026, начисление в октябре.
--
-- Таблица нужна ровно для одного: премия за месяц должна начислиться РОВНО ОДИН РАЗ.
-- Расчёт запускается при входе в систему, а входов в день десятки — без этой отметки
-- каждый открывший страницу начислял бы всем швеям ещё по десять тысяч.
CREATE TABLE sewer_monthly_bonus (
    id SERIAL PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    -- Первое число месяца, ЗА который начислена премия (2026-09-01 = сентябрь).
    period_month DATE NOT NULL,
    -- Сколько метров человек сдал за месяц: сохраняем на момент расчёта, чтобы потом
    -- можно было объяснить сотруднику, откуда взялась (или не взялась) премия.
    meters NUMERIC(10, 2) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    -- Ссылка на само начисление в зарплате — по ней видно транзакцию «Бонус».
    accrual_id INTEGER NULL REFERENCES salary_accruals(id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    -- Защита от повторного начисления той же премии тому же человеку.
    UNIQUE (user_id, period_month)
);
