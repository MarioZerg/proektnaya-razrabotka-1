-- Уборка тестовых записей-остатков (Привезенцева Е.А., штраф №8856).
--
-- При проверке частичного погашения долга остались две технические записи с
-- нулевой суммой. На деньги они не влияют (0 ₽), но висят в списке
-- невыплаченных и мешают админу читать историю.
--
-- Закрываем их и подписываем, чтобы было понятно происхождение. Сам штраф
-- 8856 не трогаем: он вернулся в исходные -3280 ₽ и ждёт настоящей выплаты.
UPDATE salary_accruals
SET paid_at = COALESCE(paid_at, now()),
    description = 'Техническая запись проверки (0 ₽, на расчёты не влияет)'
WHERE split_from_id = 8856 AND amount = 0;
