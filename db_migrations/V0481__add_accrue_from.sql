-- С какой даты система сама считает начисления менеджеру.
--
-- Зачем. Отчёты за прошлые недели владелец сверяет и оплачивает вручную:
-- в них есть перерасчёты площадки и досрочные выводы баланса, которые
-- автоматике разобрать не под силу. Начинаем с чистого листа — с новой недели.
--
-- Всё, что раньше этой даты, система не трогает: не начисляет и не показывает
-- в балансе, чтобы старые суммы не смешивались с ручным расчётом.
ALTER TABLE manager_commission_settings
    ADD COLUMN IF NOT EXISTS accrue_from DATE;

-- Ближайший понедельник: с него и считаем.
UPDATE manager_commission_settings
SET accrue_from = '2026-08-24'
WHERE accrue_from IS NULL;

COMMENT ON COLUMN manager_commission_settings.accrue_from IS
    'С какой даты система считает начисления сама; более ранние — вручную';
