-- Фиксируем фактический остаток на рулоне в момент закрытия.
--
-- Раньше закройщик указывал только недостачу, а поле remaining_quantity тут же
-- обнулялось. Из-за этого нельзя было проверить, откуда взялась цифра: сколько
-- метров реально оставалось на рулоне, когда сотрудник назвал недостачу.
-- Администратор видел «недостача 90 м» без единой возможности это перепроверить.
--
-- Теперь сохраняем остаток ДО обнуления — он и есть та самая «фактически было
-- в рулоне на момент указания недостачи».
ALTER TABLE rolls ADD COLUMN IF NOT EXISTS remaining_at_close NUMERIC;

COMMENT ON COLUMN rolls.remaining_at_close IS
    'Сколько метров фактически оставалось на рулоне в момент закрытия закройщиком';
