-- Фото профиля из MAX храним отдельно от avatar_url.
--
-- avatar_url — это фото, которое загрузил администратор через карточку сотрудника.
-- Оно главнее: если админ поставил фото вручную, мессенджер не должен его перебивать.
-- А max_avatar_url обновляется при каждом входе через бота — человек сменил аватар
-- в MAX, он поменяется и здесь.
--
-- Два поля вместо одного нужны, чтобы эти два источника не затирали друг друга:
-- иначе после ручной загрузки следующий вход через бота вернул бы старое фото.
ALTER TABLE users ADD COLUMN max_avatar_url TEXT NULL;
