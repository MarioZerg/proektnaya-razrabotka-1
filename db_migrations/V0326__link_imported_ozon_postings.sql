-- Восстанавливаем связь импортных FBS-заказов с отправлениями маркетплейса.
--
-- Заказы, перенесённые из старой системы (source='import'), приехали без номера
-- отправления: поле ozon_posting_number пустое. Из-за этого система не могла спросить
-- у OZON их статус — в поставке они висели без пометки площадки, и кладовщик не видел,
-- готов товар к отгрузке или уже отменён.
--
-- У OZON номер отправления совпадает с номером заказа (формат 12345678-0123-1).
-- Проставляем его там, где формат подходит: тогда синхронизация статусов подхватит
-- эти заказы и покажет реальное положение дел на площадке.
UPDATE orders
SET ozon_posting_number = order_number
WHERE marketplace = 'OZON'
  AND order_type = 'FBS'
  AND ozon_posting_number IS NULL
  AND order_number ~ '^\d+-\d+-\d+$';
