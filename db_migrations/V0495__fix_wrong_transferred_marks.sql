-- Сбрасываем ошибочные отметки о поступлении.
--
-- Первая версия считала поступлением любой вывод больше нуля. По неделе
-- 10–16.08 вывод составил 24 893 ₽ при сумме к переводу 1 490 035 ₽ — это
-- техническое движение по балансу, а не выплата, и неделя ошибочно получила
-- отметку «деньги пришли».
--
-- Теперь поступлением считается вывод не меньше половины суммы к переводу.
-- Отметки пересчитаются при ближайшей синхронизации.
UPDATE marketplace_payouts
SET transferred_at = NULL
WHERE marketplace_code = 'ozon'
  AND coalesce(withdrawn_amount, 0) < coalesce(transferred_amount, 0) * 0.5;
