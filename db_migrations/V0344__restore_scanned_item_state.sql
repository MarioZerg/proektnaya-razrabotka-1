-- Возвращаем вещи в состояние «собрана и ждёт поставку» после проверки сканирования.
--
-- Вещь 000651067 (отправление 0140003248-0530-1) сканировали в поставку, чтобы убедиться,
-- что ярлык теперь принимается. Убирая её обратно, система сбросила отметку о наклеенном
-- ярлыке и вернула вещь на полку — но физически ярлык на пакете наклеен, вещь собрана и
-- лежит в зоне отгрузки. Возвращаем ей реальное состояние, иначе кладовщик пойдёт
-- собирать заново то, что уже собрано.
UPDATE goods_warehouse
SET status = 'awaiting_supply',
    shipping_labeled_at = COALESCE(shipping_labeled_at, now())
WHERE storage_barcode = '000651067'
  AND status = 'in_stock';
