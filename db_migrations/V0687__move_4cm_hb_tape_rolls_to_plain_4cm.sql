-- ОСТАТКИ ТЕСЬМЫ «4 СМ ХБ» ПЕРЕЕЗЖАЮТ НА ОБЫЧНУЮ «ТЕСЬМА 4 СМ».
--
-- ЧТО БЫЛО НЕ ТАК. В цехе одна узкая лента, а в справочнике их оказалось две:
-- «Тесьма 4 см» (id 7) и «Тесьма 4 см ХБ» (id 32). В составе карточек товара
-- стоит первая, а физические рулоны кладовщик заводил на вторую. Из-за этого
-- швея не могла сдать вещь на стикеровку: карточка требовала материал id 7,
-- а список рулонов фильтруется по этому же id — и оказывался пустым, хотя
-- 4900 м ленты лежат на складе.
--
-- ПОЧЕМУ V0686 НЕ ПОМОГЛА. Та миграция искала пару «ХБ / обычная» по маске
-- названия и при неудаче молча выходила (RETURN). Пару она не нашла, отработала
-- впустую, и данные остались разъехавшимися: карточки на id 7, рулоны на id 32.
-- Здесь никаких догадок по названию — id проверены запросами и заданы прямо.
--
-- ЧТО ИМЕННО ПЕРЕНОСИМ. Только РУЛОНЫ: это живой склад, из-за него стоит работа.
-- История движений (3018 записей material_movements за июнь–август) остаётся на
-- карточке ХБ. Так решено осознанно: переписать историю значит задним числом
-- сказать, что ленту весь сезон списывали с другого материала, — отчёты за
-- закрытые месяцы изменились бы. Карточка ХБ остаётся в архиве как «архивная
-- папка» этой истории; активной работы на ней больше нет.
--
-- УДАЛИТЬ СТРОКУ ХБ НЕЛЬЗЯ и не нужно: за ней остаются движения, а внешний ключ
-- material_movements.material_id их удалить не даст. Статус 'archive' убирает её
-- из рабочих списков — этого достаточно.

-- 1. РУЛОНЫ. Переносим только те, что реально существуют на складе или в цехе.
--    Закрытые (completed) не трогаем: по ним лента давно израсходована, и их
--    материал — часть истории, ровно как и движения.
UPDATE rolls
SET material_id = 7
WHERE material_id = 32
  AND status IN ('in_storage', 'in_workshop')
  AND removed_at IS NULL;

-- 2. СЕБЕСТОИМОСТЬ В СПРАВОЧНИКЕ.
--
--    Поле materials.cost код уже не читает: себестоимость берётся из прайса
--    поставщика (supplier_prices) и из цены каждого рулона (rolls.cost_per_unit).
--    Но пустой 0 ₽ в карточке выглядит как незаполненные данные, поэтому
--    переносим значение с ХБ — чтобы в справочнике не осталось «дырки».
--
--    На расчёты это не влияет: у «Тесьма 4 см» есть прайс 2,90 ₽, и себестоимость
--    считается по нему.
UPDATE materials
SET cost = 2.45
WHERE id = 7 AND cost = 0;
