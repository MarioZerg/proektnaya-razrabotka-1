-- Восстанавливаем связь перенесённых заказов WB со сборочными заданиями.
--
-- При переносе из старой системы номер заказа сохранился (это и есть id сборочного
-- задания WB), а поле wb_order_id осталось пустым. Из-за этого синхронизация не
-- узнавала уже загруженный заказ, пыталась создать его заново и падала на проверке
-- уникальности номера — загрузка обрывалась целиком, и кнопка «Загрузить заказы»
-- не работала вообще.
UPDATE orders
SET wb_order_id = order_number::bigint
WHERE marketplace = 'WB'
  AND wb_order_id IS NULL
  AND order_number ~ '^[0-9]+$'
  AND length(order_number) <= 18
  -- Защита от конфликта: если такое сборочное задание уже есть у другого заказа,
  -- связь не проставляем — иначе нарушим уникальность.
  AND NOT EXISTS (
    SELECT 1 FROM orders o2
    WHERE o2.wb_order_id = orders.order_number::bigint
  );
