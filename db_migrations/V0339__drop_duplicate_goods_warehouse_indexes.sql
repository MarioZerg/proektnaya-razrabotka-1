-- Убираем дублирующие индексы на складе товара.
--
-- На колонке status стояло ТРИ одинаковых индекса (idx_gw_status,
-- idx_goods_warehouse_status и составной по status+received_at). Каждый из них
-- база обязана обновлять при любом изменении вещи — а статус меняется постоянно:
-- подбор, стикеровка, поставка, отгрузка. Пользы от копий нет, поиск одинаково
-- быстро работает и по одному индексу.
--
-- Оставляем составной (status, received_at): он закрывает и поиск по статусу,
-- и сортировку по дате поступления, которую использует список склада.
DROP INDEX IF EXISTS idx_gw_status;
DROP INDEX IF EXISTS idx_goods_warehouse_status;

-- Такой же дубль на штрихкоде хранения: уникальный индекс уже обеспечивает поиск,
-- обычный поверх него — лишняя работа при каждом приёме вещи.
DROP INDEX IF EXISTS idx_goods_warehouse_storage_barcode;
