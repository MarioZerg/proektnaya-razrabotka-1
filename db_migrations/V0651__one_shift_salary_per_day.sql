-- ОДИН ОКЛАД ЗА СМЕНУ НА ЧЕЛОВЕКА В ДЕНЬ — ЗАЩИТА НА УРОВНЕ БАЗЫ.
--
-- ПРОБЛЕМА. Оклад кладовщика пишется типом 'storekeeper_shift', а старшего
-- кладовщика — 'senior_storekeeper_shift'. Существующие уникальные индексы
-- включают type, поэтому две записи РАЗНЫХ типов за один день проходили
-- свободно: человек получал 2400 рублей вместо 1200 за одну смену.
--
-- РЕШЕНИЕ. Индекс без учёта type: оба вида оклада за смену конкурируют за
-- одну строку (user_id, accrued_for), второй вставиться не сможет.
--
-- Учитываем только записи С СУММОЙ. Нулевые не мешают: это снятые дубли и
-- служебные пометки, они не деньги и уникальности требовать не должны.
-- Уже выплаченный дубль от 10.08 под индекс не попадает по той же причине —
-- его сумму мы намеренно не переписывали.
CREATE UNIQUE INDEX IF NOT EXISTS idx_salary_accruals_one_shift_per_day
    ON salary_accruals (user_id, accrued_for)
    WHERE type IN ('storekeeper_shift', 'senior_storekeeper_shift')
      AND accrued_for IS NOT NULL
      AND amount > 0
      AND paid_at IS NULL;

COMMENT ON INDEX idx_salary_accruals_one_shift_per_day IS
    'Один оклад за смену на человека в день, независимо от роли (кладовщик/старший кладовщик).';
