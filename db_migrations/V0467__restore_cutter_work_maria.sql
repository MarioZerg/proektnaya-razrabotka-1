-- Восстановление раскроя Марии Ануфриевой.
--
-- Что произошло. При проверке новой логики добора заказов по одному я вернул в
-- очередь 13 заказов, взятых во время проверки. Мария к тому моменту уже начала
-- с ними работать: 6 из них она раскроила, но перевела в «Раскроено» вручную из
-- карточки заказа, а не кнопкой «Раскроил» на терминале.
--
-- Ручной перевод статуса НЕ проставляет закройщика и время раскроя и НЕ начисляет
-- зарплату — этим занимается только кнопка на терминале. В итоге работа сделана,
-- а в системе её как будто нет: ни выработки, ни оплаты.
--
-- Здесь дописываем то, что не проставилось: закройщика, время раскроя и начисление
-- по расценке цеха (15 ₽ за пог.м., как в уже начисленных заказах той же смены).
--
-- shift_session_id намеренно оставляем пустым: на нём стоит уникальность по типу
-- начисления (одна смена — одно начисление данного типа), а здесь шесть отдельных
-- сдельных начислений. Связь с работой держится через order_id.

-- 1. Проставляем закройщика и время раскроя.
UPDATE orders
SET cutter_user_id = 34,
    cut_at = COALESCE(cut_at, now())
WHERE id IN (88044, 88076, 88083, 88084, 88085, 88086)
  AND assigned_user_id = 34
  AND sewing_status = 'Раскроено'
  AND cutter_user_id IS NULL;

-- 2. Начисляем оплату за раскрой — только тем заказам, где её ещё нет.
-- Метраж по ширине изделия: 200 см = 2 пог.м. → 30 ₽, 400 см = 4 пог.м. → 60 ₽.
INSERT INTO salary_accruals (user_id, type, amount, order_id, description, accrued_for)
SELECT 34,
       'cutter_cut',
       ROUND((o.width / 100.0) * 15, 2),
       o.id,
       'Раскрой заказа #' || o.id || ' (' || o.material || ' ' || o.width || ' см) - '
         || ROUND(o.width / 100.0, 1) || ' пог.м.',
       CURRENT_DATE
FROM orders o
WHERE o.id IN (88044, 88076, 88083, 88084, 88085, 88086)
  AND NOT EXISTS (
      SELECT 1 FROM salary_accruals sa
      WHERE sa.order_id = o.id AND sa.type = 'cutter_cut'
  );
