-- ЦЕЛЬ РОБОТА — ПРОСТОЙ ПОДЪЁМ ЦЕН, А НЕ МАРЖА.
--
-- Маржа считается по юнит-экономике и выкупам, а там своя длинная арифметика:
-- фактическое удержание площадки, себестоимость, реклама, налоги. Пока в
-- каком-то месяце нет отчёта о реализации, маржа показывает не то, и робот
-- принимал бы решения по кривой цифре.
--
-- Владельцу нужно проще: «подними на 10% и смотри на спрос». Спрос — вещь
-- прямая, её видно по числу проданных штук, и никакой отчётности для неё
-- не нужно.
ALTER TABLE price_robot_settings
    ADD COLUMN IF NOT EXISTS target_total_percent NUMERIC(6,2) NOT NULL DEFAULT 10.0;

COMMENT ON COLUMN price_robot_settings.target_total_percent IS
    'На сколько процентов всего надо поднять цены. Дошли — робот остановился';

-- Старая цель по марже больше не используется: оставляем колонку, чтобы не
-- ломать историю, но робот на неё не смотрит.
COMMENT ON COLUMN price_robot_settings.target_margin IS
    'Не используется: цель робота теперь в процентах подъёма (target_total_percent)';

-- Предел от старта должен быть не меньше цели, иначе робот упрётся в
-- предохранитель, не дойдя до неё.
UPDATE price_robot_settings
SET max_total_percent = GREATEST(max_total_percent, target_total_percent + 5);