-- Возврат в цех 50 отправлений OZON FBS, застрявших после принудительного
-- закрытия поставки №1 (10.08).
--
-- Что произошло: поставку закрыли скопом вместе со всеми 584 заказами. 449 из них
-- реально уехали, а эти 50 уехать не могли — они не были собраны ни физически
-- (ни одной вещи на складе, ни одного стикера), ни на стороне OZON. Закрытие
-- проставило им «Готов», и они исчезли из работы цеха: система считала их
-- выполненными, а OZON пятый день ждёт сборки.
--
-- Проверка перед возвратом: по каждому из 50 отправлений опрошен OZON напрямую —
-- все 50 в статусе awaiting_packaging, живы, ни одного отменённого. Шить есть смысл.
--
-- Условие ниже намеренно повторяет признаки поломки целиком (ozon_status,
-- status, привязка к закрытой поставке и отсутствие сшитой вещи), чтобы не задеть
-- заказы, которые действительно отгружены.

UPDATE orders o
SET status = 'Новый',
    sewing_status = 'Новый',
    -- Отвязываем от закрытой поставки: иначе заказ снова считается отгруженным
    -- и не попадёт ни в раскрой, ни в новую поставку.
    supply_id = NULL,
    -- Сбрасываем исполнителей и отметки прошлого прохода — заказ идёт с начала:
    -- раскрой, пошив, стикеровка. Иначе в цехе он выглядел бы уже начатым.
    assigned_user_id = NULL,
    cutter_user_id = NULL,
    sewer_user_id = NULL,
    packer_user_id = NULL,
    taken_at = NULL,
    cut_at = NULL,
    completed_at = NULL,
    -- Номер вешалки обязателен и у новых заказов равен 0 — вешалку заказ получит
    -- заново, когда его возьмут в работу.
    hanger_number = 0
WHERE o.marketplace = 'OZON'
  AND o.order_type = 'FBS'
  AND o.ozon_status = 'awaiting_packaging'
  AND o.status = 'Готов'
  AND o.supply_id = 1
  AND o.fulfilled_from_stock_id IS NULL
  AND NOT EXISTS (
      SELECT 1 FROM goods_warehouse gw WHERE gw.reserved_order_id = o.id
  );
