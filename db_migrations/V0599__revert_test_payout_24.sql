-- Откат тестовой выплаты №24 (Коротков Кирилл, 2730 ₽ за 25.08.2026).
--
-- ЧТО ПРОИЗОШЛО. При разборе проблемы с удержаниями я вызвал выплату на
-- реальных данных, чтобы увидеть поведение системы. Выплата прошла: три
-- начисления закрылись (в том числе удержание -2720), из кассы ушли деньги.
-- Реальной выдачи сотруднику не было — возвращаем состояние.
--
-- 1) Начисления снова открыты и ждут настоящей выплаты.
UPDATE salary_accruals
SET paid_at = NULL, payout_id = NULL
WHERE payout_id = 24;

-- 2) Кассу возвращаем встречной записью, а не удалением: история операций
--    кассы не переписывается задним числом — это денежный документ. Плюс
--    2730 ₽ компенсируют ушедшее списание, итоговый остаток сходится.
INSERT INTO cash_box_transactions (amount, description, payout_id, created_by)
VALUES (2730.00, 'Отмена тестовой выплаты №24 (Коротков К.): возврат средств в кассу', NULL, NULL);

-- 3) Саму выплату помечаем отменённой суммой 0, чтобы она не считалась
--    выданной и не попадала в отчёты как реальная.
UPDATE salary_payouts
SET amount = 0
WHERE id = 24;
