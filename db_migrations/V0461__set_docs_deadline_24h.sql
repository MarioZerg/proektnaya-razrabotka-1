-- ДОКУМЕНТЫ: включаем требование для тех, кому срок не назначили.
--
-- Что было сломано: срок на загрузку паспорта ставился ТОЛЬКО при утверждении
-- должности. Но админ заводит сотрудника сразу с утверждённой должностью —
-- этот шаг не наступал, и docs_deadline оставался пустым. В итоге у двадцати
-- человек срок не был назначен вовсе: требование не действовало ни для кого,
-- хотя люди работают больше недели.
--
-- Сам механизм блокировки исправен: он срабатывает, когда срок вышел, а
-- комплекта нет. Ему просто нечего было проверять.
--
-- Даём 24 часа, а не 7 дней: люди работают давно, но предупреждения не видели
-- ни разу — не по своей вине. Сутки на то, чтобы сфотографировать документы,
-- и при этом требование наконец начинает действовать.
UPDATE users
SET docs_deadline = now() + interval '24 hours'
WHERE is_active = true
  AND role <> 'admin'
  AND docs_deadline IS NULL
  AND personal_data_verified = false;

-- Тем, кто документы уже прислал и ждёт проверки администратора, срок не
-- нужен вовсе: очередь за админом, а не за сотрудником. Блокировать человека
-- за чужую задержку нельзя — это же правило уже заложено в docs_status().
UPDATE users
SET docs_deadline = NULL
WHERE docs_submitted_at IS NOT NULL
  AND personal_data_verified = false;
