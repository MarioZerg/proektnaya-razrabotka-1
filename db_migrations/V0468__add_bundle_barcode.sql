-- Отдельный стикер для вещей СВЯЗКИ Яндекса.
--
-- Зачем. У заказа Яндекса из нескольких вещей ярлык маркетплейса ОДИН на всех:
-- на каждой наклейке один и тот же номер грузоместа и «1/1». Отсканировать им
-- четыре разные вещи невозможно — система каждый раз находит первую.
--
-- Собирать связку по складскому стикеру (GW-…) оказалось плохой идеей: он
-- означает «вещь лежит на полке хранения», и кладовщик путал два разных стикера
-- с одинаковым видом. Поэтому для связок заводим СВОЙ код — YM-…, который ни с
-- чем не спутать: увидел YM — это сборка связки в поставку.
--
-- Код живёт рядом со складским, а не вместо него: вещь может и лежать на полке
-- (GW), и ехать в связке (YM). Это два разных смысла, и путать их нельзя.
ALTER TABLE goods_warehouse
    ADD COLUMN IF NOT EXISTS bundle_barcode VARCHAR(40);

COMMENT ON COLUMN goods_warehouse.bundle_barcode IS
    'Стикер вещи из связки Яндекса (YM-…): по нему связка собирается в поставку. '
    'Нужен потому, что ярлык маркетплейса у связки один на все вещи';

-- Код уникален: два одинаковых стикера на разных вещах сделали бы сборку связки
-- невозможной — сканер находил бы не ту вещь.
CREATE UNIQUE INDEX IF NOT EXISTS idx_goods_bundle_barcode
    ON goods_warehouse (bundle_barcode)
    WHERE bundle_barcode IS NOT NULL;
