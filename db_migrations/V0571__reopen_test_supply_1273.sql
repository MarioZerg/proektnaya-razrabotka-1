-- Возврат тестовой поставки 1273 в статус «Открытая», чтобы удалить её штатно.
--
-- Она создавалась при настройке ЭТрН для проверки блокировки отгрузки и осталась
-- в статусе «На сборке» — а удалить можно только открытую поставку.
UPDATE marketplace_supplies
SET status = 'Открытая'
WHERE id = 1273 AND comment LIKE 'Тестовая поставка%';