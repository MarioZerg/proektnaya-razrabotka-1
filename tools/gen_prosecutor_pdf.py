def money(v):
    """Сумма с неразрывным пробелом между разрядами.

    Обычный пробел fpdf считает местом переноса, и «111 235,00» могло разорваться
    между строками — в документе для прокуратуры это выглядит как опечатка.
    """
    return f'{float(v):,.2f}'.replace(',', '\u00a0').replace('.', ',')


