_MP_WORDS = {
    'ozon': r'ozon|озон',
    'wildberries': r'wildberries|\bwb\b|вб|вайлдб',
    'yandex_market': r'яндекс|yandex|\bym\b|маркет',
}


def pick(question, marketplaces=None, limit=4):
    """Подбирает до limit разделов под вопрос. Без явной площадки — по всем."""
    q = (question or '').lower()
    mps = set(marketplaces or [])
    if not mps:
        mps = {mp for mp, rx in _MP_WORDS.items() if re.search(rx, q)}
    if not mps:
        mps = {'ozon', 'wildberries', 'yandex_market'}
    scored = []
    for i, (mp, title, rx, text) in enumerate(SECTIONS):
        if mp != 'all' and mp not in mps:
            continue
        hits = len(re.findall(rx, q))
        if hits:
            scored.append((-hits, i, mp, title, text))
    scored.sort()
    chosen = scored[:limit]
    if not chosen:
        return ''
    out = ['СПРАВКА ПЛОЩАДОК (из официальных баз знаний; спорное — сверь через web_search):']
    used = set()
    for _, _, mp, title, text in chosen:
        out.append(text)
        used.add(mp)
    links = []
    for mp in sorted(used):
        links.extend(DOCS.get(mp, []))
    if links:
        out.append('Официальные источники: ' + '; '.join(links))
    return '\n\n'.join(out)
