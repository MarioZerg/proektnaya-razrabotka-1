_fonts_ready = False


def _ensure_fonts():
    """Регистрирует шрифт с кириллицей.

    Шрифт вшит в код (fonts_data.py): встроенные шрифты PDF кириллицу не умеют,
    а отдельные файлы .ttf в развёртывание облачной функции не попадают.
    """
    global _fonts_ready
    if _fonts_ready:
        return
    pdfmetrics.registerFont(TTFont('OS', io.BytesIO(base64.b64decode(REGULAR_B64))))
    pdfmetrics.registerFont(TTFont('OS-B', io.BytesIO(base64.b64decode(BOLD_B64))))
    _fonts_ready = True


MONTHS = [
    'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
    'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
]


def ru_date(value) -> str:
    if not value:
        return '____________'
    return f'{value.day} {MONTHS[value.month - 1]} {value.year} г.'


def dash(value) -> str:
    """Пустое поле в договоре — это дыра, поэтому показываем явный прочерк."""
    return str(value).strip() if value and str(value).strip() else '—'


